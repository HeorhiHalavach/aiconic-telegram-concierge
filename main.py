"""Точка входа: дирижёр отвечает в Telegram.

    python main.py

Первый запуск делайте в режиме наблюдения (TG_WHITELIST пустой): процесс
залогирует id всех, кто написал, и никому не ответит. Возьмите нужный id из
лога, положите в TG_WHITELIST и перезапустите.
"""

from __future__ import annotations

import asyncio
import os
import sys
from dataclasses import dataclass
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Awaitable, Callable

from aiconic import env, guards, handover, reminders
from aiconic.app import Дирижёр, Лог
from aiconic.llm import CerebrasProvider, ОшибкаПровайдера
from aiconic.salon import Салон
from aiconic.sender import Sender

КОРЕНЬ = Path(__file__).resolve().parent


def _белый_список() -> set[int]:
    сырое = os.environ.get("TG_WHITELIST", "").strip()
    if not сырое:
        return set()
    return {int(x) for x in сырое.replace(";", ",").split(",") if x.strip()}


async def _цикл_напоминаний(салон, отправитель, лог, интервал: float = 60.0) -> None:
    """Единственное место, где система пишет ПЕРВОЙ.

    Идёт через Sender, значит подчиняется и файлу STOP, и белому списку.
    Отметка о напоминании кладётся в bookings.yaml, а не в память процесса:
    иначе перезапуск отправил бы всё заново.

    Отмечаем только фактически отправленное. Отказ (STOP, белый список) не
    гасится — напоминание уйдёт на следующем тике, а когда визит начнётся,
    оно погасится само.
    """
    while True:
        await asyncio.sleep(интервал)
        try:
            await _тик_напоминаний(салон, отправитель, лог)
        except asyncio.CancelledError:
            raise                                   # остановка процесса — не ошибка
        except Exception as e:
            # ЗАСЛОН ОТ МОЛЧАЛИВОЙ СМЕРТИ. Задача создана через create_task, её
            # исключение никто не забирает: без этого except рассылка
            # прекратилась бы навсегда, а бот продолжал бы отвечать — и в логе
            # не было бы ни строки. Реальный путь: RuntimeError из
            # tg.отправить при длинном FloodWait.
            лог.пропуск(0, f"напоминания, тик провален: {type(e).__name__}: {e}")


async def _тик_напоминаний(салон, отправитель, лог) -> None:
    """Один проход. Вынесен отдельно, чтобы его можно было прогнать в тесте."""
    сейчас = datetime.now(timezone.utc)
    созревшие = reminders.созревшие(салон.записи, сейчас)

    изменилось = False
    for индекс, вид, гасим in созревшие:
        запись = салон.записи[индекс]
        отмечаем = list(гасим)

        if вид:
            услуга = салон.услуга(str(запись.get("услуга", "")))
            мастер = салон.мастер(int(запись.get("мастер", 0) or 0))
            текст = reminders.текст(
                запись, вид,
                услуга.название if услуга else "визит",
                мастер.имя if мастер else "мастер",
            )
            решение = await отправитель.отправить_шаблон(
                int(запись.get("чат", 0) or 0), текст,
                причина=f"напоминание {вид}",
            )
            if not решение.отправлено:
                continue                            # не гасим, попробуем позже

        запись.setdefault("напомнили", [])
        запись["напомнили"] = sorted(set(запись["напомнили"]) | set(отмечаем))
        изменилось = True

    if изменилось:
        салон.сохранить_записи()


@dataclass
class Система:
    """Собранная система: всё, что нужно, чтобы отвечать и напоминать.

    Существует отдельно от main() ровно по одной причине: сборку надо
    проверять тестом. Пока она была внутри main(), тест на неё написать было
    нельзя — main() требует настоящий Telegram, — и ошибка проводки (забытый
    белый список у Sender, необработанный отказ истории) прошла бы незамеченной
    сквозь все 382 теста, потому что каждый из них собирает дирижёра сам.
    """

    дирижёр: Дирижёр
    отправитель: Sender
    обработчик: Callable[[object], Awaitable[None]]
    напоминать: bool
    передачи: handover.Передачи
    # Время старта приёма нужно добору: он берёт сообщения СТРОГО до него.
    приём_старт: datetime


def собрать_систему(
    *, канал, салон, провайдер, белый: set[int], наблюдение: bool, лог: Лог,
    корень: Path = КОРЕНЬ,
) -> Система:
    # ⚠️ ОДИН экземпляр метки на процесс. Дирижёр её ставит, окно читает, Sender
    # снимает — если создать три объекта, их списки в памяти разойдутся, и
    # запись одного затрёт запись другого. Поэтому создаётся здесь, в одном
    # месте, и передаётся всем троим.
    передачи = handover.Передачи(салон.каталог)

    отправитель = Sender(
        канал,
        салон,
        белый_список=белый,
        лимит=guards.Лимит(на_чат=6, всего=30, окно_сек=60),
        файл_выключателя=корень / "STOP",
        лог=лог,
        передачи=передачи,
    )

    старт = datetime.now(timezone.utc)   # не отвечаем на всё, что было до запуска
    приём = guards.Приём(
        белый_список=белый,
        старт=старт,
        режим_наблюдения=наблюдение,
    )

    история_кэш: dict[int, list[dict]] = {}

    def история(чат_id: int, сколько: int) -> list[dict]:
        return история_кэш.get(чат_id, [])

    # Напоминания — единственное, что уходит клиенту первым. В режиме
    # наблюдения их не бывает по определению: там вообще ничего не уходит.
    напоминать = (
        os.environ.get("REMINDERS", "on").strip().lower() not in ("off", "0", "no")
        and not наблюдение
    )

    дирижёр = Дирижёр(
        салон=салон,
        провайдер=провайдер,
        sender=отправитель,
        приём=приём,
        лог=лог,
        история=история,
        сегодня=lambda: date.today(),
        напоминания=напоминать,
        передачи=передачи,
    )

    async def обработчик(вх) -> None:
        # историю читаем из Telegram — одно чтение на пачку, не на сообщение
        try:
            история_кэш[вх.чат_id] = await канал.история(вх.чат_id, дирижёр.глубина)
        except Exception as e:
            лог.пропуск(вх.чат_id, f"история недоступна: {e}")
            история_кэш[вх.чат_id] = []
        await дирижёр.принять(вх)

    return Система(дирижёр=дирижёр, отправитель=отправитель,
                   обработчик=обработчик, напоминать=напоминать,
                   передачи=передачи, приём_старт=старт)


async def догнать(канал, система, лог, *, часов: float, старт) -> int:
    """Ответить на то, что пришло, пока процесс лежал. Возвращает сколько добрал.

    ⚠️ Зачем это вообще нужно. Отсечка «сообщение старше запуска» защищает от
    того, чтобы первый запуск ответил на весь непрочитанный backlog. Но у неё
    есть цена: клиент, написавший ночью, не получает ответа НИКОГДА — процесс
    подняли утром, и его сообщение уже «старое». Для продукта, который держится
    на отложенных ответах, это дыра, а не защита.

    Добор узкий по трём границам сразу, и каждая нужна:

    1. **Только чаты, где последнее слово за клиентом.** Значит мы точно ещё не
       отвечали. Счётчик непрочитанных для этого не годится: мы не помечаем
       сообщения прочитанными, и он остаётся большим после нашего же ответа.
    2. **Только последние `часов`** (по умолчанию 12). Через сутки отвечать
       «здравствуйте, чем помочь» — хуже, чем промолчать.
    3. **Только белый список** — его проверяет сам `Приём`, мы его не обходим.

    Обходится ровно одна проверка — отсечка по старту, — и обходится явным
    флагом `догоняем`, а не сдвигом времени старта: сдвиг заставил бы отвечать
    заново на то, что мы УЖЕ ответили до перезапуска.
    """
    from datetime import timedelta

    from aiconic.app import Входящее

    порог = старт - timedelta(hours=часов)
    добрано = 0
    try:
        диалоги = await канал.диалоги(50)
    except Exception as e:
        лог.пропуск(0, f"добор не состоялся, лента недоступна: {e}")
        return 0

    for д in диалоги:
        if д.наше_последним or д.когда is None:
            continue
        if not (порог < д.когда <= старт):
            continue
        if not (д.последнее or "").strip():
            continue          # голосовое или вложение: шаблон про текст уже был
        лог.пропуск(д.чат_id, f"добор: сообщение от {д.когда.isoformat()}")
        await система.обработчик(Входящее(
            чат_id=д.чат_id, текст=д.последнее, дата=д.когда,
            личный=True, исходящее=False, есть_вложение=False,
            автор=д.имя, догоняем=True,
        ))
        добрано += 1
    if добрано:
        print(f"добрано сообщений, пришедших пока процесс лежал: {добрано}")
    return добрано


def добор_часов() -> float:
    """0 выключает добор совсем — это и есть флаг."""
    try:
        return max(0.0, float(os.environ.get("CATCHUP_HOURS", "12")))
    except ValueError:
        return 12.0


def окно_включено() -> bool:
    return os.environ.get("INBOX", "off").strip().lower() in ("on", "1", "yes")


async def _задача_окна(система, канал, салон, лог) -> None:
    """Веб-окно администратора отдельной задачей рядом с напоминаниями.

    ⚠️ Токен обязателен: без него окно НЕ поднимается. Заслон, у которого есть
    «безопасное» значение по умолчанию, рано или поздно оказывается выключенным,
    а здесь за ним переписка клиентов, включая вопросы о здоровье.

    Печатаем готовую строку для `.env`, но НЕ пишем файл сами: секрет кладёт
    Георгий своими руками — так в этом проекте со всеми секретами.
    """
    import secrets as _secrets

    import uvicorn

    from aiconic.inbox.api import создать_приложение

    токен = os.environ.get("INBOX_TOKEN", "").strip()
    if not токен:
        print("окно НЕ поднято: нет INBOX_TOKEN. Положите в .env строку:")
        print(f"INBOX_TOKEN={_secrets.token_urlsafe(24)}")
        return

    приложение = создать_приложение(
        # Список из одного: второй мессенджер добавится сюда, а не в окно.
        каналы=[канал], салон=салон, отправитель=система.отправитель,
        передачи=система.передачи, токен=токен,
    )
    порт = int(os.environ.get("INBOX_PORT", "8000"))
    # 0.0.0.0, иначе окно не открыть с телефона — а оно ради телефона и сделано.
    конфиг = uvicorn.Config(приложение, host="0.0.0.0", port=порт, log_level="warning")
    сервер = uvicorn.Server(конфиг)
    print(f"окно администратора: http://<адрес-этой-машины>:{порт}")
    try:
        await сервер.serve()
    except Exception as e:
        # Тем же приёмом, что цикл напоминаний: окно упало — Telegram живёт.
        лог.пропуск(0, f"окно администратора упало: {type(e).__name__}: {e}")


async def main() -> int:
    env.загрузить()

    for обязательное in ("TG_API_ID", "TG_API_HASH", "TG_SESSION"):
        if not os.environ.get(обязательное):
            print(f"нет {обязательное} — заполните .env (см. .env.example)")
            if обязательное == "TG_SESSION":
                print("строку сессии выдаёт: python login.py")
            return 1

    белый = _белый_список()
    наблюдение = not белый
    if наблюдение:
        print("РЕЖИМ НАБЛЮДЕНИЯ: белый список пуст, никому не отвечаем.")
        print("Логируем id тех, кто написал. Затем впишите нужный в TG_WHITELIST.")

    салон = Салон()
    print(f"прайс: {len(салон.услуги)} услуг, мастеров: {len(салон.мастера)}, "
          f"записей: {len(салон.записи)}")

    try:
        провайдер = CerebrasProvider(seed=int(os.environ["LLM_SEED"])
                                     if os.environ.get("LLM_SEED") else None)
    except ОшибкаПровайдера as e:
        print(f"провайдер не готов: {e}")
        return 1

    # tg импортируется только здесь и внутри aiconic/tg.py
    from aiconic.tg import TelegramКанал

    канал = TelegramКанал(
        строка_сессии=os.environ["TG_SESSION"],
        api_id=int(os.environ["TG_API_ID"]),
        api_hash=os.environ["TG_API_HASH"],
        белый_список=белый,
    )

    лог = Лог(путь=КОРЕНЬ / "logs" / "dialogs.jsonl")

    система = собрать_систему(
        канал=канал, салон=салон, провайдер=провайдер,
        белый=белый, наблюдение=наблюдение, лог=лог,
    )
    print("напоминания:", "включены (за день и за 2 часа)" if система.напоминать
          else "выключены — бот про них не обещает")

    канал.подключить(система.обработчик)
    print("создайте файл STOP рядом с main.py, чтобы мгновенно замолчать")

    # ⚠️ Добор перенесён ВНУТРЬ запуска канала — см. `запустить`. Здесь его
    # звать нельзя: клиент Telegram ещё не подключён, и живой прогон
    # 2026-08-15 дал ровно это — «добор не состоялся, лента недоступна:
    # Cannot send requests while disconnected». Дефект был невидим для тестов:
    # они подменяют канал, а у подделки нет состояния «не подключён».

    рассылка = (
        asyncio.create_task(
            _цикл_напоминаний(салон, система.отправитель, лог)
        )
        if система.напоминать else None
    )
    окно = (
        asyncio.create_task(_задача_окна(система, канал, салон, лог))
        if окно_включено() else None
    )
    if not окно:
        print("окно администратора выключено (INBOX=off)")
    async def после_подключения() -> None:
        """Что сделать, когда клиент Telegram уже на связи."""
        if добор_часов() and not наблюдение:
            await догнать(
                канал, система, лог,
                часов=добор_часов(), старт=система.приём_старт,
            )

    try:
        await канал.запустить(после_подключения)
    finally:
        for задача in (рассылка, окно):
            if задача:
                задача.cancel()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(asyncio.run(main()))
    except KeyboardInterrupt:
        print("\nостановлено")
