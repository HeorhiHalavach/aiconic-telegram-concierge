"""Окно администратора: три маршрута и одна страница.

Живёт в ТОМ ЖЕ процессе, что Telegram и напоминания — проверено пробой до кода:
uvicorn работает задачей внутри уже запущенного цикла. Причина не «проще»:
ответ администратора обязан идти через `Sender`, единственный выход с заслонами
и логом. В одном процессе это вызов метода; в двух — очередь, а в очереди легко
завести второй, «удобный» путь отправки в обход заслонов.

⚠️ Про `telethon` этот модуль не знает и знать не может: за этим следит тест
границ импортов, который с 2026-08-15 проверяет и вложенные папки. Мессенджер
виден только через протокол `Канал`.

⚠️ Маршруты ASCII (`/api/chats`), хотя весь код на русском. Проба показала:
кириллица в пути URL роняет запрос — `UnicodeEncodeError` при кодировании
строки запроса в ASCII.

Заслон доступа — отказ по умолчанию: без верного токена каждый маршрут отдаёт
401 и НИ ОДНОГО байта данных. Токен берётся из `.env`; поднять окно без токена
нельзя (см. `main.py`).
"""

from __future__ import annotations

import secrets
import time
from datetime import date
from pathlib import Path

from fastapi import Depends, FastAPI, Header, HTTPException, Request
from fastapi.responses import HTMLResponse, JSONResponse

from .. import карточка as карточка_клиента

СТРАНИЦА = Path(__file__).parent / "страница.html"
# Лента кэшируется на несколько секунд: страница опрашивает её раз в 5 секунд,
# а у Telegram свои лимиты. Кэш общий на всех вкладок — админ один.
КЭШ_СЕК = 4.0


# Человеческие названия каналов. Ключ — `Канал.имя`.
ПОДПИСИ_КАНАЛОВ = {
    "telegram": "Telegram",
    "instagram": "Instagram",
    "whatsapp": "WhatsApp",
}


def строки_ленты(диалоги: list, открытые: dict) -> list[dict]:
    """Строки ленты в готовом для страницы виде, отсортированные.

    Вынесено из маршрута: это единственное место с порядком и признаками, и его
    надо было проверять без поднятого сервера. Чистая функция — на входе
    диалоги и открытые метки, на выходе список словарей.
    """
    строки = []
    for д in диалоги:
        передача = открытые.get(д.чат_id)
        строки.append({
            "чат_id": д.чат_id,
            "имя": д.имя,
            "последнее": д.последнее,
            "когда": д.когда.isoformat() if д.когда else None,
            # ⚠️ Два РАЗНЫХ признака. Непрочитанные — счётчик мессенджера, он
            # остаётся и на чатах, которые бот закрыл сам. «Нужен ответ» — наше
            # решение передать разговор человеку. Смешать их значит сделать
            # ленту бесполезной.
            "непрочитанных": д.непрочитанных,
            "нужен_ответ": передача is not None,
            "причина": (карточка_клиента.ПОДПИСИ.get(передача.код, передача.код)
                        if передача else ""),
            "канал": д.канал,
        })
    # ⚠️ Порядок двух сортировок несущий, и первая версия была НЕВЕРНОЙ. Живой
    # прогон 2026-08-15: лента шла от СТАРЫХ к новым, чат с только что
    # пришедшим сообщением оставался внизу, и Георгий увидел это как «сайт не
    # подгружает новые сообщения». Сообщения подгружались — просто тонули.
    #
    # Сначала по времени УБЫВАЮЩЕ (свежие сверху), потом стабильной сортировкой
    # поднимаем ждущих: вторая сортировка стабильна, поэтому внутри каждой
    # группы порядок по времени сохраняется.
    строки.sort(key=lambda с: с["когда"] or "", reverse=True)
    строки.sort(key=lambda с: not с["нужен_ответ"])
    return строки


def создать_приложение(
    *, каналы, салон, отправитель, передачи, токен: str,
    глубина_истории: int = 50, сегодня=None,
) -> FastAPI:
    """Собирает приложение. Всё нужное передаётся снаружи — как `Sender`.

    `токен` обязателен и не имеет значения по умолчанию: заслон, у которого есть
    безопасное значение «пусто», рано или поздно окажется выключенным.
    """
    if not токен:
        raise ValueError("окно без токена не поднимается: это заслон, а не настройка")
    if not токен.isascii():
        # ⚠️ Заголовки HTTP кодируются в ASCII. Русский токен в .env выглядел бы
        # рабочим, а окно молча не пускало бы: браузер не смог бы его отправить,
        # и админ получал бы 401 с верным, по его мнению, токеном. Ловим на
        # старте с внятным текстом, а не на первом заходе с телефона.
        raise ValueError(
            "INBOX_TOKEN обязан быть из латиницы, цифр и знаков: "
            "заголовки HTTP кодируются в ASCII, и кириллицу браузер не отправит"
        )

    # Один канал тоже приходит списком: иначе «добавить Instagram» означало бы
    # переписать все три маршрута, а Георгий назвал мультиканальность причиной
    # делать окно вообще (2026-08-15).
    каналы = list(каналы) if isinstance(каналы, (list, tuple)) else [каналы]
    по_имени = {к.имя: к for к in каналы}

    сегодня = сегодня or date.today
    приложение = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)
    кэш: dict[str, object] = {"когда": 0.0, "лента": []}

    def проверить_токен(x_inbox_token: str = Header(default="")) -> None:
        """Отказ по умолчанию.

        `secrets.compare_digest` вместо `==` намеренно: сравнение строк выходит
        на первом различии, и по времени ответа токен подбирается посимвольно.
        В домашней сети это паранойя, но заслон, который проще сделать
        правильно, чем объяснить, почему он неправильный.
        """
        если_нет = HTTPException(status_code=401, detail="нужен заголовок X-Inbox-Token")
        if not x_inbox_token:
            raise если_нет
        if not secrets.compare_digest(str(x_inbox_token), токен):
            raise если_нет

    защита = [Depends(проверить_токен)]

    # --- страница ---

    @приложение.get("/", response_class=HTMLResponse)
    async def страница() -> HTMLResponse:
        """Сама страница отдаётся без токена — данных в ней нет.

        Токен спрашивает уже она, у администратора, и держит в localStorage.
        Иначе первый заход был бы невозможен: заголовок в адресную строку не
        впишешь.
        """
        return HTMLResponse(СТРАНИЦА.read_text(encoding="utf-8"))

    # --- лента ---

    async def _лента_всех() -> list:
        """Диалоги всех каналов, с кэшем на несколько секунд.

        Кэш общий, а не по каналу: страница опрашивает ленту раз в 5 секунд, и
        каждый мессенджер имеет свои лимиты. Один поход за все — дешевле всего.
        Сбой одного канала не должен гасить остальные: Instagram лежит, а
        Telegram обязан работать.
        """
        сейчас = time.monotonic()
        if сейчас - float(кэш["когда"]) <= КЭШ_СЕК:
            return list(кэш["лента"])
        собрано: list = []
        for к in каналы:
            try:
                собрано += await к.диалоги(глубина_истории)
            except Exception as e:
                print(f"канал {к.имя} недоступен: {type(e).__name__}: {e}")
        кэш["лента"] = собрано
        кэш["когда"] = сейчас
        return list(собрано)

    @приложение.get("/api/channels", dependencies=защита)
    async def список_каналов() -> JSONResponse:
        """Первый экран: какие мессенджеры есть и где сколько ждут помощи.

        Отдельный маршрут, а не подсчёт на странице: администратор открывает
        окно, чтобы увидеть, ГДЕ он нужен, — и это должно быть видно до того,
        как он выберет мессенджер.
        """
        диалоги = await _лента_всех()
        открытые = передачи.открытые()
        сводка = []
        for к in каналы:
            свои = [д for д in диалоги if д.канал == к.имя]
            сводка.append({
                "имя": к.имя,
                "подпись": ПОДПИСИ_КАНАЛОВ.get(к.имя, к.имя),
                "чатов": len(свои),
                "ждут": sum(1 for д in свои if д.чат_id in открытые),
                "непрочитанных": sum(д.непрочитанных for д in свои),
            })
        return JSONResponse({"каналы": сводка,
                             "ждут_всего": sum(с["ждут"] for с in сводка)})

    @приложение.get("/api/chats", dependencies=защита)
    async def лента(channel: str = "") -> JSONResponse:
        диалоги = await _лента_всех()
        if channel:
            диалоги = [д for д in диалоги if д.канал == channel]
        строки = строки_ленты(диалоги, передачи.открытые())
        return JSONResponse({"чаты": строки, "ждут": sum(
            1 for с in строки if с["нужен_ответ"])})

    # --- один разговор ---

    # ⚠️ Имя параметра в пути — ASCII, и это не стиль. Starlette ищет имена
    # параметров по [a-zA-Z_], поэтому «{чат_id}» она принимает за буквальный
    # текст пути: запрос /api/chat/7 давал 404 вместо 401, то есть заслон
    # доступа выглядел сломанным, хотя был цел. Найдено тестом через настоящий
    # HTTP-путь; вызов обработчика напрямую этого не показал бы никогда.
    @приложение.get("/api/chat/{chat_id}", dependencies=защита)
    async def разговор(chat_id: int, сколько: int = 30) -> JSONResponse:
        чат_id = chat_id
        имя, имя_канала = "", каналы[0].имя
        for д in (кэш["лента"] or []):
            if д.чат_id == чат_id:
                имя, имя_канала = д.имя, д.канал
                break
        # ⚠️ История читается у ТОГО канала, откуда чат. Иначе с появлением
        # Instagram окно спрашивало бы переписку у Telegram и показывало пустоту.
        канал = по_имени.get(имя_канала) or каналы[0]
        сообщения = await канал.история(чат_id, сколько)
        к = карточка_клиента.собрать(
            чат_id=чат_id, имя=имя, салон=салон, передачи=передачи,
            сегодня=сегодня(), канал=имя_канала,
        )
        return JSONResponse({
            # Переписка отдаётся ЖИВЬЁМ и никуда не сохраняется.
            "сообщения": [
                {
                    "текст": m.get("текст", ""),
                    "наше": bool(m.get("наше")),
                    "когда": (m["дата"].isoformat()
                              if m.get("дата") is not None else None),
                }
                for m in сообщения
            ],
            "карточка": {
                "чат_id": к.чат_id,
                "имя": к.имя,
                "канал": к.канал,
                "визитов_всего": к.визитов_всего,
                "визиты": [vars(в) for в in к.визиты],
                "нужен_ответ": к.нужен_ответ,
                "причина": к.причина,
                "передана": к.передана,
            },
        })

    # --- ответ администратора ---

    @приложение.post("/api/reply", dependencies=защита)
    async def ответить(запрос: Request) -> JSONResponse:
        тело = await запрос.json()
        чат_id = int(тело.get("чат_id", 0))
        текст = str(тело.get("текст", ""))
        решение = await отправитель.отправить_от_админа(чат_id, текст)
        # Отказ показываем администратору дословно: молчание он примет за сбой
        # страницы и напишет то же самое второй раз.
        return JSONResponse(
            {"отправлено": решение.отправлено, "причина": решение.причина},
            status_code=200 if решение.отправлено else 409,
        )

    return приложение
