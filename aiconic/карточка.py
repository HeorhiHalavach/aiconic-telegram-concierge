"""Карточка клиента для окна администратора.

⚠️ **Здесь НЕТ данных о здоровье, и это конструкция, а не обещание.** Требование
Георгия от 2026-08-15: про здоровье в карточке стоит только отметка, а сам
вопрос администратор читает в переписке. Поэтому карточка собирается из двух
источников, и ни один из них не содержит слов клиента:

  • `bookings.yaml` — визиты: дата, время, услуга, мастер;
  • `handovers.yaml` — КОД причины передачи.

Переписка в карточку не попадает вовсе: окно показывает её живьём из Telegram,
к нам она не копируется.

Отдельный модуль, а не функция внутри веб-части, — чтобы карточку мог собрать и
кто-то ещё. По чертежу этапа 2: сегодня она отдаётся страницей как JSON, а если
когда-нибудь понадобится уведомление в мессенджер, тот же вызов даст текст. Две
разные сборки одной карточки разошлись бы (§17).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date


# Что показывать администратору вместо кода. Расшифровка живёт здесь, а не в
# файле метки: в файле — код, в интерфейсе — человеческая строка.
ПОДПИСИ = {
    "медицина": "вопрос о здоровье",
    "торг": "торг или скидка",
    "отмена": "просит отменить запись",
    "перезапись": "просит перенести запись",
    "абонемент": "про абонемент",
    "заслон_цены": "бот назвал цену не из прайса",
    "заслон_времени": "бот назвал время не из свободных окон",
    "заслон_условий": "бот пообещал условие не из правил",
    "запись_не_вышла": "запись не создалась, клиент предупреждён",
    "модель_просит": "бот сам попросил человека",
}


@dataclass
class Визит:
    дата: str
    время: str
    услуга: str
    мастер: str
    цена: int | None = None
    прошёл: bool = False


@dataclass
class Карточка:
    чат_id: int
    имя: str
    канал: str = "telegram"
    визитов_всего: int = 0
    визиты: list[Визит] = field(default_factory=list)
    нужен_ответ: bool = False
    причина_код: str = ""
    причина: str = ""              # расшифровка кода, НЕ текст клиента
    передана: str = ""             # когда передали, ISO


def собрать(
    *, чат_id: int, имя: str, салон, передачи=None, сегодня: date | None = None,
    канал: str = "telegram", сколько_визитов: int = 5,
) -> Карточка:
    """Карточка одного клиента. Без единого слова из его сообщений."""
    сегодня = сегодня or date.today()

    визиты: list[Визит] = []
    for з in салон.записи:
        if int(з.get("чат", -1)) != int(чат_id):
            continue
        услуга = салон.услуга(str(з.get("услуга", "")))
        мастер = салон.мастер(int(з.get("мастер", 0)))
        д = str(з.get("дата", ""))
        визиты.append(
            Визит(
                дата=д,
                время=str(з.get("начало", "")),
                услуга=услуга.название if услуга else str(з.get("услуга", "")),
                мастер=мастер.имя if мастер else "",
                цена=услуга.цена if услуга else None,
                прошёл=bool(д and д < сегодня.isoformat()),
            )
        )
    визиты.sort(key=lambda в: (в.дата, в.время), reverse=True)

    передача = передачи.открытая(чат_id) if передачи else None
    return Карточка(
        чат_id=int(чат_id),
        имя=имя,
        канал=канал,
        визитов_всего=len(визиты),
        визиты=визиты[:сколько_визитов],
        нужен_ответ=передача is not None,
        причина_код=передача.код if передача else "",
        причина=ПОДПИСИ.get(передача.код, передача.код) if передача else "",
        передана=передача.открыта if передача else "",
    )
