"""Заслоны. Каждый БЛОКИРУЕТ действие, а не пишет предупреждение в лог.

Разница принципиальная: отчёт можно проигнорировать, заслон — нет.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime, timezone

# --- 1. Триггеры: поиск по НАЧАЛУ СЛОВА, а не подстрокой --------------------
# Найдено 2026-08-13: подстрока давала ложные срабатывания на безобидных
# фразах — 8 из 14 проверенных. «а можно больше времени?» уходило к человеку
# («боль» внутри «больше»), «условия доставки» уходило в спам и получало
# ПОЛНОЕ МОЛЧАНИЕ («ставки» внутри «доставки»).
#
# Механизм: `\b` + триггер. Это ищет триггер как НАЧАЛО слова и разрешает
# любое окончание — «операц» ловит «операция», «операции», «операцию», но
# «кооперация» уже нет. Русский язык склоняется, поэтому точное совпадение
# слова здесь не годится.
#
# ⚠️ Границей слова лечится не всё. «больше» и «признаться» начинаются ровно
# с «боль» и «приз», поэтому такие жадные триггеры пришлось заменить на более
# длинные формы. Правило на будущее: **триггер не должен быть началом
# безобидного слова** — проверять новый триггер на этом (test_triggers.py).


def _триггер(текст: str, триггеры: tuple[str, ...]) -> str | None:
    t = (текст or "").lower()
    for слово in триггеры:
        if re.search(r"\b" + re.escape(слово), t):
            return слово
    return None


