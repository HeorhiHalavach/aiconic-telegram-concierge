# --- 3. Сверка чисел: цены и время ------------------------------------------
# Модель не должна выдумывать ни цену, ни свободное окно. Промптом это
# не гарантируется, поэтому проверяем результат перед отправкой.

_ЦЕНА = re.compile(r"\b(\d{2,5})\s*(?:₾|лари|gel|л\.)?\b", re.IGNORECASE)
_ВРЕМЯ = re.compile(r"\b([01]?\d|2[0-3]):([0-5]\d)\b")

# Дата — не цена. Живой случай 2026-08-13: модель написала «14.08.2026»,
# заслон увидел в этом цену 2026 и подменил верное подтверждение записи
# шаблоном «передала администратору». Год без валюты рядом вырезаем;
# «2026 ₾» — оставляем, это уже похоже на выдуманную цену.
_ДАТА = re.compile(
    r"\b\d{4}-\d{2}-\d{2}\b"                        # 2026-08-14
    r"|\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b"      # 14.08 и 14.08.2026
    r"|\b(?:19|20)\d{2}\b(?!\s*(?:₾|лари|gel))",    # год, но не «2026 ₾»
    re.IGNORECASE,
)

# Часы, записанные без минут: «работаем с 10 до 21». Имитация 2026-08-13:
# число 21 поймалось как выдуманная цена, и верный ответ про часы работы уехал
# администратору. Оба числа ограничены 24 — «с 60 до 120» под шаблон не попадёт.
_ЧАСОВОЙ_ДИАПАЗОН = re.compile(
    r"\b(?:с|от)?\s*(?:[01]?\d|2[0-4])\s*(?:до|по|–|—|-)\s*(?:[01]?\d|2[0-4])\b",
    re.IGNORECASE,
)


def выдуманные_цены(текст: str, допустимые: set[int]) -> list[int]:
    """Числа, похожие на цену, которых нет в прайсе.

    Намеренно игнорируем время (12:00), даты (14.08.2026) и длительность
    в минутах — иначе заслон ложно срабатывает на верных ответах.
    """
    очищено = _ЧАСОВОЙ_ДИАПАЗОН.sub(" ", _ДАТА.sub(" ", текст or ""))
    без_времени = _ВРЕМЯ.sub(" ", очищено)
    длительности = {30, 60, 90, 120}
    найдено: list[int] = []
    for m in _ЦЕНА.finditer(без_времени):
        n = int(m.group(1))
        if n in допустимые or n in длительности:
            continue
        if n < 20:  # «через 2 часа», «на 5 сеансов» — не цены
            continue
        найдено.append(n)
    return найдено


@dataclass(frozen=True)
class Окна:
    """Свободные времена, разложенные ПО ДНЯМ. Ключ — смещение от сегодня.

    До 2026-08-13 заслон времени сверял с множеством, склеенным по всем трём
    дням, — и пропускал «сегодня в 20:30», когда 20:30 свободно только завтра.
    Дефект был назван в STATUS как B и жил там, пока не дошла очередь.

    `метки` — словарь «слово или дата → смещение». Собирается там же, где
    промпт печатает эти слова, чтобы вокабуляр не разошёлся (§17).

    `часы` — границы рабочего дня. Их можно называть применительно к любому
    дню: «работаем с 10:00 до 21:00» — это факт, а не окно.
    """

    по_дням: dict[int, frozenset[str]]
    метки: dict[str, int]
    часы: frozenset[str] = frozenset()

    def для_дня(self, смещение: int) -> frozenset[str]:
        return self.по_дням.get(смещение, frozenset()) | self.часы

    def любой_день(self) -> frozenset[str]:
        """Времена, свободные хотя бы в один из дней, плюс часы работы.

        Нужно для случая, когда день не назван НИГДЕ — ни в ответе, ни в
        вопросе клиента. Тогда день неизвестен, и строгая сверка с сегодня
        превращается в угадывание: живой прогон 2026-08-13 дал так четыре
        ложных срабатывания подряд. А вот время, свободное ни в один день, —
        по-прежнему выдумка.
        """
        итог: frozenset[str] = self.часы
        for времена in self.по_дням.values():
            итог = итог | времена
        return итог

    def записываемые(self) -> set[str]:
        """Все настоящие окна без часов работы — для заслона записи."""
        итог: set[str] = set()
        for времена in self.по_дням.values():
            итог |= set(времена)
        return итог


def _разметить_дни(текст: str, метки: dict[str, int]) -> list[tuple[int, int]]:
    """[(позиция в тексте, смещение дня)] по возрастанию позиции."""
    найдено: list[tuple[int, int]] = []
    низ = текст.lower()
    for слово, смещение in метки.items():
        начало = 0
        while (i := низ.find(слово.lower(), начало)) != -1:
            найдено.append((i, смещение))
            начало = i + 1
    найдено.sort()
    return найдено


# «8 утра» — то же время, что «08:00», но под ЧЧ:ММ не подходит. Живой прогон
# 2026-08-14: клиент спросил «можно в 8 утра?», модель верно ответила «в 08:00 мы
# закрыты», и заслон счёл 08:00 выдумкой — освобождение по цитате искало только
# формат с двоеточием. Берём ТОЛЬКО явно часовые формы: «в 5 сеансов» не должно
# превращаться в 05:00, иначе освобождение начнёт дырявить заслон.
_ЧАС_СЛОВАМИ = re.compile(
    r"\b([01]?\d|2[0-3])\s*(?:час(?:ов|а)?|утра|вечера|дня|ночи)\b"
)


def _процитированные_времена(сказал_клиент: str) -> set[str]:
    т = сказал_клиент or ""
    времена = {f"{h.zfill(2)}:{m}" for h, m in _ВРЕМЯ.findall(т)}
    времена |= {f"{ч.zfill(2)}:00" for ч in _ЧАС_СЛОВАМИ.findall(т)}
    return времена


def выдуманное_время(текст: str, окна: Окна, сказал_клиент: str = "") -> list[str]:
    """Времена в ответе, которых нет среди свободных окон НАЗВАННОГО ДНЯ.

    `сказал_клиент` — сообщение клиента, на которое отвечаем. Оно нужно по двум
    причинам, и обе выяснились на живом прогоне 2026-08-13, где заслон трижды
    задушил верный ответ:

    1. **День берётся из вопроса клиента**, если в ответе метки дня нет. Клиент
       написал «запишите на завтра в 20:30», модель ответила «в 20:30 есть
       30-минутные сеансы» — без слова «завтра». Раньше это сверялось с сегодня
       и уезжало администратору. День задаёт разговор, а не одна реплика.
    2. **Время, процитированное из вопроса клиента, не выдумка.** На «а в 23:00
       можно?» модель отвечает «в 23:00 мы закрыты» — это верный отказ, а не
       предложение несуществующего окна. Записать на такое время всё равно
       нельзя: `Booker` откажет, а клиент получит поправку.

    Правила отнесения времени к дню — простые намеренно, потому что сложный
    разбор естественного языка здесь ненадёжнее самой проверки:

    - все метки про ОДИН день → он относится ко всем временам. Работает и
      «20:30 у Мариам завтра или 20:00 у Мариам завтра», где метка идёт после
      времени;
    - метки про разные дни → у каждого времени берётся ближайшая СЛЕВА;
    - меток нет НИГДЕ → день неизвестен, и сверяем с любым днём горизонта.
      Время, свободное хотя бы в один день, пропускаем; свободное ни в один —
      ловим. Раньше здесь стояла сверка с сегодня, и это оказалось угадыванием:
      день мог быть задан тремя репликами раньше. Живой прогон 2026-08-13 дал
      так четыре ложных срабатывания подряд, а ни одного настоящего улова эта
      строгость не принесла — настоящие галлюцинации либо шли с меткой дня,
      либо не существовали ни в один день.
    """
    т = текст or ""
    метки = _разметить_дни(т, окна.метки)
    if not метки and сказал_клиент:
        метки = _разметить_дни(сказал_клиент, окна.метки)
    процитированные = _процитированные_времена(сказал_клиент)

    лишние: list[str] = []
    for m in _ВРЕМЯ.finditer(т):
        часы, минуты = m.group(1), m.group(2)
        строка = f"{часы.zfill(2)}:{минуты}"

        if строка in процитированные:
            continue        # клиент назвал это время сам — не наша выдумка

        if not метки:
            # день не назван нигде — судить о нём нечем
            if строка not in окна.любой_день():
                лишние.append(строка)
            continue

        # По умолчанию — день ПЕРВОЙ метки, дальше уточняем ближайшей слева.
        # Отдельного правила «все метки про один день» не нужно: при одном дне
        # обе ветки дают одно и то же. Это выяснила мутационная проверка —
        # мутация того правила ничего не меняла, значит правило было лишним.
        день = метки[0][1]
        for позиция, смещение in метки:
            if позиция < m.start():
                день = смещение
            else:
                break

        if строка not in окна.для_дня(день):
            лишние.append(строка)
    return лишние


# --- 3-бис. Сверка обязательств --------------------------------------------
# Дважды на живых прогонах модель приписала салону денежное условие, которого
# в правилах нет: «будет удержана часть стоимости» и «позже возврата не будет».
# Ни цены, ни времени в таких фразах нет — прежние два заслона слепы к ним.
#
# Приём: словарь обязательств задают САМИ правила салона. Корень, которого нет
# в тексте правил, бот произносить не вправе. Смысл мы не понимаем и не
# пытаемся — сверяем вокабуляр, и этого достаточно, чтобы поймать оба случая.
#
# Осознанная грубость: фраза клиента, процитированная в отказе, тоже уедет
# администратору. Эскалация безопасна, выдуманное денежное условие — нет.
ОБЯЗЫВАЮЩИЕ_КОРНИ = (
    # «возвращ» и «возмещ» добавлены 2026-08-13 после живого промаха: заслон
    # пропустил клиенту «стоимость не будет ВОЗВРАЩЕНА» — в списке были только
    # «возврат» и «вернут», а этот корень другой. Промах ровно на том классе,
    # для которого заслон и создан.
    "возврат", "возвращ", "возмещ", "вернём", "вернем", "вернут",
    "вычт", "вычет",
    # «верну» убрано: начало «вернуться», «вернусь». Формы возврата денег уже
    # покрыты «вернём», «вернут», «возврат», «возвращ».
    # «пеня»/«пени» убрано: начало «пение». Штрафы покрыты «штраф», «неустойк».
    "удерж", "штраф", "неустойк",
    "доплат", "предоплат", "аванс", "залог", "депозит",
    "компенс", "спишем", "списан", "спишут",
    "гарантиру", "обязан", "обязуем", "приплат",
    "скидк", "акци", "бонус", "кэшбэк", "кешбэк",
)


# --- 3-трис. Просил ли клиент записать -------------------------------------
# Нужно ровно для одного решения: извиняться ли, когда запись не создалась.
#
# Имитация 2026-08-14: клиент написал «?», модель сама предложила 14:00 и в том
# же ходу попыталась записать. Заслон верно отказал — клиент ничего не
# подтверждал, — но клиент увидел «записать не получилось», хотя ни о чём не
# просил. Извинение на пустом месте пугает.
#
# Отсюда правило: поправка нужна, если клиент МОГ ПОВЕРИТЬ, что записан, то есть
# если он сам просил записать. Модель забежала вперёд — молчим и пишем в лог.
СЛОВА_ЗАПИСИ = (
    "запиш", "записать", "записаться", "запись",
    "давайте", "подтвержд", "хочу", "годится", "подходит", "оформ",
    "да", "ок", "окей", "согласен", "согласна",
)


def просил_записать(текст: str) -> bool:
    """Есть ли в сообщении клиента просьба или согласие записаться."""
    t = (текст or "").lower()
    if _ВРЕМЯ.search(t):
        return True
    for слово in СЛОВА_ЗАПИСИ:
        # короткие слова — только целиком: «да» не должно ловиться в «давно»
        шаблон = r"\b" + re.escape(слово) + (r"\b" if len(слово) <= 3 else "")
        if re.search(шаблон, t):
            return True
    return False


def выдуманные_условия(текст: str, правила) -> list[str]:
    """Обязывающие корни в ответе, которых нет в правилах салона.

    Пустой список — можно отправлять. Непустой — отдать человеку.

    ⚠️ Ищем ПО НАЧАЛУ СЛОВА, как и остальные триггеры. Здесь это исправлено
    позже, и вот чем обошлось: «нет в раСПИСАНии» ловилось как «списан», и
    верный ответ уехал администратору на живом прогоне 2026-08-13. Тот же класс
    бага был исправлен в медицинских и спам-триггерах, а сюда я его перенести
    забыл — ровно то расхождение, от которого предостерегает §17.
    """
    свод = " ".join(str(п) for п in (правила or [])).lower()
    t = (текст or "").lower()
    return [
        к for к in ОБЯЗЫВАЮЩИЕ_КОРНИ
        if re.search(r"\b" + re.escape(к), t)
        and not re.search(r"\b" + re.escape(к), свод)
    ]


# --- 4. Приём: что вообще обрабатываем --------------------------------------


@dataclass
class Приём:
    """Фильтры на входе. Все проверки дублируют фильтры Telethon намеренно:
    ошибка в фильтре молча открыла бы доступ всем."""

    белый_список: set[int]
    старт: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    режим_наблюдения: bool = False

    def причина_отказа(
        self, *, чат_id: int, личный: bool, исходящее: bool, дата: datetime | None,
        догоняем: bool = False,
    ) -> str | None:
        if исходящее:
            return "исходящее сообщение"
        if not личный:
            return "не личный чат"
        if дата is not None:
            # дата от Telegram — tz-aware UTC; наивное время здесь дало бы TypeError
            if дата.tzinfo is None:
                return "дата без таймзоны — не доверяем"
            # ⚠️ Отсечка по старту снимается ТОЛЬКО для догоняющих сообщений.
            # Она существует, чтобы первый запуск не ответил на весь непрочитанный
            # backlog; добор при старте обходит её осознанно и узко: только чаты,
            # где последнее слово за клиентом, и только за последние часы.
            # Остальные заслоны — белый список, личный чат, tz-aware — остаются
            # на месте и для догоняющих.
            if not догоняем and дата <= self.старт:
                return "сообщение старше запуска процесса"
        if чат_id not in self.белый_список:
            return "чат не в белом списке"
        return None


# --- 5. Ограничение частоты -------------------------------------------------


class Лимит:
    """Не больше N ответов за окно, на чат и суммарно."""

    def __init__(self, на_чат: int = 6, всего: int = 30, окно_сек: int = 60) -> None:
        self.на_чат = на_чат
        self.всего = всего
        self.окно = окно_сек
        self._события: list[tuple[float, int]] = []

    def _подчистить(self, сейчас: float) -> None:
        порог = сейчас - self.окно
        self._события = [(t, c) for t, c in self._события if t > порог]

    def разрешено(self, чат_id: int, сейчас: float) -> bool:
        self._подчистить(сейчас)
        if len(self._события) >= self.всего:
            return False
        if sum(1 for _, c in self._события if c == чат_id) >= self.на_чат:
            return False
        return True

    def отметить(self, чат_id: int, сейчас: float) -> None:
        self._события.append((сейчас, чат_id))
