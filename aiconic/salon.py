"""Данные салона: прайс, мастера, записи и расчёт свободных окон.

Всё время здесь — местное время салона (Тбилиси, UTC+4), строками "HH:MM".
Даты сообщений Telegram приходят в UTC и с этим временем не смешиваются.

Свободные окна не хранятся, а вычисляются: хранимый список мгновенно
разошёлся бы с записями.
"""

from __future__ import annotations

import os
import re
import tempfile
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

import yaml

DATA = Path(__file__).resolve().parent.parent / "data"

# Часовой пояс салона живёт здесь: это его свойство, а не свойство напоминаний.
ЗОНА_САЛОНА = timezone(timedelta(hours=4))   # Тбилиси, UTC+4


def минут_сейчас() -> int:
    """Минуты от полуночи по времени салона.

    Нужно, чтобы прошедшее время не считалось свободным. Живой случай
    2026-08-13: в 21:32 бот предложил клиенту «сегодня в 17:30» — расчёт окон
    шёл от начала смены мастера и про текущее время не знал вовсе.
    """
    т = datetime.now(ЗОНА_САЛОНА)
    return т.hour * 60 + т.minute

# пн=0 ... вс=6, как в date.weekday()
_ДНИ = {"пн": 0, "вт": 1, "ср": 2, "чт": 3, "пт": 4, "сб": 5, "вс": 6}


def записать_атомарно(
    каталог: Path, имя: str, данные: dict, *, шапка: str = ""
) -> Path:
    """Временный файл рядом + `os.replace`. Битого файла не остаётся никогда.

    Вынесено из `Салон.сохранить_записи` 2026-08-15: тем же приёмом пишет метку
    передачи (`handover.py`), а две копии одного приёма разошлись бы — у одной
    забыли бы уборку `.tmp`, и это заметили бы только при сбое записи (§17).

    Уборка `.tmp` в `except BaseException` — несущая: без неё сбой посреди
    `safe_dump` оставляет мусор рядом с данными. На это стоит отдельный тест с
    подменённым `safe_dump`, падающим на середине.
    """
    путь = Path(каталог) / имя
    fd, tmp = tempfile.mkstemp(dir=str(каталог), suffix=".tmp")
    os.close(fd)
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            if шапка:
                f.write(шапка)
            yaml.safe_dump(данные, f, allow_unicode=True, sort_keys=False)
        os.replace(tmp, путь)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise
    return путь


def мин(hhmm: str) -> int:
    """"10:30" -> 630 минут от полуночи."""
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


def чч_мм(t: int) -> str:
    """630 -> "10:30"."""
    return f"{t // 60:02d}:{t % 60:02d}"


@dataclass(frozen=True)
class Мастер:
    id: int
    имя: str
    пол: str
    часы: str
    график: tuple[int, ...]

    def работает(self, день: date) -> bool:
        return день.weekday() in self.график


@dataclass(frozen=True)
class Услуга:
    id: str
    название: str
    длительность: int
    цена: int


class Салон:
    """Читает три YAML-файла. Пишет только в bookings.yaml (см. booker)."""

    def __init__(self, каталог: Path | None = None) -> None:
        self.каталог = Path(каталог) if каталог else DATA
        self.перечитать()

    # --- загрузка ---

    def _файл(self, имя: str) -> dict:
        путь = self.каталог / имя
        with open(путь, encoding="utf-8") as f:
            return yaml.safe_load(f) or {}

    def перечитать(self) -> None:
        прайс = self._файл("price.yaml")
        график = self._файл("schedule.yaml")
        записи = self._файл("bookings.yaml")

        self.инфо: dict = прайс.get("салон", {})
        self.правила: list[str] = прайс.get("правила", []) or []
        self.абонементы: list[dict] = прайс.get("абонементы", []) or []

        self.услуги: list[Услуга] = [
            Услуга(u["id"], u["название"], int(u["длительность"]), int(u["цена"]))
            for u in прайс.get("услуги", []) or []
        ]
        self.мастера: list[Мастер] = [
            Мастер(
                int(m["id"]),
                m["имя"],
                m["пол"],
                m["часы"],
                tuple(_ДНИ[d] for d in m.get("график", []) or []),
            )
            for m in график.get("мастера", []) or []
        ]
        self.шаг: int = int(график.get("шаг_сетки", 30))
        self.записи: list[dict] = list(записи.get("записи", []) or [])

    # --- справочники ---

    def услуга(self, что: str) -> Услуга | None:
        """Найти услугу по id, по названию или по «название, N мин».

        ⚠️ Терпимость появилась после имитации 2026-08-13: модель прислала
        `услуга: "Массаж спины, 60 мин"` вместо `back60`, поиск не нашёл — и
        настоящая запись не состоялась. Промпт теперь требует id, но строгий
        поиск делал из вариативности модели потерянного клиента.

        Длительность в строке — не украшение, а способ различить одноимённые
        услуги: «Классический массаж» есть на 60 и на 90 минут с разными id.
        Если различить нельзя, возвращаем None: угадать хуже, чем отказать.
        """
        s = (что or "").strip().lower()
        if not s:
            return None
        for u in self.услуги:
            if u.id.lower() == s:
                return u

        длительность = None
        if m := re.search(r"(\d{2,3})\s*мин", s):
            длительность = int(m.group(1))
        имя = re.sub(r"[,;(]?\s*\d{2,3}\s*мин\w*\.?\)?", "", s).strip(" ,.;-—")

        похожие = [u for u in self.услуги if u.название.lower() == имя]
        if длительность is not None:
            уточнённые = [u for u in похожие if u.длительность == длительность]
            if уточнённые:
                похожие = уточнённые
        return похожие[0] if len(похожие) == 1 else None

    def мастер(self, id_: int) -> Мастер | None:
        return next((m for m in self.мастера if m.id == id_), None)

    def все_цены(self) -> set[int]:
        """Все допустимые числа-цены — для заслона от выдуманной цены."""
        цены = {u.цена for u in self.услуги}
        цены |= {int(a["цена"]) for a in self.абонементы if "цена" in a}
        return цены

    # --- свободные окна ---

    def занятость(self, мастер_id: int, день: date) -> list[tuple[int, int]]:
        д = день.isoformat()
        return [
            (мин(з["начало"]), мин(з["начало"]) + int(з["длительность"]))
            for з in self.записи
            if int(з["мастер"]) == мастер_id and str(з["дата"]) == д
        ]

    def свободные_окна(
        self,
        день: date,
        длительность: int,
        пол: str | None = None,
        мастер_id: int | None = None,
        не_раньше: int | None = None,
    ) -> dict[str, list[str]]:
        """{имя мастера: ["10:00", "12:30", ...]}.

        Окно годится, если услуга влезает ЦЕЛИКОМ до конца смены и не
        пересекает ни одну запись. Окно, кончающееся ровно в час конца
        смены, годится.

        `не_раньше` — минуты от полуночи; окна раньше этого времени
        отбрасываются. Передаётся только для СЕГОДНЯ: на завтра прошедшего
        времени не существует.
        """
        итог: dict[str, list[str]] = {}
        for m in self.мастера:
            if пол and m.пол != пол:
                continue
            if мастер_id is not None and m.id != мастер_id:
                continue
            if not m.работает(день):
                continue

            начало_смены, конец_смены = (мин(x) for x in m.часы.split("-"))
            занято = self.занятость(m.id, день)

            времена: list[str] = []
            t = начало_смены
            if не_раньше is not None and t < не_раньше:
                # выравниваем по сетке, чтобы не появилось окно вне шага
                шагов = -(-(не_раньше - t) // self.шаг)      # округление вверх
                t += шагов * self.шаг
            while t + длительность <= конец_смены:
                если_свободно = not any(
                    t < конец and начало < t + длительность for начало, конец in занято
                )
                if если_свободно:
                    времена.append(чч_мм(t))
                t += self.шаг

            if времена:
                итог[m.имя] = времена
        return итог

    def окно_свободно(
        self, день: date, время: str, длительность: int, мастер_id: int,
        не_раньше: int | None = None,
    ) -> bool:
        m = self.мастер(мастер_id)
        if m is None:
            return False
        окна = self.свободные_окна(
            день, длительность, мастер_id=мастер_id, не_раньше=не_раньше
        )
        return время in окна.get(m.имя, [])

    # --- запись на диск (только bookings.yaml) ---

    def сохранить_записи(self) -> Path:
        return записать_атомарно(
            self.каталог, "bookings.yaml", {"записи": self.записи},
            шапка=(
                "# ЭТИМ ФАЙЛОМ ВЛАДЕЕТ КОД — он перезаписывается целиком.\n"
                "# Ручные правки и комментарии здесь не сохранятся.\n"
                "# Правьте schedule.yaml и price.yaml.\n\n"
            ),
        )
