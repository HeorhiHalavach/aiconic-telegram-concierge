"""Метка «здесь администратор должен ответить».

Единственное, чего Telegram про диалог не знает. `unread_count` он знает, а вот
«бот передал разговор человеку» — нет, потому что это наше решение, а не факт
мессенджера.

⚠️ **Причина хранится КОДОМ, а не текстом клиента.** Это требование Георгия от
2026-08-15: в карточке не должно быть данных о здоровье. Поэтому здесь лежит
`медицина`, а не «болит спина после операции». Сама переписка не копируется —
окно показывает её живьём из Telegram.

⚠️ **Метка обязана переживать перезапуск.** Тем же приёмом, что отметка
`напомнили` в `bookings.yaml`: состояние в файле, а не в памяти процесса. Флаг в
памяти — это намерение, а не гарантия: упал, поднялся — и администратор больше
не знает, где его ждут.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import yaml

from .salon import ЗОНА_САЛОНА, записать_атомарно

# Коды причин. Закрытый список намеренно: свободный текст здесь рано или поздно
# станет копией сообщения клиента, а этого нельзя (см. шапку).
МЕДИЦИНА = "медицина"
ТОРГ = "торг"
ОТМЕНА = "отмена"
ПЕРЕЗАПИСЬ = "перезапись"
АБОНЕМЕНТ = "абонемент"
ЗАСЛОН_ЦЕНЫ = "заслон_цены"
ЗАСЛОН_ВРЕМЕНИ = "заслон_времени"
ЗАСЛОН_УСЛОВИЙ = "заслон_условий"
ЗАПИСЬ_НЕ_ВЫШЛА = "запись_не_вышла"
МОДЕЛЬ_ПРОСИТ = "модель_просит"

КОДЫ = frozenset({
    МЕДИЦИНА, ТОРГ, ОТМЕНА, ПЕРЕЗАПИСЬ, АБОНЕМЕНТ,
    ЗАСЛОН_ЦЕНЫ, ЗАСЛОН_ВРЕМЕНИ, ЗАСЛОН_УСЛОВИЙ, ЗАПИСЬ_НЕ_ВЫШЛА, МОДЕЛЬ_ПРОСИТ,
})

ФАЙЛ = "handovers.yaml"


class НеизвестныйКод(ValueError):
    """Код не из закрытого списка.

    Это заслон, а не придирка: любой свободный текст здесь — потенциальная
    выдержка из сообщения клиента о здоровье.
    """


@dataclass(frozen=True)
class Передача:
    чат: int
    код: str
    открыта: str          # ISO, местное время салона
    снята: str | None = None

    @property
    def открытая(self) -> bool:
        return self.снята is None


def _сейчас() -> str:
    return datetime.now(ЗОНА_САЛОНА).isoformat(timespec="seconds")


class Передачи:
    """Список передач в файле. Класс, а не модуль-с-глобалами: тестам нужен
    свой каталог, а процессу — свой."""

    def __init__(self, каталог: Path) -> None:
        self.каталог = Path(каталог)
        self.записи: list[dict] = []
        self.перечитать()

    def перечитать(self) -> None:
        путь = self.каталог / ФАЙЛ
        if not путь.exists():
            self.записи = []
            return
        данные = yaml.safe_load(путь.read_text(encoding="utf-8")) or {}
        сырое = данные.get("передачи") if isinstance(данные, dict) else None
        # ⚠️ Форма проверяется, а не предполагается. Найдено собственным
        # враждебным тестом: файл с «передачи: не список» ронял `открытые()`
        # через AttributeError, то есть окно администратора не открывалось
        # вовсе. Мусор молча отбрасываем — окно обязано подняться и показать
        # то, что уцелело, а не упасть целиком.
        self.записи = [
            з for з in (сырое if isinstance(сырое, list) else [])
            if isinstance(з, dict) and "чат" in з and "код" in з
        ]

    def сохранить(self) -> Path:
        return записать_атомарно(
            self.каталог, ФАЙЛ, {"передачи": self.записи},
            шапка=(
                "# ЭТИМ ФАЙЛОМ ВЛАДЕЕТ КОД — он перезаписывается целиком.\n"
                "# Здесь только КОД причины, никогда не текст клиента:\n"
                "# в переписке бывают данные о здоровье, им тут не место.\n\n"
            ),
        )

    # --- изменение ---

    def открыть(self, чат: int, код: str) -> Передача:
        """Пометить, что в чате ждут человека. Повторный вызов не плодит копий.

        Первый код побеждает намеренно: медицинский вопрос, за которым клиент
        начал торговаться, остаётся медицинским — так администратор увидит
        главное, а не последнее.
        """
        if код not in КОДЫ:
            raise НеизвестныйКод(
                f"код {код!r} не из списка {sorted(КОДЫ)}. "
                "Свободный текст здесь запрещён: в нём окажется сообщение клиента."
            )
        уже = self.открытая(чат)
        if уже:
            return уже
        запись = {"чат": int(чат), "код": код, "открыта": _сейчас(), "снята": None}
        self.записи.append(запись)
        self.сохранить()
        return Передача(**запись)

    def снять(self, чат: int) -> bool:
        """Администратор ответил. Возвращает, была ли открытая передача."""
        нашлась = False
        for з in self.записи:
            if int(з.get("чат", -1)) == int(чат) and з.get("снята") is None:
                з["снята"] = _сейчас()
                нашлась = True
        if нашлась:
            self.сохранить()
        return нашлась

    # --- чтение ---

    def открытая(self, чат: int) -> Передача | None:
        for з in self.записи:
            if int(з.get("чат", -1)) == int(чат) and з.get("снята") is None:
                return Передача(
                    чат=int(з["чат"]), код=str(з["код"]),
                    открыта=str(з["открыта"]), снята=None,
                )
        return None

    def открытые(self) -> dict[int, Передача]:
        """Что показывать в ленте красным. Ключ — чат, значение — передача."""
        итог: dict[int, Передача] = {}
        for з in self.записи:
            if з.get("снята") is None:
                чат = int(з.get("чат", -1))
                итог[чат] = Передача(
                    чат=чат, код=str(з["код"]),
                    открыта=str(з["открыта"]), снята=None,
                )
        return итог
