"""Создание записи. Модель не пишет — пишет Booker.

Тот же принцип, что у Sender: модель только предлагает, действие выполняет
отдельный компонент со своими заслонами.

Три заслона, каждый отвергает конкретную поломку:

1. Время должно быть из тех, что МЫ САМИ предлагали в этом чате.
   Иначе модель может записать на выдуманное или занятое время, а шаг
   «предложили → подтвердили» останется пожеланием в промпте, а не
   требованием кода.
2. Свободность проверяется В МОМЕНТ ЗАПИСИ, а не в момент предложения:
   клиент подтверждает через пять минут, за которые окно могли занять.
3. Идемпотентность по (чат, дата, время, мастер): клиент дважды сказал «да» —
   вторая запись не появляется.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass
from datetime import date

from .salon import мин


class ЗаписьОтклонена(Exception):
    """Заслон не пропустил запись. Текст пригоден для показа администратору.

    ⚠️ Для КЛИЕНТА это означает, что записи нет, а он мог прочитать «записала
    вас». Дирижёр обязан ему об этом сказать — см. app.py.
    """


class ЗаписьУжеЕсть(ЗаписьОтклонена):
    """Идемпотентность: такая запись уже создана.

    Отдельный класс намеренно. Для клиента это НЕ отказ: он записан, и
    подтверждение, которое он получил, — правда. Сказать ему «не получилось»
    было бы хуже молчания.

    Несёт `существующая` — ту самую запись из файла. Без неё дирижёр мог бы
    сказать только «вы уже записаны», не сумев назвать, на что именно: имитация
    показала, что клиент дважды слышит «Записываю вас» и остаётся в неведении.
    """

    def __init__(self, сообщение: str, существующая: dict | None = None) -> None:
        super().__init__(сообщение)
        self.существующая = существующая or {}


@dataclass
class Запись:
    чат: int
    мастер: int
    дата: str
    начало: str
    длительность: int
    услуга: str
    клиент: str


class Booker:
    def __init__(self, салон) -> None:
        self.салон = салон
        self._замок = asyncio.Lock()

    # --- проверки, вынесены отдельно, чтобы их можно было прогнать без файла ---

    def _проверить_предлагали(self, время: str, предложенные: list[str]) -> None:
        if время not in (предложенные or []):
            raise ЗаписьОтклонена(
                f"время {время} мы в этом чате не предлагали — записывать нельзя"
            )

    def _проверить_дубль(
        self, чат: int, день: date, время: str, длительность: int
    ) -> None:
        """Клиент не может быть в двух местах одновременно.

        ⚠️ Раньше ключом было (чат, дата, время, МАСТЕР) — и имитация обошла
        заслон в два хода: «запишите на 14:00» дало запись к Мариам, тот же
        запрос ещё раз — к Нино. Формально не дубль, фактически человек в двух
        креслах.

        Мастера в ключе нет намеренно, и сравниваются не начала, а ИНТЕРВАЛЫ:
        14:00–15:00 и 14:30–15:00 тоже несовместимы, хотя начала разные.
        """
        начало = мин(время)
        конец = начало + длительность
        д = день.isoformat()
        for з in self.салон.записи:
            if int(з.get("чат", -1)) != чат or str(з["дата"]) != д:
                continue
            н = мин(str(з["начало"]))
            к = н + int(з["длительность"])
            if начало < к and н < конец:
                raise ЗаписьУжеЕсть(
                    f"клиент уже записан на {з['начало']} — время пересекается",
                    существующая=з,
                )

    def _проверить_свободно(
        self, день: date, время: str, длительность: int, мастер_id: int,
        не_раньше: int | None = None,
    ) -> None:
        if not self.салон.окно_свободно(
            день, время, длительность, мастер_id, не_раньше=не_раньше
        ):
            raise ЗаписьОтклонена(f"время {время} уже занято или прошло")

    # --- собственно запись ---

    def записать_синхронно(
        self,
        *,
        чат: int,
        день: date,
        время: str,
        мастер_id: int,
        услуга_id: str,
        предложенные: list[str],
        клиент: str = "",
        не_раньше: int | None = None,
    ) -> Запись:
        """Без замка — для тестов и для вызова изнутри записать()."""
        услуга = self.салон.услуга(услуга_id)
        if услуга is None:
            raise ЗаписьОтклонена(f"услуги «{услуга_id}» нет в прайсе")
        if self.салон.мастер(мастер_id) is None:
            raise ЗаписьОтклонена(f"мастера с id {мастер_id} нет")

        self._проверить_предлагали(время, предложенные)
        self._проверить_дубль(чат, день, время, услуга.длительность)
        self._проверить_свободно(
            день, время, услуга.длительность, мастер_id, не_раньше=не_раньше
        )

        запись = Запись(
            чат=чат,
            мастер=мастер_id,
            дата=день.isoformat(),
            начало=время,
            длительность=услуга.длительность,
            услуга=услуга.id,
            клиент=клиент,
        )
        self.салон.записи.append(vars(запись))
        self.салон.сохранить_записи()
        return запись

    async def записать(self, **kwargs) -> Запись:
        """Под замком: два чата могут подтвердить одновременно."""
        async with self._замок:
            return self.записать_синхронно(**kwargs)
