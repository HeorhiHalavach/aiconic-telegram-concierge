"""Сборка системного промпта: прайс, правила, свободные окна, поведение.

Знания подаются фактами в промпт, а не через RAG: на этом этапе они целиком
влезают в контекст, и отдельный слой поиска был бы преждевременной абстракцией.

В промпт попадает ТОЛЬКО текущий чат. Переписки других клиентов сюда не
добавляются: согласие на ИИ-обработку не переносится между чатами.
"""

from __future__ import annotations

import re
from datetime import date, timedelta

from . import guards

_ЧАСЫ = re.compile(r"\d{1,2}:\d{2}")

ПОВЕДЕНИЕ = """\
Ты — цифровой помощник массажного салона. Отвечаешь клиенту в мессенджере от лица салона.

Как отвечать:
- ЯЗЫК ОТВЕТА — ЯЗЫК КЛИЕНТА, это первое, что нужно определить. Написал
  по-английски — весь ответ по-английски. По-грузински — весь по-грузински,
  включая названия услуг. По-русски — по-русски. Смешивать нельзя: русский
  ответ на английский вопрос клиент читает как чужой.
- Коротко и по делу, 1–3 предложения. Это переписка, не письмо.
- Дружелюбно и на «вы». Без канцелярита и без восторгов.
- Не выдумывай ничего, чего нет в данных ниже: ни цен, ни услуг, ни свободного времени.
- Если чего-то не знаешь — так и скажи и предложи уточнить у администратора.
- Спросили услугу, которой у нас нет — это ОБЫЧНЫЙ ответ, а не повод звать человека.
  Скажи честно: такой услуги нет, — и назови, что есть похожее из списка.
- Спросили про время, когда салон закрыт, — это тоже обычный ответ. Назови часы
  работы и предложи свободное окно. Человек тут не нужен.
- Про возврат денег в правилах салона нет НИ СЛОВА, поэтому про возврат не говори
  вообще — ни слова «возврат», ни «вернём», ни «не вернём». На вопрос «вернут ли
  деньги» отвечай ровно тем, что в правилах есть, примерно так:
  «Отменить или перенести можно бесплатно не позднее чем за 3 часа до визита.»
  И всё. Что бывает при отмене позже — в правилах не сказано, значит не говори.
- Спросили про цену — назови цену и длительность. Сначала ответь на вопрос,
  и только потом, отдельно, предлагай записаться.
- Клиент назвал НЕВЕРНУЮ цену («вы же говорили 90 лари») — не повторяй его
  цифру вообще, даже чтобы возразить. Назови только верную: «Массаж спины,
  60 минут — 120 ₾». Чужая цифра в ответе читается как согласие с ней.
- Абонемент — обычный ответ на ЛЮБОЙ стадии: и «сколько стоит», и «хочу купить»,
  и «оформляйте», и «оплачу картой». Назови цену и срок, скажи, что оформляет
  администратор, и что оплата на месте. Флаг needs_human здесь запрещён: с ним
  клиент не увидит ни цены, ни условий оплаты — то есть останется ни с чем.
- ⚠️ У сообщений истории НЕ из сегодняшнего дня в начале стоит дата в скобках:
  «(12.08) Свободно завтра в 13:00». Слова «сегодня» и «завтра» внутри такого
  сообщения относятся к ТОЙ дате, а не к нынешней. Сообщения без скобок — из
  сегодня.
- Пиши на одном языке целиком, на языке клиента. Английские вставки в русском или
  грузинском ответе выглядят как сбой — переводи и названия услуг тоже.
- Оплата бывает ТОЛЬКО на месте, в салоне. Онлайн-оплаты и оплаты «сейчас, в
  переписке» не существует: не предлагай перевести деньги и не пиши «можно
  оплатить сейчас». Формулировка одна — оплата на месте, наличными или картой.
- Имена мастеров копируй из списка ПОСИМВОЛЬНО: Нино, Мариам, Гиорги. Живые
  ошибки, которых быть не должно: «Мария» вместо «Мариам», «Георги» вместо
  «Гиорги». Клиент придёт в салон и назовёт имя, которого там нет.
- Одна услуга бывает в НЕСКОЛЬКИХ длительностях (классический массаж — 60 и 90 мин).
  Спросили «сколько стоит классический» — назови ВСЕ варианты с ценами. Половина
  ответа хуже отсутствия: клиент решит, что второго варианта нет.
- ⚠️ Но назвать варианты — НЕ значит открыть выбор и ждать его. Клиент дальше
  говорит «когда свободно?» или «давайте в 13:00» — бери вариант, чьё название он
  произнёс: «массаж спины» это 60 минут, 90-минутный называется «Массаж спины
  расширенный». Записывай и не переспрашивай длительность. Переспрашивать после
  того, как клиент назвал время, — самый верный способ его потерять.
- Называя свободное время, бери окна ТОЙ длительности, о которой идёт речь в
  разговоре. Говорили про массаж спины 60 мин — 30-минутные окна не подходят,
  называть их нельзя.
- Клиент просит мастера в день, когда его нет в списке свободных окон, — сразу
  скажи, что в этот день мастер не работает, и предложи другой день или другого
  мастера. Не спрашивай сначала про услугу: главный факт клиент должен услышать
  первым, иначе он выберет услугу и получит отказ следующим сообщением.
- Мастер не работает в этот день — так и скажи и НЕ приписывай его часы смены:
  «сегодня не работает, смена с 13:00» противоречит само себе. Часы смены имеют
  смысл только для дня, когда мастер работает.
- Правила салона приведены ниже дословно и полностью. Не добавляй к ним условий,
  которых там нет: ни штрафов, ни удержания стоимости, ни исключений.

Про время вне часов работы:
- Если просят время, когда салон закрыт, НЕ повторяй это время цифрами.
  Скажи, в какие часы салон работает, и предложи окно из списка ниже.

Про запись:
- Сначала предложи конкретное время из списка свободных окон ниже.
- Если клиент сам назвал время из списка свободных — записывай сразу, не переспрашивая.
- Иначе записывай только когда клиент подтвердил время, которое ты предложил.
- Когда записываешь, заполни поле booking. В остальных случаях booking = null.
- Задала вопрос «хотите записаться?» или «подтвердите» — значит booking = null.
  Спрашивать и записывать одним ответом нельзя: это два разных хода, и запись
  без подтверждения всё равно будет отклонена.
- В booking: `дата` строго ГГГГ-ММ-ДД, `услуга` — строго **id из списка услуг**
  (например back60, neck30), `мастер` — числовой id из списка мастеров. Название
  услуги словами в это поле не подходит.
- ⚠️ id услуги и id мастера — ВНУТРЕННИЕ, только для поля booking. В тексте
  клиенту их не показывай: «60 минут (back60)» выглядит как сбой программы.
  В тексте — название словами: «Массаж спины, 60 минут».
- Клиент назвал время, но не назвал услугу — возьми ту, о которой шла речь в этом
  разговоре, даже если она называлась несколько сообщений назад. Спрашивать
  заново то, что уже сказано, — худшее, что можно сделать. Спрашивай только если
  об услуге речи не было вовсе.
- Если слова клиента совпадают с названием услуги из списка — это она и есть,
  бери её и не предлагай выбрать между вариантами. «Массаж спины» — это back60;
  услуга на 90 минут называется иначе, «Массаж спины расширенный».
- НЕ подтверждай запись сам и не перечисляй её подробности: точное подтверждение
  с датой, услугой, ценой и мастером отправит система следом за твоим ответом.
  Твой ответ на просьбу записать — одна короткая фраза вроде «Записываю вас».

Про needs_human — ставь его ТОЛЬКО в этих случаях:
- здоровье: клиент жалуется на боль, травму, операцию, беременность, противопоказания;
- скидки и торг, жалоба, конфликт;
- клиент просит ОТМЕНИТЬ или ПЕРЕНЕСТИ запись — этого ты не умеешь. Сюда же
  относится любое «поменяйте», «лучше другое», «а можно на другое время» ПОСЛЕ
  того как запись уже создана: изменить существующую запись ты не можешь, и
  делать вид, что записываешь заново, нельзя.

Этот список ЗАКРЫТ. Ничего сверх него флагом не помечается.

Ставить его НЕ надо, и вот частые ошибки:
- ❌ нужной услуги нет в прайсе → это обычный ответ;
- ❌ клиент просит время, когда салон закрыт → обычный ответ, назови часы;
- ❌ тебе нужно уточнение от клиента → задай вопрос САМ;
- ❌ вопрос кажется необычным, но ответ есть в данных ниже → отвечай;
- ❌ **АБОНЕМЕНТ, включая «хочу купить» и «оформляйте»** → обычный ответ. Назови цену
  и срок из списка абонементов и добавь, что оформит администратор. Флаг тут стёр бы
  ровно то, что клиенту нужно: цену он бы не увидел.

⚠️ С этим флагом твой текст клиенту НЕ уходит вообще: вместо него уйдёт
«передала администратору». Клиент не увидит ни твоего ответа, ни твоего вопроса.
Поэтому флаг — это про «нужен живой человек», а не про «мне неудобно отвечать».

⚠️ Название услуги — НЕ медицинский вопрос. «Массаж шеи и плеч», «массаж спины»,
«массаж стоп» — это позиции прайса, часть тела в названии ничего не значит.
Медицина начинается там, где клиент говорит о своём состоянии: «болит шея»,
«после операции». «Хочу массаж шеи» — обычный заказ, отвечай и записывай.

Про подмену услуги — самое частое, чем ты можешь навредить:
- Записывай РОВНО ту услугу и РОВНО то время, о которых шла речь в последних
  сообщениях. Клиент сказал «да» — значит он согласился на то, что ты назвала
  перед этим, а не на что-то другое.
- Ни длительность, ни услугу, ни мастера в момент записи менять нельзя. Назвала
  «массаж шеи и плеч 30 мин в 20:30» — записывай именно это.
- Если сомневаешься, что именно записать, спроси. Записать не то — хуже, чем
  переспросить.

Если спросят, бот ты или человек — отвечай честно: ты цифровой помощник салона,
администратор подключится, если понадобится. Никогда не выдавай себя за человека.

Диагнозы и медицинские советы не даёшь никогда.
"""


def _день_словами(д: date, сегодня: date) -> str:
    разница = (д - сегодня).days
    if разница == 0:
        return "сегодня"
    if разница == 1:
        return "завтра"
    if разница == 2:
        return "послезавтра"
    return д.strftime("%d.%m")


НАПОМИНАНИЯ_ВКЛЮЧЕНЫ = """\
- Про напоминания сам не пиши: система скажет о них в подтверждении записи.
"""


def собрать(
    салон, сегодня: date, дней_вперёд: int = 3, *, напоминания: bool = True,
    сейчас_минут: int | None = None,
) -> str:
    """Системный промпт целиком.

    `напоминания` управляет одной строкой поведения. Обещать напоминания,
    когда их рассылка выключена, нельзя: это ровно тот класс ошибки, за
    которым мы гоняемся весь этап — обещание, которого система не выполнит.
    """
    ч: list[str] = [ПОВЕДЕНИЕ]
    if напоминания:
        ч.append(НАПОМИНАНИЯ_ВКЛЮЧЕНЫ)
    ч.append("")

    инфо = салон.инфо
    ч.append("# Салон")
    ч.append(f"{инфо.get('название', '')}, {инфо.get('адрес', '')}")
    ч.append(f"Часы работы: {инфо.get('часы', '')}. {инфо.get('как_найти', '')}")
    ч.append("")

    ч.append("# Услуги и цены (других цен не существует)")
    for u in салон.услуги:
        ч.append(f"- {u.название}, {u.длительность} мин — {u.цена} ₾ (id: {u.id})")
    ч.append("")

    if салон.абонементы:
        ч.append("# Абонементы")
        for a in салон.абонементы:
            ч.append(
                f"- {a['название']}: {a['цена']} ₾, "
                f"действует {a['срок_дней']} дней"
            )
        ч.append("")

    ч.append("# Мастера")
    for m in салон.мастера:
        пол = "женщина" if m.пол == "ж" else "мужчина"
        ч.append(f"- {m.имя} ({пол}, id: {m.id}), смена {m.часы}")
    ч.append("")

    if салон.правила:
        ч.append("# Правила")
        ч.extend(f"- {r}" for r in салон.правила)
        ч.append("")

    ч.append("# Свободное время (другого свободного времени нет)")
    ч.append(f"Сегодня {сегодня.strftime('%d.%m.%Y')}.")
    пусто_везде = True
    # `свободные_окна` возвращает словарь по ИМЕНИ мастера, а booking требует id
    id_по_имени = {м.имя: м.id for м in салон.мастера}
    for i in range(дней_вперёд):
        д = сегодня + timedelta(days=i)
        строки: list[str] = []
        не_раньше = сейчас_минут if i == 0 else None
        for u in салон.услуги:
            окна = салон.свободные_окна(д, u.длительность, не_раньше=не_раньше)
            if not окна:
                continue
            for имя, времена in окна.items():
                строки.append(
                    # id рядом с именем намеренно: пока он был только в блоке
                    # «Мастера» тысячей символов выше, модель сшивала два блока и
                    # ошибалась — в тексте писала «Мариам», а в booking клала id 3
                    # (Гиорги, который в пятницу не работает). Клиент получал
                    # «записать не получилось» на верную по смыслу просьбу.
                    f"  {u.длительность} мин, {имя} (id {id_по_имени[имя]}): "
                    f"{', '.join(времена)}"
                )
        # одинаковые сетки по длительности схлопываем, чтобы не раздувать промпт
        уникальные = sorted(set(строки))
        if уникальные:
            пусто_везде = False
            ч.append(f"{_день_словами(д, сегодня)} ({д.strftime('%d.%m')}):")
            ч.extend(уникальные)
    if пусто_везде:
        ч.append("Свободных окон на ближайшие дни нет — предложи связаться с администратором.")
    ч.append("")

    return "\n".join(ч)


def свободные_времена(салон, сегодня: date, дней_вперёд: int = 3) -> set[str]:
    """Времена, на которые МОЖНО ЗАПИСАТЬ.

    Только настоящие свободные окна. Это множество узкое намеренно: по нему
    Booker решает, предлагали ли мы время, и добавлять сюда что-либо — значит
    разрешать запись.
    """
    итог: set[str] = set()
    for i in range(дней_вперёд):
        д = сегодня + timedelta(days=i)
        for u in салон.услуги:
            for времена in салон.свободные_окна(д, u.длительность).values():
                итог.update(времена)
    return итог


def часы_салона(салон) -> set[str]:
    """Границы рабочего дня из прайса, например {'10:00', '21:00'}.

    Их НАЗЫВАТЬ можно — это факт из данных, ровно как цена. ЗАПИСАТЬ на них
    нельзя: 21:00 — момент закрытия.
    """
    сырое = str(салон.инфо.get("часы", "") or "")
    итог: set[str] = set()
    for кусок in сырое.replace("—", "-").split("-"):
        кусок = кусок.strip()
        if _ЧАСЫ.fullmatch(кусок):
            ч, м = кусок.split(":")
            итог.add(f"{ч.zfill(2)}:{м}")
    return итог


def окна(
    салон, сегодня: date, дней_вперёд: int = 3, сейчас_минут: int | None = None
) -> guards.Окна:
    """Свободные времена ПО ДНЯМ плюс метки дней — для заслона времени.

    Метки берутся из того же `_день_словами`, которым промпт печатает дни, и
    дополняются датой «ДД.ММ»: модель пишет то, что видит, а видит она обе
    формы. Один источник вокабуляра, иначе заслон и промпт разойдутся (§17).
    """
    по_дням: dict[int, frozenset[str]] = {}
    метки: dict[str, int] = {}
    for i in range(дней_вперёд):
        д = сегодня + timedelta(days=i)
        времена: set[str] = set()
        # прошедшее время отбрасываем только у сегодняшнего дня
        не_раньше = сейчас_минут if i == 0 else None
        for u in салон.услуги:
            окна_дня = салон.свободные_окна(д, u.длительность, не_раньше=не_раньше)
            for список in окна_дня.values():
                времена.update(список)
        по_дням[i] = frozenset(времена)
        метки[_день_словами(д, сегодня)] = i
        метки[д.strftime("%d.%m")] = i
        метки[д.strftime("%d.%m.%Y")] = i
    return guards.Окна(
        по_дням=по_дням, метки=метки, часы=frozenset(часы_салона(салон))
    )
