"""Sender — единственная точка выхода.

Модель не умеет отправлять. Она возвращает текст, отправляет только Sender.
Все заслоны живут внутри него, поэтому их нельзя обойти, дописав вызов в стороне.

Ни один модуль, кроме aiconic/tg.py, не работает с Telegram напрямую.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from . import guards, handover
from .llm import Ответ

ШАБЛОН_АДМИНУ = (
    "Передала ваш вопрос администратору — он ответит совсем скоро."
)
ШАБЛОН_НЕ_ТЕКСТ = (
    "Голосовые и файлы я пока не разбираю. Напишите, пожалуйста, текстом — "
    "и я сразу отвечу."
)
# Ответ «записала вас» уже ушёл, а запись не создалась: окно успели занять,
# либо модель назвала время, которого мы не предлагали. Молчать здесь нельзя —
# клиент будет считать себя записанным. Текст фиксированный: ни цен, ни времени,
# ни обязательств, поэтому выдумать в нём нечего.
ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА = (
    "Прошу прощения — записать на это время не получилось. Передала "
    "администратору, он свяжется с вами и подберёт ближайшее свободное."
)


class Транспорт(Protocol):
    async def отправить(self, чат_id: int, текст: str) -> None: ...


@dataclass
class Решение:
    отправлено: bool
    причина: str = ""
    текст: str | None = None
    администратору: bool = False


class Sender:
    def __init__(
        self,
        транспорт: Транспорт,
        салон,
        *,
        белый_список: set[int],
        лимит: guards.Лимит | None = None,
        файл_выключателя: Path | None = None,
        лог=None,
        передачи=None,
    ) -> None:
        self.транспорт = транспорт
        self.салон = салон
        self.белый_список = set(белый_список)
        self.лимит = лимит or guards.Лимит()
        self.файл_выключателя = файл_выключателя
        self.лог = лог
        # `передачи` необязательны: без окна администратора этап 1 работает
        # ровно как раньше. Это флаг из §14 в самой конструкции, а не в if.
        self.передачи = передачи

    # --- общие заслоны для любой отправки ---

    def _базовый_отказ(self, чат_id: int, сейчас: float) -> str | None:
        if self.выключено():
            return "kill switch включён"
        if чат_id not in self.белый_список:
            return "чат не в белом списке"
        if not self.лимит.разрешено(чат_id, сейчас):
            return "превышен лимит ответов"
        return None

    def выключено(self) -> bool:
        return bool(self.файл_выключателя and self.файл_выключателя.exists())

    # --- отправка ответа модели ---

    async def отправить_ответ(
        self,
        чат_id: int,
        ответ: Ответ,
        *,
        окна: guards.Окна,
        сказал_клиент: str = "",
        админ_ответил: bool = False,
        сейчас: float | None = None,
    ) -> Решение:
        сейчас = time.monotonic() if сейчас is None else сейчас

        отказ = self._базовый_отказ(чат_id, сейчас)
        if отказ:
            return self._записать(Решение(False, отказ))

        if админ_ответил:
            return self._записать(Решение(False, "администратор ответил раньше"))

        if ответ.needs_human:
            return await self._администратору(
                чат_id, f"модель просит человека: {ответ.reason}", сейчас,
                код=handover.МОДЕЛЬ_ПРОСИТ,
            )

        текст = (ответ.reply or "").strip()
        if not текст:
            return self._записать(Решение(False, "пустой ответ модели"))

        # Заслон от выдуманной цены
        лишние_цены = guards.выдуманные_цены(текст, self.салон.все_цены())
        if лишние_цены:
            return await self._администратору(
                чат_id, f"в ответе цены не из прайса: {лишние_цены}", сейчас,
                код=handover.ЗАСЛОН_ЦЕНЫ,
            )

        # Заслон от выдуманного свободного времени — С УЧЁТОМ ДНЯ.
        # Склеенное по дням множество пропускало «сегодня в 20:30», когда
        # 20:30 свободно только завтра.
        лишнее_время = guards.выдуманное_время(текст, окна, сказал_клиент)
        if лишнее_время:
            return await self._администратору(
                чат_id, f"в ответе время не из свободных окон: {лишнее_время}", сейчас,
                код=handover.ЗАСЛОН_ВРЕМЕНИ,
            )

        # Заслон от выдуманного условия: денежное или обязывающее утверждение,
        # которого нет в правилах салона. Двое предыдущих заслонов к таким
        # фразам слепы — в них нет ни цены, ни времени.
        лишние_условия = guards.выдуманные_условия(текст, self.салон.правила)
        if лишние_условия:
            return await self._администратору(
                чат_id,
                f"в ответе условия не из правил: {лишние_условия}",
                сейчас,
                код=handover.ЗАСЛОН_УСЛОВИЙ,
            )

        await self.транспорт.отправить(чат_id, текст)
        self.лимит.отметить(чат_id, сейчас)
        return self._записать(Решение(True, "ответ модели", текст))

    # --- отправка фиксированного шаблона (модель не участвует) ---

    async def отправить_шаблон(
        self, чат_id: int, текст: str, *, причина: str = "шаблон", сейчас: float | None = None
    ) -> Решение:
        сейчас = time.monotonic() if сейчас is None else сейчас
        отказ = self._базовый_отказ(чат_id, сейчас)
        if отказ:
            return self._записать(Решение(False, отказ))
        await self.транспорт.отправить(чат_id, текст)
        self.лимит.отметить(чат_id, сейчас)
        return self._записать(Решение(True, причина, текст))

    async def _администратору(
        self, чат_id: int, причина: str, сейчас: float, *, код: str
    ) -> Решение:
        """Клиенту уходит нейтральный шаблон, не текст модели.

        Здесь же ставится метка для окна администратора. Место выбрано не
        случайно: все эскалации выхода сходятся в этот метод, значит метка и
        решение передать человеку принимаются ОДНИМ куском кода и разойтись не
        могут (§17). В метку идёт `код`, а не `причина`: причина — свободный
        текст, в котором окажется цитата клиента, а в переписке бывают данные
        о здоровье.
        """
        await self.транспорт.отправить(чат_id, ШАБЛОН_АДМИНУ)
        self.лимит.отметить(чат_id, сейчас)
        self.отметить_передачу(чат_id, код)
        return self._записать(
            Решение(True, причина, ШАБЛОН_АДМИНУ, администратору=True)
        )

    # --- метка «нужен ответ» ---

    def отметить_передачу(self, чат_id: int, код: str) -> None:
        """Поставить метку, если окно администратора вообще подключено."""
        if self.передачи is None:
            return
        self.передачи.открыть(чат_id, код)

    # --- второй выход: пишет ЧЕЛОВЕК, а не модель ---

    async def отправить_от_админа(
        self, чат_id: int, текст: str, *, сейчас: float | None = None
    ) -> Решение:
        """Ответ администратора из окна. ⚠️ Заслонов здесь МЕНЬШЕ — намеренно.

        §26 требует не выдавать одно за другое, поэтому прямо: это второй выход,
        и он слабее первого. Что проверяется и что нет:

        | заслон          | модель | человек | почему                            |
        |-----------------|--------|---------|-----------------------------------|
        | белый список    |   ✅   |   ✅    | защита от письма не тому чату     |
        | файл STOP       |   ✅   |   ❌    | человек нажал «отправить» осознанно |
        | лимит частоты   |   ✅   |   ❌    | человек печатает медленнее лимита |
        | цены/время/условия | ✅  |   ❌    | это заслоны от выдумки МОДЕЛИ     |

        Администратор вправе дать скидку и назвать условие, которого нет в
        правилах: он их и устанавливает. Прогонять его слова через заслон от
        галлюцинаций значило бы блокировать законный ответ.

        Метка снимается здесь же: человек ответил — окно больше не требует
        ответа. Открытие и снятие живут в одном классе, чтобы не разъехались.
        """
        сейчас = time.monotonic() if сейчас is None else сейчас
        текст = (текст or "").strip()
        if not текст:
            return self._записать(Решение(False, "администратор: пустой текст"))
        if чат_id not in self.белый_список:
            # Единственный заслон, который остаётся: письмо не тому чату
            # необратимо, и осознанность нажатия от этого не спасает.
            return self._записать(
                Решение(False, "администратор: чат не в белом списке")
            )
        await self.транспорт.отправить(чат_id, текст)
        if self.передачи is not None:
            self.передачи.снять(чат_id)
        return self._записать(Решение(True, "ответ администратора", текст))

    def _записать(self, р: Решение) -> Решение:
        if self.лог:
            self.лог.решение(р)
        return р
