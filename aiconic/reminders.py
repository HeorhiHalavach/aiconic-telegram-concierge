"""Напоминания о визите: за день и за 2 часа.

⚠️ Это ПЕРВОЕ в проекте, что система отправляет ПЕРВОЙ. До сих пор она умела
только отвечать. Напоминание привязано к существующей записи — именно эту
категорию правила Telegram называют допустимой, в отличие от реактивации и
рассылок, которых здесь нет и не будет.

Здесь только чистые функции: что и когда пора отправить. Ни сети, ни часов
внутри — «сейчас» приходит аргументом, поэтому всё проверяемо без ожидания.

Гашение переживает перезапуск процесса: отметка лежит в самой записи, в
bookings.yaml. Флаг в памяти процесса гарантией не был бы — упал, поднялся,
напомнил второй раз.
"""

from __future__ import annotations

from datetime import date, datetime, time, timedelta, timezone

# Часовой пояс салона объявлен в salon.py: это его свойство. Здесь реэкспорт,
# чтобы не было двух источников одной константы (§17).
from .salon import ЗОНА_САЛОНА  # noqa: E402

ЗА_ДЕНЬ = "за_день"
ЗА_2_ЧАСА = "за_2_часа"
СДВИГИ = {ЗА_ДЕНЬ: timedelta(days=1), ЗА_2_ЧАСА: timedelta(hours=2)}

# Порядок важен: если созрели оба, отправляем только ближайшее к визиту.
ВИДЫ = (ЗА_ДЕНЬ, ЗА_2_ЧАСА)


def начало_визита(запись: dict) -> datetime | None:
    """Момент начала визита в UTC. None — если дата или время битые."""
    try:
        д = date.fromisoformat(str(запись["дата"]))
        ч, м = (int(x) for x in str(запись["начало"]).split(":"))
        местное = datetime.combine(д, time(ч, м), tzinfo=ЗОНА_САЛОНА)
    except (KeyError, ValueError, TypeError):
        return None
    return местное.astimezone(timezone.utc)


def момент(запись: dict, вид: str) -> datetime | None:
    """Когда пора отправить напоминание данного вида, в UTC."""
    начало = начало_визита(запись)
    if начало is None or вид not in СДВИГИ:
        return None
    return начало - СДВИГИ[вид]


def созревшие(записи, сейчас: datetime) -> list[tuple[int, str, list[str]]]:
    """Что пора отправить прямо сейчас.

    Возвращает список (индекс записи, вид к отправке, виды к гашению).

    Правила, каждое из них — заслон от конкретной глупости:

    - момент прошёл, визит ещё не начался → пора. Иначе после суточного
      простоя процесс разослал бы напоминания о вчерашних визитах;
    - на одну запись за раз — одно напоминание. Созрели оба (процесс лежал) —
      уходит только ближайшее к визиту, дальнее гасится без отправки: два
      сообщения подряд выглядят как сбой;
    - уже отмеченное не отправляется повторно;
    - визит начался → все виды гасятся молча.
    """
    if сейчас.tzinfo is None:
        raise ValueError("«сейчас» обязано быть tz-aware: местное и UTC смешивать нельзя")

    итог: list[tuple[int, str, list[str]]] = []
    for i, з in enumerate(записи):
        начало = начало_визита(з)
        if начало is None:
            continue
        уже = set(з.get("напомнили") or [])

        осталось = [в for в in ВИДЫ if в not in уже]
        if not осталось:
            continue

        if сейчас >= начало:
            # Визит начался или прошёл — напоминать нечего, гасим тихо.
            итог.append((i, "", осталось))
            continue

        созрели = [в for в in осталось if (м := момент(з, в)) and сейчас >= м]
        if not созрели:
            continue

        # ближайшее к визиту = последнее в ВИДЫ
        к_отправке = созрели[-1]
        итог.append((i, к_отправке, созрели))
    return итог


def текст(запись: dict, вид: str, услуга_название: str, мастер_имя: str) -> str:
    """Текст напоминания. Фиксированный — модель тут не участвует.

    Модель к напоминаниям не подпускается намеренно: это сообщение уходит
    первым, проверить его перед отправкой некому, а выдумать условие она
    уже умеет.
    """
    когда = "завтра" if вид == ЗА_ДЕНЬ else "через 2 часа"
    return (
        f"Напоминаем: {когда} в {запись['начало']} у вас {услуга_название}, "
        f"мастер {мастер_имя}. Если планы изменились — напишите, перенесём."
    )
