"""Дирижёр: приём → контекст → заслон → модель → Sender.

Никакого Telegram здесь нет: на входе обычные данные, на выходе решение.
Поэтому весь этот файл проверяется тестами без живого аккаунта.
"""

from __future__ import annotations

import asyncio
import json
from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from pathlib import Path

from . import guards, prompt
from . import handover
from .booker import Booker, ЗаписьОтклонена, ЗаписьУжеЕсть
from .salon import ЗОНА_САЛОНА
from .llm import ОшибкаПровайдера, Ответ
from .salon import минут_сейчас as салон_минут
from .sender import ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА, ШАБЛОН_НЕ_ТЕКСТ, Sender


@dataclass
class Входящее:
    чат_id: int
    текст: str
    дата: datetime
    личный: bool = True
    исходящее: bool = False
    есть_вложение: bool = False
    автор: str = ""
    # ⚠️ Догоняющее сообщение: пришло, пока процесс лежал. Отсечка «старше
    # запуска» для него не применяется — иначе клиент, написавший ночью,
    # не получит ответа никогда. Ставит этот флаг ТОЛЬКО функция добора при
    # старте (main.догнать), и только для чатов, где последнее слово за
    # клиентом, то есть мы точно ещё не отвечали.
    догоняем: bool = False


@dataclass
class Лог:
    """Промпт и ответ целиком — без этого этап не даёт доказательств."""

    путь: Path | None = None
    записи: list[dict] = field(default_factory=list)

    def _пиши(self, событие: dict) -> None:
        событие["ts"] = datetime.now(timezone.utc).isoformat()
        self.записи.append(событие)
        if self.путь:
            self.путь.parent.mkdir(parents=True, exist_ok=True)
            with open(self.путь, "a", encoding="utf-8") as f:
                f.write(json.dumps(событие, ensure_ascii=False) + "\n")

    def запрос(self, чат_id: int, системный: str, сообщения: list[dict]) -> None:
        self._пиши({"вид": "запрос", "чат": чат_id,
                    "системный": системный, "сообщения": сообщения})

    def ответ(self, чат_id: int, о: Ответ) -> None:
        self._пиши({"вид": "ответ", "чат": чат_id, "reply": о.reply,
                    "needs_human": о.needs_human, "reason": о.reason,
                    "booking": о.booking})

    def решение(self, р) -> None:
        self._пиши({"вид": "решение", "отправлено": р.отправлено,
                    "причина": р.причина, "администратору": р.администратору,
                    "текст": р.текст})

    def пропуск(self, чат_id: int, причина: str, автор: str = "") -> None:
        self._пиши({"вид": "пропуск", "чат": чат_id,
                    "причина": причина, "автор": автор})


class Дирижёр:
    def __init__(
        self,
        *,
        салон,
        провайдер,
        sender: Sender,
        приём: guards.Приём,
        лог: Лог,
        история,
        сегодня=None,
        сейчас_минут=None,
        глубина_истории: int = 20,
        передачи=None,
        пауза_группировки: float = 2.5,
        напоминания: bool = True,
    ) -> None:
        self.салон = салон
        self.провайдер = провайдер
        self.sender = sender
        self.приём = приём
        self.лог = лог
        self.история = история          # callable(чат_id, n) -> list[dict]
        self._сегодня = сегодня or (lambda: date.today())
        # Прошедшее время не свободно. Часы знает дирижёр: салон про них не
        # спрашивает, а Booker получает значение аргументом.
        self._сейчас_минут = сейчас_минут or салон_минут
        self.глубина = глубина_истории
        # Один экземпляр на процесс: окно и дирижёр обязаны видеть
        # одну и ту же метку, иначе их списки в памяти разойдутся.
        self._передачи = передачи
        self.пауза = пауза_группировки
        # Обещать напоминания можно только когда их рассылка включена.
        self.напоминания = напоминания
        self.booker = Booker(салон)
        self._пачки: dict[int, list[Входящее]] = {}
        self._таймеры: dict[int, asyncio.Task] = {}
        # что мы сами предлагали в каждом чате — основа заслона записи
        self._предлагали: dict[int, set[str]] = {}

    # --- приём и группировка ---

    async def принять(self, вх: Входящее) -> None:
        причина = self.приём.причина_отказа(
            чат_id=вх.чат_id, личный=вх.личный,
            исходящее=вх.исходящее, дата=вх.дата,
            догоняем=вх.догоняем,
        )
        if причина:
            # в режиме наблюдения логируем всех, кто написал, но не отвечаем
            if self.приём.режим_наблюдения or причина == "чат не в белом списке":
                self.лог.пропуск(вх.чат_id, причина, вх.автор)
            else:
                self.лог.пропуск(вх.чат_id, причина)
            return

        self._пачки.setdefault(вх.чат_id, []).append(вх)
        старый = self._таймеры.get(вх.чат_id)
        if старый and not старый.done():
            старый.cancel()
        self._таймеры[вх.чат_id] = asyncio.create_task(self._после_паузы(вх.чат_id))

    async def _после_паузы(self, чат_id: int) -> None:
        try:
            await asyncio.sleep(self.пауза)
        except asyncio.CancelledError:
            return
        await self.обработать(чат_id)

    # --- обработка пачки ---

    async def обработать(self, чат_id: int) -> None:
        пачка = self._пачки.pop(чат_id, [])
        if not пачка:
            return

        # ⚠️ Разговор передан человеку — бот молчит. Иначе клиент получит два
        # ответа: слова администратора и поверх них ответ модели, которая про
        # эти слова ничего не знает. Заслон стоит ДО всего остального, включая
        # вызов модели: платить за ответ, который нельзя отправлять, незачем.
        передача = self._передачи.открытая(чат_id) if self._передачи else None
        if передача:
            self.лог.пропуск(
                чат_id, f"разговор у администратора ({передача.код}) — не отвечаем"
            )
            return

        # Нетекстовое: голосовые в салонных чатах — норма, а текста в них нет.
        текст = " ".join(m.текст.strip() for m in пачка if (m.текст or "").strip())
        if not текст:
            await self.sender.отправить_шаблон(
                чат_id, ШАБЛОН_НЕ_ТЕКСТ, причина="нетекстовое сообщение"
            )
            return

        # Заслон до модели: медицина и спам.
        триггер = guards.медицинский_триггер(текст)
        if триггер:
            self.лог.пропуск(чат_id, f"медицинский триггер: {триггер}")
            # Метка нужна и здесь: этот путь идёт МИМО Sender._администратору
            # (модель не вызывается вовсе), а для администратора это точно
            # такая же передача. В метку идёт код, слово-триггер туда не едет.
            self.sender.отметить_передачу(чат_id, handover.МЕДИЦИНА)
            await self.sender.отправить_шаблон(
                чат_id,
                "Такой вопрос лучше обсудить с администратором — передала ему, "
                "он свяжется с вами.",
                причина=f"медицинский триггер: {триггер}",
            )
            return

        мусор = guards.спам(текст)
        if мусор:
            self.лог.пропуск(чат_id, f"спам: {мусор}")
            return

        сегодня = self._сегодня()
        сейчас_минут = self._сейчас_минут()
        системный = prompt.собрать(
            self.салон, сегодня, напоминания=self.напоминания,
            сейчас_минут=сейчас_минут,
        )
        # Окна разложены ПО ДНЯМ: заслон времени обязан знать, про какой день
        # говорит модель, иначе «сегодня в 20:30» пройдёт из-за завтрашнего
        # окна. Отдельно `записываемые` — плоское множество без часов работы,
        # по нему Booker решает, можно ли записать.
        окна = prompt.окна(self.салон, сегодня, сейчас_минут=сейчас_минут)
        записываемые = окна.записываемые()

        # Время, которое клиент назвал САМ, — законное основание для записи:
        # он его выбрал, показывать ему это время повторно не нужно.
        # Пересечение с «записываемые» обязательно: «запишите на 23:00» так
        # записью не станет, а свободность всё равно проверит Booker.
        просил_сам = {
            f"{h.zfill(2)}:{m}" for h, m in guards._ВРЕМЯ.findall(текст)
        } & записываемые
        if просил_сам:
            self._предлагали.setdefault(чат_id, set()).update(просил_сам)

        сообщения = self._собрать_историю(чат_id, текст, сегодня)

        self._восстановить_предложенное(чат_id, сообщения, записываемые)
        self.лог.запрос(чат_id, системный, сообщения)

        try:
            ответ = self.провайдер.ответить(системный, сообщения)
        except ОшибкаПровайдера as e:
            # Клиенту НИЧЕГО не отправляем: мусор хуже молчания.
            self.лог.пропуск(чат_id, f"провайдер недоступен: {e}")
            return

        self.лог.ответ(чат_id, ответ)

        решение = await self.sender.отправить_ответ(
            чат_id,
            ответ,
            окна=окна,
            сказал_клиент=текст,
            админ_ответил=self._админ_ответил(чат_id, пачка[-1]),
        )

        if решение.отправлено and not решение.администратору:
            # ПОРЯДОК НЕСУЩИЙ. Сначала запись, потом пополнение списка
            # предложенных — иначе время, названное в ЭТОМ же ответе, само
            # себе выдаёт разрешение, и «предложили → подтвердили»
            # превращается в «предложили → записали».
            # Живой случай 2026-08-13: клиент спросил цену, модель ответила
            # «предлагаю 13:00» и в том же ходу создала запись.
            await self._может_записать(
                чат_id, ответ, сегодня, сейчас_минут, просил=текст
            )

            # Запомнили, какие времена мы сами назвали — заслон записи.
            # Отсечка по «записываемые» обязательна: в тексте законно может
            # стоять 21:00 из часов работы, но записать на закрытие нельзя.
            назвали = {
                f"{h.zfill(2)}:{m}"
                for h, m in guards._ВРЕМЯ.findall(решение.текст or "")
            }
            self._предлагали.setdefault(чат_id, set()).update(
                назвали & записываемые
            )

    # --- запись ---

    @staticmethod
    def _с_датой(текст: str, когда, сегодня: date | None) -> str:
        """Сообщение не из сегодня получает дату в начале: «(12.08) …».

        ⚠️ Зачем. Вчера мы написали «свободно ЗАВТРА в 13:00». Сегодня модель
        читает эту строку в истории и видит в системном промпте «Сегодня
        13.08» — то есть считает, что речь про 14-е. Проверено пробой: у
        сообщений истории не было ни одного признака даты, и ошибиться модель
        была обязана.

        Датируем ТОЛЬКО чужие дни. Сегодняшние сообщения оставляем как есть:
        лишняя дата в каждой строке раздувает промпт, а он уходит с каждым
        запросом и это 90% стоимости.

        Сравнение идёт в местном времени салона: дата сообщения приходит в UTC,
        и около полуночи «сегодня по UTC» и «сегодня в Тбилиси» — разные дни.
        """
        if не_дата := (когда is None or сегодня is None):
            return текст
        try:
            местное = когда.astimezone(ЗОНА_САЛОНА).date()
        except (AttributeError, ValueError, TypeError):
            return текст
        if местное == сегодня:
            return текст
        return f"({местное.strftime('%d.%m')}) {текст}"

    async def _может_записать(
        self, чат_id: int, ответ: Ответ, сегодня: date,
        сейчас_минут: int | None = None, просил: str = "",
    ) -> None:
        """Пытается создать запись, которую пообещала модель.

        ⚠️ Ответ клиенту в этот момент УЖЕ УШЁЛ, и в нём, скорее всего, стоит
        «записала вас». Поэтому любой отказ обязан дойти до клиента — иначе он
        считает себя записанным, а записи нет. Раньше это был только лог, то
        есть отчёт вместо заслона (§26).

        Исключение — дубль: там клиент записан по-настоящему, и подтверждение,
        которое он прочитал, — правда. Говорить ему «не получилось» было бы
        хуже молчания.
        """
        b = ответ.booking
        if not b:
            return
        try:
            день = date.fromisoformat(str(b["дата"]))
        except (ValueError, KeyError, TypeError):
            # Модель отдала дату не по ISO — записи нет, а клиент уже прочитал
            # подтверждение. Это тот же случай, что отказ заслона.
            self.лог.пропуск(чат_id, f"плохая дата в booking: {b!r}")
            await self._сказать_что_не_вышло(чат_id, f"плохая дата: {b!r}", просил)
            return
        try:
            запись = await self.booker.записать(
                чат=чат_id,
                день=день,
                время=str(b.get("время", "")),
                мастер_id=int(b.get("мастер", 0)),
                услуга_id=str(b.get("услуга", "")),
                предложенные=sorted(self._предлагали.get(чат_id, set())),
                не_раньше=сейчас_минут if день == сегодня else None,
            )
            self.лог.пропуск(чат_id, f"записан: {запись.дата} {запись.начало}")
            await self._подтвердить(чат_id, запись, сегодня)
        except ЗаписьУжеЕсть as e:
            # Клиент записан — «не получилось» было бы ложью. Но и молчать нельзя:
            # имитация 13.08 показала, как на повторную просьбу модель второй раз
            # отвечает «Записываю вас», и клиент не понимает, записан он один раз
            # или два. Говорим прямо, на что он уже записан, — текст строит КОД.
            self.лог.пропуск(чат_id, f"запись уже есть: {e}")
            await self._сказать_что_уже_записан(
                чат_id, e.существующая, сегодня, просил
            )
        except ЗаписьОтклонена as e:
            self.лог.пропуск(чат_id, f"запись отклонена: {e}")
            await self._сказать_что_не_вышло(чат_id, f"запись отклонена: {e}", просил)

    def _словами(self, дата: str, начало: str, услуга_id: str,
                 мастер_id: int, сегодня: date) -> str:
        """«завтра в 13:00, Массаж спины, 60 мин — 120 ₾, мастер Нино».

        Один сборщик на подтверждение и на «вы уже записаны»: две копии этой
        строки разошлись бы, а клиент читает их как одно и то же (§17).
        """
        услуга = self.салон.услуга(услуга_id)
        мастер = self.салон.мастер(мастер_id)
        день = prompt._день_словами(date.fromisoformat(дата), сегодня)
        части = [
            f"{день} в {начало}",
            f"{услуга.название}, {услуга.длительность} мин — {услуга.цена} ₾"
            if услуга else "визит",
        ]
        if мастер:
            части.append(f"мастер {мастер.имя}")
        return ", ".join(части)

    async def _сказать_что_уже_записан(
        self, чат_id: int, существующая: dict, сегодня: date, просил: str = ""
    ) -> None:
        """Повторная просьба записать на занятое собой же время.

        Условие то же, что у поправки: молчим, если клиент записи не просил, —
        непрошеное «вы уже записаны» такой же шум, как непрошеное извинение.
        """
        if not существующая:
            return
        if просил and not guards.просил_записать(просил):
            self.лог.пропуск(чат_id, "дубль, но клиент записи не просил — молчим")
            return
        строка = self._словами(
            str(существующая.get("дата", "")), str(существующая.get("начало", "")),
            str(существующая.get("услуга", "")), int(существующая.get("мастер", 0)),
            сегодня,
        )
        await self.sender.отправить_шаблон(
            чат_id, f"Вы уже записаны: {строка}. Ждём вас!",
            причина="клиент уже записан на это время",
        )

    async def _сказать_что_не_вышло(
        self, чат_id: int, причина: str, просил: str = ""
    ) -> None:
        """Поправка нужна, только если клиент МОГ ПОВЕРИТЬ, что записан.

        ⚠️ Имитация 2026-08-14: клиент написал «?», модель сама предложила
        14:00 и в том же ходу попыталась записать. Заслон верно отказал, но
        клиент получил «записать не получилось», хотя ни о чём не просил.
        Извинение на пустом месте пугает не меньше, чем молчание после
        настоящего отказа.

        Модель забежала вперёд — пишем в лог и молчим.
        """
        if просил and not guards.просил_записать(просил):
            self.лог.пропуск(
                чат_id, f"{причина} — клиент записи не просил, поправку не шлём"
            )
            return
        self.sender.отметить_передачу(чат_id, handover.ЗАПИСЬ_НЕ_ВЫШЛА)
        await self.sender.отправить_шаблон(
            чат_id, ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА, причина=причина
        )

    async def _подтвердить(self, чат_id: int, запись, сегодня: date) -> None:
        """Подтверждение строит КОД из созданной записи, а не модель.

        Модель в подтверждениях врала на живых прогонах: «14:08» вместо 14.08,
        «14.08.2026» вместо ISO, чужой мастер. Здесь каждое значение взято из
        того, что реально записано в файл, поэтому соврать нечем.

        Идёт через `отправить_шаблон`, то есть БЕЗ сверки цен и времени. Так и
        нужно: сразу после записи это время уже занято — своей же записью, — и
        заслон времени пометил бы верное подтверждение как выдуманное.
        """
        строка = self._словами(
            запись.дата, запись.начало, запись.услуга, запись.мастер, сегодня
        )
        текст = f"Готово, вы записаны: {строка}."
        if self.напоминания:
            текст += " Напомним за день и за 2 часа до визита."
        await self.sender.отправить_шаблон(
            чат_id, текст, причина=f"подтверждение записи {запись.дата} {запись.начало}"
        )

    # --- контекст ---

    def _восстановить_предложенное(
        self, чат_id: int, сообщения: list[dict], записываемые: set[str]
    ) -> None:
        """Времена, которые МЫ предлагали раньше, — из истории, а не из памяти.

        ⚠️ Без этого клиент, ответивший «да, давайте» на следующий день, получал
        «записать не получилось»: список предложенного жил в памяти процесса и
        умирал с перезапуском. Проверено пробой до починки — дефект
        воспроизводился на настоящем дирижёре.

        Своего состояния не добавляем намеренно: наши прошлые ответы и есть
        запись того, что мы предлагали, а хранилищем переписки служит сам
        Telegram. Второй список разошёлся бы с первым (§17).

        Пересечение с `записываемые` обязательно по двум причинам: в прошлом
        ответе законно могло стоять 21:00 из часов работы, и время, свободное
        вчера, сегодня может быть занято. Свободность всё равно проверит
        `Booker` в момент записи — это второй слой, и он несущий.
        """
        предлагали_раньше = {
            f"{h.zfill(2)}:{m}"
            for м in сообщения if м.get("role") == "assistant"
            for h, m in guards._ВРЕМЯ.findall(м.get("content") or "")
        } & записываемые
        if not предлагали_раньше:
            return
        новые = предлагали_раньше - self._предлагали.get(чат_id, set())
        if новые:
            self.лог.пропуск(
                чат_id, f"предложенное восстановлено из истории: {sorted(новые)}"
            )
        self._предлагали.setdefault(чат_id, set()).update(предлагали_раньше)

    def _собрать_историю(
        self, чат_id: int, текущий: str, сегодня: date | None = None
    ) -> list[dict]:
        """История для модели, ОЧИЩЕННАЯ от того, что модель видеть не должна.

        ⚠️ Живой случай 2026-08-13, найденный только многоходовым диалогом.
        Медицинский заслон не пускает модель на сообщении с триггером — но
        сообщение остаётся в чате Telegram, и на следующем ходу приходит в
        модель уже как история. Последствия были двойные:

        1. Модель залипала: после «болит спина после операции» ВСЕ ответы
           становились про послеоперационную боль, что бы клиент ни спросил.
        2. Медицинский текст всё равно доезжал до внешнего API — а обещание
           заслона было «модель не вызывается вообще» (BLUEPRINT 4.4).

        Заслон, работающий только на текущем сообщении, дырявый по построению:
        Telegram и есть наша память, значит фильтровать надо и её.
        """
        прошлое = self.история(чат_id, self.глубина) or []
        сообщения: list[dict] = []
        for m in прошлое:
            текст = (m.get("текст") or "").strip()
            if not текст:
                continue
            # Направление не важно: медицинские данные не уходят наружу, даже
            # если их набрал руками администратор.
            if guards.медицинский_триггер(текст) or guards.спам(текст):
                self.лог.пропуск(чат_id, "история: сообщение с триггером вырезано")
                continue
            # Наши прошлые ответы, которые сегодня заслон бы НЕ пропустил.
            # В чате остались фразы вроде «позже возврата не будет», сказанные
            # до появления заслона условий: модель их переписывает как образец.
            # Фильтруем историю тем же правилом, что и выход, — только свои
            # сообщения: вопрос клиента «деньги вернутся?» нужен как контекст.
            if m.get("наше") and guards.выдуманные_условия(текст, self.салон.правила):
                self.лог.пропуск(чат_id, "история: свой ответ с выдуманным условием вырезан")
                continue
            сообщения.append(
                {
                    "role": "assistant" if m.get("наше") else "user",
                    "content": self._с_датой(текст, m.get("дата"), сегодня),
                }
            )
        # Текущее сообщение — из сегодня по определению, его не датируем.
        if not сообщения or сообщения[-1]["content"].strip() != текущий.strip():
            сообщения.append({"role": "user", "content": текущий})
        return сообщения

    def _админ_ответил(self, чат_id: int, последнее: Входящее) -> bool:
        """Человек мог ответить руками быстрее модели."""
        прошлое = self.история(чат_id, 3) or []
        for m in reversed(прошлое):
            if m.get("наше"):
                дата = m.get("дата")
                if дата is not None and дата > последнее.дата:
                    return True
            break
        return False
