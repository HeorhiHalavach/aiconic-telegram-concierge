"""Канал связи: то, что окно администратора знает о мессенджерах.

Зачем протокол, если реализация одна. Две причины, и обе настоящие:

1. **Мессенджеров будет несколько** (решение Георгия 2026-08-15). Второй канал
   должен добавляться новым файлом, а не правкой окна.
2. **Заслон границ импортов это уже требует.** `telethon` разрешён только в
   `aiconic/tg.py`, и тест `test_telethon_импортируется_только_в_tg` следит за
   этим во всех вложенных папках. Значит `aiconic/inbox/` физически не может
   спросить Telegram напрямую — только через этот протокол.

⚠️ Абстракция намеренно тонкая: три метода и один плоский объект. «Универсальный
механизм» под один случай был бы таким же костылём, как хак в коде (§12).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol


@dataclass(frozen=True)
class Диалог:
    """Строка ленты. Плоская намеренно: окно не должно знать типов мессенджера.

    `непрочитанных` — счётчик самого мессенджера, он НЕ означает «нужен ответ».
    Это разные признаки, и в ленте они показываются по-разному: непрочитанное
    бывает у чата, который бот уже закрыл сам.
    """

    чат_id: int
    имя: str
    последнее: str
    когда: datetime | None
    непрочитанных: int = 0
    канал: str = "telegram"
    # За кем последнее слово. Единственный надёжный признак «мы ещё не
    # отвечали»: счётчик непрочитанных для этого НЕ годится — мы намеренно не
    # помечаем сообщения прочитанными, поэтому он остаётся большим и после
    # нашего ответа (проверено живьём: 35 непрочитанных в отвеченном чате).
    наше_последним: bool = False


class Канал(Protocol):
    """Что окну нужно от мессенджера — и ничего сверх этого."""

    имя: str

    async def диалоги(self, сколько: int) -> list[Диалог]: ...

    async def история(self, чат_id: int, сколько: int) -> list[dict]: ...

    async def отправить(self, чат_id: int, текст: str) -> None: ...
