"""Расчёт свободных окон. По каждому тесту названа отвергаемая реализация."""

from __future__ import annotations

from datetime import date

from conftest import ЧЕТВЕРГ

ПЯТНИЦА = date(2026, 8, 14)   # Нино и Мариам
ВОСКРЕСЕНЬЕ = date(2026, 8, 16)  # только Гиорги


def test_s1_свободные_окна_есть_и_последнее_влезает(салон):
    """Отвергает реализацию, теряющую последнее окно смены."""
    окна = салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1)  # Нино 10:00-18:00
    assert окна["Нино"][0] == "10:00"
    # последнее окно для 60 мин при смене до 18:00 — 17:00
    assert окна["Нино"][-1] == "17:00"


def test_s2_всё_занято_пусто(салон):
    """Отвергает возвращающую «что-нибудь» вместо пустоты."""
    салон.записи = [
        {"чат": 0, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "10:00", "длительность": 480, "услуга": "back60"}
    ]
    assert салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1) == {}


def test_s3_запись_в_середине_нет_пересечений(салон):
    """Отвергает проверку пересечений с ошибкой в границах."""
    окна = салон.свободные_окна(ЧЕТВЕРГ, 60, мастер_id=1)["Нино"]
    # в bookings.yaml у Нино занято 12:00-13:00 и 15:00-16:30
    for занятое in ("12:00", "12:30", "15:00", "15:30", "16:00"):
        assert занятое not in окна
    assert "11:00" in окна and "13:00" in окна


def test_s4_окно_ровно_к_концу_смены_разрешено(салон):
    """Отвергает `<` вместо `<=` — именно эта мутация ловилась на черновике."""
    окна = салон.свободные_окна(ВОСКРЕСЕНЬЕ, 60, мастер_id=3)  # Гиорги 11:00-19:00
    assert "18:00" in окна["Гиорги"], "окно, кончающееся ровно в 19:00, должно быть"


def test_s5_услуга_длиннее_смены_пусто(салон):
    """Отвергает не проверяющую, что услуга влезает целиком."""
    assert салон.свободные_окна(ПЯТНИЦА, 600, мастер_id=1) == {}


def test_s6_фильтр_по_полу(салон):
    """Отвергает игнорирующую пол мастера."""
    женщины = салон.свободные_окна(ЧЕТВЕРГ, 60, пол="ж")
    assert set(женщины) == {"Нино"}          # в четверг Мариам не работает
    мужчины = салон.свободные_окна(ЧЕТВЕРГ, 60, пол="м")
    assert set(мужчины) == {"Гиорги"}


def test_s7_щель_ровно_равна_услуге(салон):
    """Отвергает добавляющую лишний зазор."""
    салон.записи = [
        {"чат": 0, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "10:00", "длительность": 60, "услуга": "back60"},
        {"чат": 0, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "12:00", "длительность": 360, "услуга": "back60"},
    ]
    assert салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1)["Нино"] == ["11:00"]


def test_s8_щель_короче_услуги(салон):
    """Отвергает не учитывающую длительность услуги."""
    салон.записи = [
        {"чат": 0, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "10:00", "длительность": 60, "услуга": "back60"},
        {"чат": 0, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "11:30", "длительность": 390, "услуга": "back60"},
    ]
    assert салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1) == {}


def test_s9_мастер_не_работает_в_этот_день(салон):
    """Отвергает игнорирующую график: Мариам в четверг не работает."""
    assert "Мариам" not in салон.свободные_окна(ЧЕТВЕРГ, 60)


def test_s10_шаг_сетки_соблюдается(салон):
    окна = салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1)["Нино"]
    минуты = {int(t.split(":")[1]) for t in окна}
    assert минуты <= {0, 30}
