"""Часы работы: назвать можно, записать нельзя.

Написано после живого прогона 2026-08-13. Тогда моя же правка промпта
заставила модель отвечать «мы работаем с 10:00 до 21:00» — верный отказ на
«можно в 23:00?» — а заслон на выдуманное время счёл 21:00 выдумкой и подменил
ответ шаблоном «передала администратору».

Наивная починка (добавить часы в свободные_времена) открыла бы дыру: app.py
запоминает КАЖДОЕ время из отправленного текста как «мы это предлагали», и
Booker пустил бы запись на 21:00 — момент закрытия салона. Поэтому множеств
два, и главный тест здесь — враждебный: test_час_закрытия_нельзя_записать.
"""

from __future__ import annotations

from datetime import date

import pytest
from conftest import ЧЕТВЕРГ, входящее

from aiconic import prompt
from aiconic.booker import Booker, ЗаписьОтклонена
from aiconic.llm import Ответ

ОТКАЗ_С_ЧАСАМИ = "Мы работаем с 10:00 до 21:00. Предлагаю 13:00 сегодня к Нино."


# --- разбор строки часов ---

def test_часы_салона_разбираются(салон):
    assert prompt.часы_салона(салон) == {"10:00", "21:00"}


def test_часы_с_тире_разной_длины(салон):
    """В прайс правит человек: длинное тире вместо дефиса — рядовая опечатка."""
    салон.инфо["часы"] = "10:00 — 21:00"
    assert prompt.часы_салона(салон) == {"10:00", "21:00"}


@pytest.mark.parametrize("мусор", ["", "круглосуточно", None, "10-21"])
def test_мусор_в_часах_не_даёт_ложных_времён(салон, мусор):
    """Пустой набор лучше выдуманного времени: заслон остаётся строгим."""
    салон.инфо["часы"] = мусор
    assert prompt.часы_салона(салон) == set()


def test_называть_можно_шире_чем_записывать_ровно_на_часы(салон):
    о = prompt.окна(салон, ЧЕТВЕРГ)
    записываемые = о.записываемые()
    называемые = о.для_дня(0) | о.для_дня(1) | о.для_дня(2)
    assert называемые - записываемые == {"21:00"}, (
        "21:00 — момент закрытия, его нет ни в одном свободном окне"
    )


def test_час_закрытия_не_попал_в_записываемые(салон):
    """Прямая проверка: 21:00 записывать нельзя ни при каком дне."""
    for сдвиг in range(3):
        д = date.fromordinal(ЧЕТВЕРГ.toordinal() + сдвиг)
        assert "21:00" not in prompt.свободные_времена(салон, д, дней_вперёд=1)


def test_часы_работы_можно_назвать_про_любой_день(салон):
    """«Работаем с 10:00 до 21:00» — факт, а не окно конкретного дня."""
    о = prompt.окна(салон, ЧЕТВЕРГ)
    for день in (0, 1, 2):
        assert "21:00" in о.для_дня(день)


# --- поведение целиком ---

@pytest.mark.asyncio
async def test_верный_отказ_с_часами_работы_уходит_клиенту(
    сделать_дирижёра, транспорт
):
    """Отвергает заслон, который душит верный ответ.

    Сломайте упоминаемые_времена до свободные_времена — 21:00 станет
    «выдуманным», и клиент получит шаблон вместо часов работы.
    """
    д, _ = сделать_дирижёра([Ответ(reply=ОТКАЗ_С_ЧАСАМИ)])
    await д.принять(входящее("а в 23:00 можно?"))
    await д.обработать(7)

    assert транспорт.отправленное, "верный отказ не должен блокироваться"
    текст = транспорт.отправленное[-1][1]
    assert "21:00" in текст, "часы работы обязаны дойти до клиента"
    assert "администратор" not in текст.lower(), (
        "это не случай для эскалации — модель ответила верно"
    )


@pytest.mark.asyncio
async def test_час_закрытия_нельзя_записать(сделать_дирижёра, транспорт, салон):
    """ГЛАВНЫЙ тест. Назвали 21:00 законно — записать на него всё равно нельзя.

    Отвергает отсечку `назвали & записываемые` в app.py: без неё 21:00
    попадает в «мы это предлагали», и первый заслон Booker пропускает запись
    на момент закрытия салона.
    """
    д, _ = сделать_дирижёра([Ответ(reply=ОТКАЗ_С_ЧАСАМИ)])
    await д.принять(входящее("а в 23:00 можно?"))
    await д.обработать(7)
    assert транспорт.отправленное, "ответ должен был уйти"

    предлагали = д._предлагали.get(7, set())
    assert "13:00" in предлагали, "настоящее окно обязано запомниться"
    assert "21:00" not in предлагали, (
        "час закрытия попал в предложенные — Booker пустит запись на 21:00"
    )

    # и то же самое через настоящий заслон, а не только через состояние
    with pytest.raises(ЗаписьОтклонена):
        Booker(салон).записать_синхронно(
            чат=7, день=ЧЕТВЕРГ, время="21:00", мастер_id=2,
            услуга_id="neck30", предложенные=sorted(предлагали),
        )
