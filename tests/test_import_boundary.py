"""Заслон на архитектуру: Telegram знает ровно один модуль.

Если telethon импортируется где-то ещё, значит отправку можно сделать в обход
Sender и всех его проверок. Это не стилистика — это дыра в защите.

⚠️ **Сам заслон был дырявым до 2026-08-15.** Все три проверки обходили пакет
плоским `glob("*.py")` и не видели вложенных папок: файл
`aiconic/что-угодно/x.py` мог импортировать и `telethon`, и `cerebras`, а прогон
оставался зелёным. Доказано пробой перед починкой — создал такой файл, все три
теста прошли. Вылезло при чертеже этапа 2, где появляется пакет `aiconic/inbox/`:
заслон, на который я собирался опереться, ровно там не работал.

Поэтому здесь есть **тесты на сам заслон**: они проверяют не код проекта, а то,
что проверка вообще умеет находить нарушителя. Заслон, который никогда не видел
красного, — это надежда, а не заслон.
"""

from __future__ import annotations

import re
from pathlib import Path

ПАКЕТ = Path(__file__).resolve().parent.parent / "aiconic"
РАЗРЕШЕНО = {"tg.py"}

_ИМПОРТ = re.compile(r"^\s*(?:from|import)\s+telethon", re.MULTILINE)


def нарушители(корень: Path, шаблон: re.Pattern[str], разрешено: set[str]) -> list[str]:
    """Файлы под `корень`, где сработал шаблон. Обход рекурсивный — см. шапку.

    Вынесено в функцию, чтобы её можно было навести на временное дерево и
    доказать, что она находит нарушителя. Без этого заслон проверялся только на
    текущем состоянии проекта, где нарушителей нет по определению.
    """
    найдены: list[str] = []
    for файл in корень.rglob("*.py"):
        if файл.name in разрешено:
            continue
        if шаблон.search(файл.read_text(encoding="utf-8")):
            найдены.append(str(файл.relative_to(корень)))
    return найдены


def test_telethon_импортируется_только_в_tg():
    найдены = нарушители(ПАКЕТ, _ИМПОРТ, РАЗРЕШЕНО)
    assert not найдены, (
        f"telethon импортируется вне tg.py: {найдены}. "
        "Отправка в обход Sender обходит все заслоны."
    )


def test_отправка_только_через_sender():
    """Никто, кроме sender.py, не должен вызывать транспорт напрямую."""
    найдены = []
    for файл in ПАКЕТ.rglob("*.py"):
        if файл.name in {"sender.py", "tg.py"}:
            continue
        текст = файл.read_text(encoding="utf-8")
        if re.search(r"\.отправить\s*\(", текст) and "отправить_шаблон" not in текст:
            найдены.append(файл.name)
    assert not найдены, f"прямой вызов транспорта в {найдены}"


def test_cerebras_импортируется_только_в_llm():
    найдены = нарушители(ПАКЕТ, re.compile(r"cerebras"), {"llm.py"})
    assert not найдены, (
        f"провайдер протёк за пределы llm.py: {найдены}. "
        "Смена провайдера должна быть переменной окружения, не правкой кода."
    )


# --- тесты на сам заслон -----------------------------------------------------

def test_нарушитель_во_вложенной_папке_ловится(tmp_path: Path):
    """ГЛАВНЫЙ ДЛЯ САМОГО ЗАСЛОНА. Проверка обязана видеть вложенные папки.

    Отвергает плоский `glob("*.py")` — ту самую реализацию, что стояла здесь до
    2026-08-15. С ней `aiconic/inbox/api.py` мог бы импортировать `telethon`, и
    ни один тест бы не покраснел.

    Дерево строится во временной папке, а не в проекте: заслон должен быть
    проверяемым, не оставляя следов.
    """
    (tmp_path / "inbox").mkdir()
    (tmp_path / "inbox" / "api.py").write_text(
        "from telethon import TelegramClient\n", encoding="utf-8"
    )
    (tmp_path / "чистый.py").write_text("x = 1\n", encoding="utf-8")

    найдены = нарушители(tmp_path, _ИМПОРТ, РАЗРЕШЕНО)
    assert найдены, "нарушитель во вложенной папке обязан быть найден"
    assert "api.py" in найдены[0]


def test_разрешённый_файл_не_считается_нарушителем(tmp_path: Path):
    """Обратный: `tg.py` импортировать telethon вправе.

    Отвергает реализацию без списка разрешённых — она объявила бы нарушителем
    единственный модуль, которому это можно, и заслон пришлось бы отключить.
    """
    (tmp_path / "tg.py").write_text(
        "from telethon import TelegramClient\n", encoding="utf-8"
    )
    assert нарушители(tmp_path, _ИМПОРТ, РАЗРЕШЕНО) == []


def test_упоминание_в_строке_не_ловится_как_импорт(tmp_path: Path):
    """Слово «telethon» в docstring — не импорт.

    Отвергает поиск подстрокой вместо начала строки: в этом проекте `telethon`
    упоминается в десятке docstring, и такой заслон объявил бы нарушителем
    почти весь пакет — а значит его бы просто выключили, и он перестал бы
    защищать вообще.
    """
    (tmp_path / "док.py").write_text(
        '"""Этот модуль не знает про telethon и не должен."""\n'
        "x = 'telethon упоминается строкой'\n",
        encoding="utf-8",
    )
    assert нарушители(tmp_path, _ИМПОРТ, РАЗРЕШЕНО) == []
