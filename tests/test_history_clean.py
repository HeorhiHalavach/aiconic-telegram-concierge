@pytest.mark.asyncio
async def test_текущее_медицинское_по_прежнему_не_доходит(сделать_дирижёра, транспорт):
    """Старый заслон не должен пострадать: модель на таком не вызывается вовсе."""
    д, провайдер = сделать_дирижёра([Ответ(reply="конечно, приходите!")])
    await д.принять(входящее(МЕДИЦИНСКОЕ))
    await д.обработать(7)
    assert провайдер.вызовы == [], "модель не должна вызываться на медицинском"
    assert "администратор" in транспорт.отправленное[-1][1].lower()
