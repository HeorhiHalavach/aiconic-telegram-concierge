"""Два дефекта, которые нашёл живой диалог 2026-08-13, а 114 тестов — нет.

Оба стоят здесь вместе намеренно: это память о том, что мутационная проверка
доказывает лишь наличие зубов у заслона, но не то, что заслон стоит в нужном
месте.

Дефект 1 — запись без подтверждения. Клиент спросил «сколько стоит массаж
спины?», модель ответила «предлагаю 13:00» и в том же ходу создала запись.
`_проверить_предлагали` не помешал: дирижёр пополнял список предложенных ДО
записи, и ответ сам себе выдавал разрешение. Мой test_b1 проверял время,
которое не предлагали НИКОГДА, и этот случай мимо него прошёл.

Дефект 2 — заслон цен принял год из даты за выдуманную цену и подменил
верное подтверждение записи шаблоном «передала администратору».
"""

from __future__ import annotations

import pytest
from conftest import ЧЕТВЕРГ, входящее

from aiconic import guards
from aiconic.llm import Ответ

ЗАПИСЬ_13 = {"мастер": 3, "дата": "2026-08-13", "время": "13:00", "услуга": "back60"}


# --- дефект 1: запись без подтверждения -------------------------------------

@pytest.mark.asyncio
async def test_предложение_и_запись_в_одном_ходу_отклоняются(
    сделать_дирижёра, транспорт, салон
):
    """ГЛАВНЫЙ тест. Проверяет запрещённый путь: цена спрошена, время только
    что предложено, подтверждения не было — записи быть не должно.

    Верните в app.py пополнение `_предлагали` перед `_может_записать` —
    тест покраснеет.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(
            reply="Массаж спины — 60 минут, 120 ₾. Предлагаю записаться сегодня в 13:00.",
            booking=dict(ЗАПИСЬ_13),
        )
    ])
    await д.принять(входящее("сколько стоит массаж спины?"))
    await д.обработать(7)

    assert транспорт.отправленное, "ответ с ценой должен уйти клиенту"
    assert len(салон.записи) == было, (
        "создана запись без подтверждения клиента: модель предложила время и "
        "сама себе разрешила запись в том же ходу"
    )


@pytest.mark.asyncio
async def test_клиент_сам_назвал_время_записываем_без_админа(
    сделать_дирижёра, транспорт, салон
):
    """Клиент выбрал время сам — предлагать ему это же время незачем.

    Решение Георгия 2026-08-13: просить админа тут не надо. Свободность всё
    равно проверит Booker, а «показали ли мы это время» для выбранного самим
    клиентом смысла не имеет.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Записала вас на 13:00 к Гиорги.", booking=dict(ЗАПИСЬ_13))
    ])
    await д.принять(входящее("запишите меня на 13:00 на массаж спины"))
    await д.обработать(7)

    assert len(салон.записи) == было + 1, (
        "клиент назвал свободное время сам — запись обязана появиться "
        "с первого хода"
    )
    ушло = транспорт.отправленное[-1][1]
    assert "администратор" not in ушло.lower(), "админа звать не надо"


@pytest.mark.asyncio
async def test_клиент_попросил_нерабочее_время_записи_нет(
    сделать_дирижёра, салон
):
    """«Запишите на 23:00» записью стать не должно.

    ⚠️ Честно про слои: запись здесь не создаётся ДВАЖДЫ независимо —
    и потому, что 23:00 не попало в предложенные, и потому, что
    `_проверить_свободно` не найдёт такого окна. Мутационная проверка это
    показала: снятие пересечения `& записываемые` результат не меняло.

    Поэтому проверяем оба слоя раздельно: сначала данные заслона, потом итог.
    Без первой проверки пересечение было бы непроверяемым украшением.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Салон работает с 10:00 до 21:00.",
              booking={"мастер": 3, "дата": "2026-08-13",
                       "время": "23:00", "услуга": "back60"})
    ])
    await д.принять(входящее("запишите меня на 23:00"))
    await д.обработать(7)

    assert "23:00" not in д._предлагали.get(7, set()), (
        "нерабочее время из сообщения клиента попало в предложенные — "
        "первый заслон Booker его пропустит"
    )
    assert len(салон.записи) == было


@pytest.mark.asyncio
async def test_подтверждение_следующим_ходом_записывает(
    сделать_дирижёра, транспорт, салон
):
    """Обратная сторона: починка не должна убить запись вообще.

    Первый ход предлагает, второй подтверждает — запись обязана появиться.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Предлагаю записаться сегодня в 13:00 к Гиорги."),
        Ответ(reply="Записала вас на 13:00.", booking=dict(ЗАПИСЬ_13)),
    ])

    await д.принять(входящее("когда свободно?"))
    await д.обработать(7)
    assert len(салон.записи) == было, "на первом ходу записи ещё нет"

    await д.принять(входящее("да, давайте", сдвиг_сек=20))
    await д.обработать(7)
    assert len(салон.записи) == было + 1, (
        "после подтверждения запись обязана появиться — иначе починка "
        "сломала весь путь записи"
    )
    новая = салон.записи[-1]
    assert новая["начало"] == "13:00" and int(новая["чат"]) == 7


# --- дефект 2: дата — не цена ------------------------------------------------

@pytest.mark.parametrize("текст", [
    "Записали на 14.08.2026 в 14:00.",
    "Записали на 2026-08-14 в 14:00.",
    "Записали на 14 августа 2026 в 14:00.",
    "Ждём вас 14.08 в 14:00.",
])
def test_дата_в_ответе_не_считается_выдуманной_ценой(текст):
    """Отвергает заслон, который душит верное подтверждение записи."""
    assert guards.выдуманные_цены(текст, {120, 170}) == [], текст


def test_год_с_валютой_всё_ещё_ловится():
    """Починка не должна ослабить заслон: «2026 ₾» — это уже цена."""
    assert guards.выдуманные_цены("Это будет 2026 ₾", {120, 170}) == [2026]


def test_выдуманная_цена_рядом_с_датой_ловится():
    """Дату вырезаем, но цену в том же предложении — нет."""
    лишние = guards.выдуманные_цены(
        "Записали на 14.08.2026, стоимость 999 ₾", {120, 170}
    )
    assert лишние == [999]


@pytest.mark.asyncio
async def test_подтверждение_с_датой_доходит_до_клиента(
    сделать_дирижёра, транспорт
):
    """Живой случай целиком: ответ с датой не должен уезжать администратору."""
    д, _ = сделать_дирижёра([
        Ответ(reply="Записано на 14.08.2026 в 14:00, массаж спины 60 мин — 120 ₾.")
    ])
    await д.принять(входящее("давайте на завтра в 14:00"))
    await д.обработать(7)

    assert транспорт.отправленное
    текст = транспорт.отправленное[-1][1]
    assert "14.08.2026" in текст, "верное подтверждение подменено шаблоном"
    assert "администратор" not in текст.lower()
