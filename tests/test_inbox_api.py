def test_в_карточке_нет_текста_клиента(окно):
    """ГЛАВНЫЙ ПО ТРЕБОВАНИЮ ГЕОРГИЯ.

    В переписке есть слова про операцию — и они обязаны остаться ТОЛЬКО в
    переписке. В карточке про здоровье стоит отметка «вопрос о здоровье».

    Отвергает карточку, копирующую последнее сообщение или причину словами:
    тогда данные о здоровье попали бы в наше хранилище и в любой будущий
    экспорт карточек.
    """
    окно["передачи"].открыть(7, handover.МЕДИЦИНА)
    карточка = окно["клиент"].get(
        "/api/chat/7", headers=с_токеном(окно)
    ).json()["карточка"]

    как_текст = str(карточка).lower()
    for запрещено in ("болит", "спина", "операц"):
        assert запрещено not in как_текст, f"в карточке слово клиента: {запрещено!r}"
    assert карточка["нужен_ответ"] is True
    assert карточка["причина"] == "вопрос о здоровье"


