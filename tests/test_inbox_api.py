def test_ответ_уходит_и_снимает_метку(окно):
    """Полный путь окна: пометили → админ ответил → метка снята."""
    окно["передачи"].открыть(7, handover.ТОРГ)
    о = окно["клиент"].post(
        "/api/reply", json={"чат_id": 7, "текст": "Сделаем скидку 20%."},
        headers=с_токеном(окно),
    )
    assert о.status_code == 200 and о.json()["отправлено"] is True
    assert окно["транспорт"].отправленное[-1] == (7, "Сделаем скидку 20%.")
    assert окно["передачи"].открытые() == {}


def test_отказ_показывается_администратору(окно):
    """ГЛАВНЫЙ. Молчание админ примет за сбой страницы и напишет второй раз.

    Отвергает реализацию, возвращающую 200 и «всё хорошо» при отказе Sender:
    администратор считал бы, что ответил, а клиент не получил ничего.
    """
    о = окно["клиент"].post(
        "/api/reply", json={"чат_id": 999, "текст": "привет"},
        headers=с_токеном(окно),
    )
    assert о.status_code == 409
    assert о.json()["отправлено"] is False
    assert "белом списке" in о.json()["причина"]
    assert окно["транспорт"].отправленное == []
