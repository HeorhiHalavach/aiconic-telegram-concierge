"""Окно администратора: заслон доступа и то, что окно показывает.

⚠️ Проверяется НАСТОЯЩИМ путём — HTTP-запросом через `TestClient`, а не вызовом
функций-обработчиков (§27). Вызов функции обходит ровно то, что здесь главное:
зависимость, которая требует токен. Тест, зовущий обработчик напрямую, был бы
проверкой с административным доступом.

Главные противоположны по смыслу:
  без токена окно не отдаёт НИ ОДНОГО байта данных;
  с токеном — отдаёт всё, что нужно для работы.
"""

