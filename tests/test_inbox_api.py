def test_неверный_токен_отвергается(окно):
    """Отвергает сравнение «начинается с», по длине и без учёта регистра.

    Все варианты ASCII намеренно: кириллицу в заголовке нельзя даже отправить,
    значит это не путь атаки. Проверяем то, что злоумышленник действительно
    может послать: префикс верного токена, обрезок, другой регистр.
    """
    плохие = (
        "",
        "test",                      # префикс верного
        ТОКЕН[:-1],                  # обрезанный на символ
        ТОКЕН + "x",                 # с лишним символом
        ТОКЕН.upper(),               # другой регистр
        "x" * len(ТОКЕН),            # та же длина, другое содержимое
    )
    for плохой in плохие:
        о = окно["клиент"].get("/api/chats", headers={"X-Inbox-Token": плохой})
        assert о.status_code == 401, f"токен {плохой!r} не должен подходить"


