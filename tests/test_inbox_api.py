    данные = окно["клиент"].get("/api/chats", headers=с_токеном(окно)).json()
    по_чату = {с["чат_id"]: с for с in данные["чаты"]}
    assert по_чату[7]["непрочитанных"] == 3
    assert по_чату[7]["нужен_ответ"] is False
    assert данные["ждут"] == 0


