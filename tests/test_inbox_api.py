def test_два_канала_считаются_отдельно(салон, лог, tmp_path: Path):
    """Настоящая мультиканальность: два канала, у каждого свой счёт.

    Отвергает реализацию, которая складывает всё в один мешок: администратор не
    увидел бы, в каком мессенджере его ждут.
    """
    from aiconic.канал import Диалог as Д

    class Инста(ФейкКанал):
        имя = "instagram"

    тг = ФейкКанал(диалоги=[
        Д(чат_id=7, имя="Гиорги", последнее="…", когда=None),
    ])
    инста = Инста(диалоги=[
        Д(чат_id=21, имя="nino_ig", последнее="…", когда=None, канал="instagram"),
        Д(чат_id=22, имя="levan_ig", последнее="…", когда=None, канал="instagram"),
    ])
    передачи = handover.Передачи(tmp_path)
    передачи.открыть(22, handover.ТОРГ)

    приложение = создать_приложение(
        каналы=[тг, инста], салон=салон,
        отправитель=Sender(ФейкТранспорт(), салон, белый_список={7}, лог=лог,
                           передачи=передачи),
        передачи=передачи, токен=ТОКЕН, сегодня=lambda: ЧЕТВЕРГ,
    )
    клиент = TestClient(приложение)
    данные = клиент.get("/api/channels", headers={"X-Inbox-Token": ТОКЕН}).json()

    по_имени = {к["имя"]: к for к in данные["каналы"]}
    assert по_имени["telegram"]["ждут"] == 0
    assert по_имени["instagram"]["ждут"] == 1
    assert по_имени["instagram"]["чатов"] == 2
    assert данные["ждут_всего"] == 1


def test_сбой_одного_канала_не_гасит_остальные(салон, лог, tmp_path: Path):
    """Instagram лёг — Telegram обязан работать.

    Отвергает сборку ленты без перехвата на канал: один отказавший мессенджер
    делал бы окно пустым целиком, и администратор решил бы, что сломалось всё.
    """
    class Падучий(ФейкКанал):
        имя = "instagram"

        async def диалоги(self, сколько):
            raise RuntimeError("Instagram недоступен")

    from aiconic.канал import Диалог as Д
    тг = ФейкКанал(диалоги=[Д(чат_id=7, имя="Гиорги", последнее="…", когда=None)])
    передачи = handover.Передачи(tmp_path)
