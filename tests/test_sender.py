"""Sender — единственная точка выхода. Заслоны внутри него нельзя обойти."""

from __future__ import annotations

from pathlib import Path

import pytest

from aiconic import guards
from aiconic.llm import Ответ
from aiconic.sender import ШАБЛОН_АДМИНУ, Sender

ОКНА = guards.Окна(
    по_дням={0: frozenset({"11:00", "13:00", "14:00"})},
    метки={"сегодня": 0},
)


async def отправить(s, ответ, **kw):
    return await s.отправить_ответ(7, ответ, окна=ОКНА, **kw)


@pytest.mark.asyncio
async def test_обычный_ответ_уходит(отправитель, транспорт):
    р = await отправить(отправитель, Ответ(reply="Массаж спины 60 минут — 120 ₾"))
    assert р.отправлено and транспорт.отправленное


@pytest.mark.asyncio
async def test_выдуманная_цена_не_уходит(отправитель, транспорт):
    """Отвергает доверяющую числам от модели: клиенту уходит шаблон, не цена."""
    р = await отправить(отправитель, Ответ(reply="Сделаем за 95 лари"))
    assert р.администратору and "цены не из прайса" in р.причина
    assert транспорт.отправленное[-1][1] == ШАБЛОН_АДМИНУ


@pytest.mark.asyncio
async def test_выдуманное_время_не_уходит(отправитель, транспорт):
    """Отвергает доверяющую расписанию от модели."""
    р = await отправить(отправитель, Ответ(reply="Приходите в 09:15"))
    assert р.администратору and "не из свободных окон" in р.причина


@pytest.mark.asyncio
async def test_needs_human_блокирует_текст_модели(отправитель, транспорт):
    """Отвергает эскалацию только по списку триггеров: флаг модели — второй слой."""
    р = await отправить(
        отправитель,
        Ответ(reply="Конечно, приходите!", needs_human=True, reason="торг"),
    )
    assert р.администратору
    assert транспорт.отправленное[-1][1] == ШАБЛОН_АДМИНУ
    assert "Конечно" not in транспорт.отправленное[-1][1]


@pytest.mark.asyncio
async def test_kill_switch(транспорт, салон, tmp_path: Path):
    """Отвергает выключатель, который не выключает."""
    стоп = tmp_path / "STOP"
    s = Sender(транспорт, салон, белый_список={7}, файл_выключателя=стоп)
    стоп.write_text("")
    р = await отправить(s, Ответ(reply="привет"))
    assert not р.отправлено and "kill switch" in р.причина
    assert транспорт.отправленное == []


@pytest.mark.asyncio
async def test_чат_не_в_белом_списке(транспорт, салон):
    s = Sender(транспорт, салон, белый_список={7})
    р = await s.отправить_ответ(999, Ответ(reply="привет"), окна=ОКНА)
    assert not р.отправлено and "белом списке" in р.причина
    assert транспорт.отправленное == []


@pytest.mark.asyncio
async def test_лимит_отсекает(транспорт, салон):
    """Отвергает отсутствие лимита."""
    s = Sender(транспорт, салон, белый_список={7},
               лимит=guards.Лимит(на_чат=2, всего=10, окно_сек=60))
    for _ in range(2):
        assert (await отправить(s, Ответ(reply="ок"), сейчас=1000.0)).отправлено
    р = await отправить(s, Ответ(reply="ок"), сейчас=1000.0)
    assert not р.отправлено and "лимит" in р.причина


@pytest.mark.asyncio
async def test_админ_ответил_раньше(отправитель, транспорт):
    """Отвергает двойной ответ клиенту."""
    р = await отправить(отправитель, Ответ(reply="ок"), админ_ответил=True)
    assert not р.отправлено and "администратор" in р.причина
    assert транспорт.отправленное == []


@pytest.mark.asyncio
async def test_пустой_ответ_модели_не_уходит(отправитель, транспорт):
    р = await отправить(отправитель, Ответ(reply="   "))
    assert not р.отправлено and "пустой" in р.причина
    assert транспорт.отправленное == []
