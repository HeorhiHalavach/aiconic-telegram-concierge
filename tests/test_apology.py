"""Поправка «записать не получилось» — только когда клиент её ждёт.

Найдено имитацией 2026-08-14. Клиент написал «?», модель сама предложила 14:00 и
в том же ходу попыталась записать. Заслон верно отказал — подтверждения не было, —
но клиент получил «Прошу прощения, записать не получилось», хотя ни о чём не
просил.

Извинение на пустом месте пугает не меньше, чем молчание после настоящего отказа.
Правило: поправка нужна, если клиент МОГ ПОВЕРИТЬ, что записан, то есть если он
сам просил записать или согласился.

Оба направления здесь равноправны, и второе важнее: молчать после настоящего
отказа нельзя ни в каком случае.
"""

from __future__ import annotations

import pytest
from conftest import ЧЕТВЕРГ, входящее

from aiconic import guards
from aiconic.llm import Ответ
from aiconic.sender import ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА

# 13:00 в четверг занять нечем: заслон «не предлагали» отвергнет запись,
# потому что клиент времени не называл и мы его не предлагали.
БРОНЬ = {"мастер": 1, "дата": ЧЕТВЕРГ.isoformat(), "время": "13:00",
         "услуга": "back60"}


# --- сама проверка намерения --------------------------------------------------

@pytest.mark.parametrize("текст", [
    "запишите меня на 13:00",
    "запишите",
    "хочу записаться",
    "да",
    "да, давайте",
    "давайте",
    "ок",
    "подтверждаю",
    "подходит",
    "оформляйте",
    "можно в 14:00?",              # время = намерение
    "согласен",
])
def test_просьба_записать_видна(текст):
    assert guards.просил_записать(текст) is True, текст


@pytest.mark.parametrize("текст", [
    "?",
    "👍",
    "спасибо",
    "сколько стоит массаж спины?",
    "где вы находитесь?",
    "а массаж лица делаете?",
    "давно у вас не был",          # «да» внутри «давно» ловиться не должно
    "здравствуйте",
])
def test_просьбы_записать_нет(текст):
    assert guards.просил_записать(текст) is False, текст


# --- поправка не приходит, когда клиент не просил -----------------------------

@pytest.mark.asyncio
async def test_модель_забежала_вперёд_поправки_нет(
    сделать_дирижёра, транспорт, салон, лог
):
    """ГЛАВНЫЙ. Клиент написал «?», модель сама решила записать.

    Отвергает безусловную отправку поправки: клиент не просил записи, значит и
    извиняться не за что.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Сегодня в 13:00 у Нино свободно. Записать?", booking=dict(БРОНЬ))
    ])
    await д.принять(входящее("?"))
    await д.обработать(7)

    assert len(салон.записи) == было, "записи быть не должно"
    ушло = [т for _, т in транспорт.отправленное]
    assert ушло, "вопрос модели обязан дойти до клиента"
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА not in ушло, (
        "клиент записи не просил — извиняться не за что"
    )
    assert any("поправку не шлём" in (з.get("причина") or "") for з in лог.записи), (
        "решение не отправлять поправку обязано попасть в лог"
    )


# --- поправка приходит, когда клиент просил ------------------------------------

@pytest.mark.asyncio
async def test_клиент_просил_поправка_приходит(сделать_дирижёра, транспорт, салон):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Молчать после настоящего отказа нельзя.

    Отвергает реализацию, которая перестала извиняться вообще: клиент попросил
    записать, прочитал «записываю» — и обязан узнать, что записи нет.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас на 13:00.", booking=dict(БРОНЬ))
    ])
    # клиент просит записать, но времени не называет → заслон «не предлагали»
    await д.принять(входящее("запишите меня пожалуйста"))
    await д.обработать(7)

    assert len(салон.записи) == было
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА in [т for _, т in транспорт.отправленное], (
        "клиент просил записать и остался без предупреждения"
    )


@pytest.mark.asyncio
async def test_согласие_одним_словом_тоже_считается(
    сделать_дирижёра, транспорт, салон
):
    """«да» — это просьба записать не меньше, чем «запишите»."""
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.", booking=dict(БРОНЬ))
    ])
    await д.принять(входящее("да"))
    await д.обработать(7)
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА in [т for _, т in транспорт.отправленное]


@pytest.mark.asyncio
async def test_плохая_дата_при_просьбе_тоже_поправляется(
    сделать_дирижёра, транспорт, салон
):
    """Дата не по ISO — тот же случай: клиент просил, записи нет."""
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.",
              booking=dict(БРОНЬ, **{"дата": "13.08.2026"}))
    ])
    await д.принять(входящее("да, запишите"))
    await д.обработать(7)
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА in [т for _, т in транспорт.отправленное]
