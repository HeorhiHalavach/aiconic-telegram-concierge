@pytest.mark.asyncio
async def test_повторная_обработка_пачки_не_даёт_второго_ответа(
    сделать_дирижёра, транспорт
):
    """Настоящий заслон от двойного ответа — пачка забирается один раз.

    Мутационная проверка показала, что отмена таймера — оптимизация, а не
    гарантия: корректность держится на том, что обработать() ЗАБИРАЕТ пачку,
    и повторный вызов уже ничего не находит. Этот тест защищает именно это.
    """
    д, провайдер = сделать_дирижёра([Ответ(reply="120 ₾"), Ответ(reply="ещё раз")])
    await д.принять(входящее("сколько стоит?"))
    await д.обработать(7)
    await д.обработать(7)          # второй таймер, если он не был отменён
    assert len(провайдер.вызовы) == 1
    assert len(транспорт.отправленное) == 1


@pytest.mark.asyncio
async def test_сообщения_с_разбросом_по_времени_один_ответ(
    сделать_дирижёра, транспорт
):
    """Отвергает реализацию, которая не перезапускает таймер на новое сообщение.

    Именно этот случай — настоящий: клиент печатает не мгновенно. Если таймер
    не сбрасывать, первый успеет сработать до третьего сообщения, и клиент
    получит ДВА ответа на одну мысль.
    """
    import asyncio

    д, провайдер = сделать_дирижёра(
        [Ответ(reply="Массаж спины — 120 ₾"), Ответ(reply="и ещё раз")], пауза=0.10
    )
    await д.принять(входящее("привет"))
    await asyncio.sleep(0.06)          # меньше паузы: таймер обязан сброситься
    await д.принять(входящее("сколько стоит массаж спины"))
    await asyncio.sleep(0.30)

    assert len(провайдер.вызовы) == 1, "таймер не сбросился — вышло два вызова модели"
    assert len(транспорт.отправленное) == 1, "клиент получил два ответа на одну мысль"
    запрос = провайдер.вызовы[0][1][-1]["content"]
    assert "привет" in запрос and "сколько стоит" in запрос
