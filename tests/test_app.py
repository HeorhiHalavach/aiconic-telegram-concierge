@pytest.mark.asyncio
async def test_успешная_запись(сделать_дирижёра, салон):
    """Запись требует ДВУХ ходов: сначала мы предложили, потом клиент согласился.

    Раньше этот тест посылал одно сообщение и зеленел — но зеленел он из-за
    дефекта: дирижёр пополнял список предложенных ДО записи, и ответ сам себе
    выдавал разрешение. Живой диалог 2026-08-13 записал клиента, который лишь
    спросил цену. Тест проверял разрешённый путь и потому дефекта не видел.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Свободно сегодня в 13:00 к Нино. Подтвердите, пожалуйста."),
        Ответ(reply="Записала вас на 13:00",
              booking={"мастер": 1, "дата": ЧЕТВЕРГ.isoformat(),
                       "время": "13:00", "услуга": "back60"}),
    ])

    await д.принять(входящее("когда свободно?"))
    await д.обработать(7)
    assert len(салон.записи) == было, "до подтверждения записи быть не должно"

    await д.принять(входящее("да, запишите на 13:00", сдвиг_сек=20))
    await д.обработать(7)
    assert len(салон.записи) == было + 1
    новая = салон.записи[-1]
    assert новая["начало"] == "13:00" and новая["чат"] == 7


