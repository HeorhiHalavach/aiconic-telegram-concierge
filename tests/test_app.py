@pytest.mark.asyncio
async def test_три_сообщения_один_ответ(сделать_дирижёра, транспорт):
    """Отвергает реализацию без группировки: три ответа на три сообщения."""
    д, провайдер = сделать_дирижёра([Ответ(reply="Массаж спины — 120 ₾")])
    await д.принять(входящее("привет"))
    await д.принять(входящее("сколько стоит"))
    await д.принять(входящее("массаж спины"))
