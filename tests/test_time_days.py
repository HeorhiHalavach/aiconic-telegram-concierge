"""Заслон времени знает про день — дефект B.

До 2026-08-13 `выдуманное_время` сверяло строку времени с множеством,
СКЛЕЕННЫМ по трём дням. На живых данных салона это дырка с именем: 19:00 и
20:30 свободны завтра у Мариам, а сегодня салон закрывается в 19:00 и таких
окон нет вовсе. Ответ «свободно сегодня в 20:30» проходил заслон.

Дефект был назван в STATUS как B сразу, но закрыт только теперь: он не выстрелил
ни в одном прогоне, и это ровно тот случай, когда «не выстрелило» путают с
«не может выстрелить».

Главные тесты здесь — те, что проверяют ЗАПРЕЩЁННЫЙ путь: время, свободное в
другой день, названное применительно к этому.
"""

from __future__ import annotations

import pytest
from conftest import ЧЕТВЕРГ, входящее

from aiconic import guards, prompt
from aiconic.llm import Ответ

# Сегодня свободно 11:00 и 13:00, завтра — 20:00. Часы работы 10:00–21:00.
ОКНА = guards.Окна(
    по_дням={
        0: frozenset({"11:00", "13:00"}),
        1: frozenset({"20:00"}),
    },
    метки={"сегодня": 0, "13.08": 0, "завтра": 1, "14.08": 1},
    часы=frozenset({"10:00", "21:00"}),
)


# --- запрещённый путь: чужой день ------------------------------------------

@pytest.mark.parametrize("текст", [
    "Свободно сегодня в 20:00.",
    "Сегодня можем в 20:00, подойдёт?",
    "13.08 есть окно в 20:00.",
])
def test_завтрашнее_окно_названное_сегодняшним_ловится(текст):
    """ГЛАВНЫЙ. 20:00 свободно ЗАВТРА — сегодня такого окна нет.

    Отвергает склеенное по дням множество: там 20:00 присутствует, и заслон
    молчал. Верните `выдуманное_время` к плоскому множеству — тест покраснеет.
    """
    assert guards.выдуманное_время(текст, ОКНА) == ["20:00"], текст


@pytest.mark.parametrize("текст", [
    "Завтра свободно в 11:00.",
    "14.08 можем в 13:00.",
])
def test_сегодняшнее_окно_названное_завтрашним_ловится(текст):
    """Симметрично: окно сегодняшнего дня, отнесённое к завтра."""
    assert guards.выдуманное_время(текст, ОКНА) != [], текст


# --- разрешённый путь: день назван верно -------------------------------------

@pytest.mark.parametrize("текст", [
    "Сегодня свободно в 11:00 и 13:00.",
    "Завтра есть 20:00.",
    "13.08 свободно 11:00, 14.08 свободно 20:00.",
    "Мы работаем с 10:00 до 21:00.",
    "Сегодня работаем до 21:00, свободно 13:00.",
])
def test_верно_названный_день_проходит(текст):
    assert guards.выдуманное_время(текст, ОКНА) == [], текст


# --- правила отнесения времени к дню ----------------------------------------

def test_без_метки_дня_сверяем_с_любым_днём():
    """День не назван нигде — судить о нём нечем, но выдумку видно и так.

    ⚠️ Правило изменено 2026-08-13 после четырёх ложных срабатываний подряд.
    Раньше сверяли с сегодня, и это было угадыванием: день мог быть задан
    тремя репликами раньше. Теперь пропускаем время, свободное хотя бы в один
    день, и ловим свободное ни в один.
    """
    assert guards.выдуманное_время("Свободно в 13:00.", ОКНА) == []
    assert guards.выдуманное_время("Свободно в 20:00.", ОКНА) == [], (
        "20:00 свободно завтра — без метки дня это не выдумка"
    )
    assert guards.выдуманное_время("Свободно в 09:15.", ОКНА) == ["09:15"], (
        "09:15 не свободно ни в один день — это выдумка при любом дне"
    )


def test_единственная_метка_действует_на_весь_текст():
    """«В 20:00 завтра» — метка стоит ПОСЛЕ времени, но она одна.

    Отвергает реализацию, смотрящую только влево: она отнесла бы 20:00
    к сегодня и заблокировала верный ответ.
    """
    assert guards.выдуманное_время("В 20:00 завтра свободно.", ОКНА) == []


def test_две_метки_про_один_день_тоже_действуют_на_весь_текст():
    """ЖИВОЙ ПРОМАХ 2026-08-13. Модель написала так, и заслон соврал.

    «20:30 у Мариам завтра или 20:00 у Мариам завтра» — меток две, обе про
    завтра. Правило «ровно одна метка» не срабатывало, 20:30 сверилось с
    сегодня, и верный ответ уехал администратору.

    Отвергает `len(метки) == 1` вместо «все метки про один день».
    """
    # Своя фикстура: у Мариам завтра свободны и 20:00, и 20:30, как в живых
    # данных. В общей ОКНА на завтра только 20:00, и тест потерял бы смысл.
    как_живьём = guards.Окна(
        по_дням={0: frozenset({"11:00", "13:00"}),
                 1: frozenset({"20:00", "20:30"})},
        метки={"сегодня": 0, "завтра": 1},
        часы=frozenset({"10:00", "21:00"}),
    )
    текст = ("Салон работает с 10:00 до 21:00. Предлагаем 20:30 у Мариам "
             "завтра или 20:00 у Мариам завтра.")
    assert guards.выдуманное_время(текст, как_живьём) == [], (
        "оба времени свободны завтра, и обе метки про завтра"
    )

    # И обратная сторона: если бы одно из них было занято, заслон обязан ловить.
    without = guards.Окна(
        по_дням={0: frozenset({"11:00"}), 1: frozenset({"20:00"})},
        метки={"сегодня": 0, "завтра": 1},
        часы=frozenset({"10:00", "21:00"}),
    )
    assert guards.выдуманное_время(текст, without) == ["20:30"]


def test_несколько_меток_каждое_время_к_своей():
    текст = "Сегодня: 11:00, 13:00. Завтра: 20:00."
    assert guards.выдуманное_время(текст, ОКНА) == []

    плохой = "Сегодня: 11:00, 20:00. Завтра: 20:00."
    assert guards.выдуманное_время(плохой, ОКНА) == ["20:00"], (
        "второе 20:00 относится к завтра и законно, первое — к сегодня и нет"
    )


def test_день_без_окон_отвергает_всё_кроме_часов_работы():
    """Пустой день — не повод пропускать: свободных окон в нём нет."""
    пусто = guards.Окна(по_дням={0: frozenset()}, метки={"сегодня": 0},
                        часы=frozenset({"10:00", "21:00"}))
    assert guards.выдуманное_время("Сегодня свободно в 13:00.", пусто) == ["13:00"]
    assert guards.выдуманное_время("Работаем с 10:00 до 21:00.", пусто) == []


def test_время_свободное_ни_в_один_день_ловится_всегда():
    """Главный улов заслона не зависит ни от каких меток.

    «14:08» из живого прогона — именно этот случай: модель превратила дату
    14.08 во время, и такого окна нет ни в один день горизонта.
    """
    for текст in (
        "Свободно в 14:08.",
        "Сегодня свободно в 14:08.",
        "Завтра свободно в 14:08.",
        "25.12 свободно в 14:08.",
    ):
        assert guards.выдуманное_время(текст, ОКНА) == ["14:08"], текст


# --- сборка из настоящих данных салона ---------------------------------------

def test_окна_салона_разложены_по_трём_дням(салон):
    о = prompt.окна(салон, ЧЕТВЕРГ)
    assert set(о.по_дням) == {0, 1, 2}
    assert о.метки["сегодня"] == 0
    assert о.метки["завтра"] == 1
    assert о.метки["13.08"] == 0
    assert о.метки["14.08"] == 1


def test_на_живых_данных_дни_действительно_разные(салон):
    """Дефект был не теоретическим: множества дней различаются.

    Если бы они совпадали, заслон по дням ничего бы не добавлял, и весь этот
    файл был бы театром.
    """
    о = prompt.окна(салон, ЧЕТВЕРГ)
    только_завтра = о.по_дням[1] - о.по_дням[0]
    assert только_завтра, (
        "нет ни одного времени, свободного завтра и занятого сегодня — "
        "проверьте data/schedule.yaml, тест потерял смысл"
    )
    время = sorted(только_завтра)[-1]
    assert guards.выдуманное_время(f"Сегодня свободно в {время}.", о) == [время]
    assert guards.выдуманное_время(f"Завтра свободно в {время}.", о) == []


# --- через Sender целиком -----------------------------------------------------

@pytest.mark.asyncio
async def test_чужой_день_не_уходит_клиенту(сделать_дирижёра, транспорт, салон):
    """Живой путь: такой ответ обязан уехать администратору, не клиенту."""
    о = prompt.окна(салон, ЧЕТВЕРГ)
    только_завтра = sorted(о.по_дням[1] - о.по_дням[0])
    assert только_завтра, "данные фикстуры потеряли смысл теста"
    время = только_завтра[-1]

    д, _ = сделать_дирижёра([
        Ответ(reply=f"Записываю вас сегодня в {время}.")
    ])
    await д.принять(входящее("когда свободно сегодня?"))
    await д.обработать(7)

    ушло = транспорт.отправленное[-1][1]
    assert время not in ушло, "время из другого дня ушло клиенту"
    assert "администратор" in ушло.lower()
