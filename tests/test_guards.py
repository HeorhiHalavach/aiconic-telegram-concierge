"""Заслоны: медицина, спам, выдуманные цены и время, приём, лимит."""

from __future__ import annotations

from datetime import datetime, timedelta, timezone

from aiconic import guards


# --- медицина ---

def test_медицинский_триггер_ловит_живые_формулировки():
    """Отвергает список, собранный из «красивых» слов вместо реальных фраз."""
    for фраза in (
        "болит спина после операции",
        "у меня беременность 20 недель, можно массаж?",
        "недавно была травма колена",
        "врач сказал остеохондроз",
        "есть противопоказания?",
    ):
        assert guards.медицинский_триггер(фраза), фраза


def test_медицинский_триггер_не_ложится_на_обычное():
    for фраза in ("сколько стоит массаж спины?", "есть окна на завтра?",
                  "а где вы находитесь?", "хочу расслабляющий на час"):
        assert guards.медицинский_триггер(фраза) is None, фраза


def test_спам_ловится():
    assert guards.спам("инвестиции в крипту, заработок с нуля")
    assert guards.спам("подпишись на канал") is not None
    assert guards.спам("хочу записаться на массаж") is None


# --- выдуманные цены ---

ЦЕНЫ = {120, 170, 130, 180, 110, 70, 60, 550, 1000}


def test_цена_из_прайса_проходит():
    assert guards.выдуманные_цены("Массаж спины 60 минут — 120 ₾", ЦЕНЫ) == []


def test_выдуманная_цена_ловится():
    """Отвергает доверяющую числам от модели."""
    assert guards.выдуманные_цены("Сделаем за 95 лари", ЦЕНЫ) == [95]


def test_время_не_принимается_за_цену():
    """Отвергает наивный поиск чисел: 12:00 — не цена."""
    assert guards.выдуманные_цены("Свободно в 12:00 и 15:30", ЦЕНЫ) == []


def test_длительность_не_принимается_за_цену():
    assert guards.выдуманные_цены("Массаж 90 минут стоит 170 ₾", ЦЕНЫ) == []


def test_маленькие_числа_не_цены():
    assert guards.выдуманные_цены("абонемент на 5 сеансов", ЦЕНЫ) == []


