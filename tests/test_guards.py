# --- приём ---

def _приём(белый={7}):
    return guards.Приём(белый_список=белый, старт=datetime.now(timezone.utc))


def _позже(п, сек=5):
    return п.старт + timedelta(seconds=сек)


def test_исходящее_не_обрабатывается():
    п = _приём()
    assert п.причина_отказа(чат_id=7, личный=True, исходящее=True,
                            дата=_позже(п)) == "исходящее сообщение"


def test_группа_не_обрабатывается():
    п = _приём()
    assert п.причина_отказа(чат_id=7, личный=False, исходящее=False,
                            дата=_позже(п)) == "не личный чат"


def test_сообщение_старше_запуска_не_обрабатывается():
    """Отвергает первый запуск, отвечающий на весь непрочитанный backlog."""
    п = _приём()
    старое = п.старт - timedelta(hours=3)
    assert "старше" in п.причина_отказа(чат_id=7, личный=True,
                                        исходящее=False, дата=старое)


def test_наивная_дата_не_доверяется():
    """Отвергает сравнение tz-aware даты с наивной: это TypeError в бою."""
    п = _приём()
    наивная = datetime.now()          # без таймзоны
    assert "таймзоны" in п.причина_отказа(чат_id=7, личный=True,
                                          исходящее=False, дата=наивная)


def test_чат_не_в_белом_списке():
    п = _приём()
    assert п.причина_отказа(чат_id=999, личный=True, исходящее=False,
                            дата=_позже(п)) == "чат не в белом списке"


def test_нормальное_сообщение_проходит():
    п = _приём()
    assert п.причина_отказа(чат_id=7, личный=True, исходящее=False,
                            дата=_позже(п)) is None


# --- лимит ---

def test_лимит_на_чат():
    л = guards.Лимит(на_чат=3, всего=100, окно_сек=60)
    for i in range(3):
        assert л.разрешено(7, 1000.0)
        л.отметить(7, 1000.0)
    assert not л.разрешено(7, 1000.0)


def test_лимит_суммарный():
    л = guards.Лимит(на_чат=100, всего=2, окно_сек=60)
    л.отметить(1, 1000.0)
    л.отметить(2, 1000.0)
    assert not л.разрешено(3, 1000.0)


def test_лимит_отпускает_после_окна():
    л = guards.Лимит(на_чат=1, всего=10, окно_сек=60)
    л.отметить(7, 1000.0)
    assert not л.разрешено(7, 1030.0)
    assert л.разрешено(7, 1061.0)
