"""Диагностика входа: login.py обязан объяснить ЛЮБОЙ способ доставки кода.

Написано после живого случая 2026-08-13. Код не пришёл, ошибки не было, и
выяснить, куда Telegram его отправил, было нечем: client.start() эту
информацию выбрасывает. Час ушёл на догадки.

Главный тест здесь — первый. Он перебирает способы доставки прямо из
установленной библиотеки, а не из моего списка: появится новый тип — тест
покраснеет, вместо того чтобы оставить нас снова без диагноза.
"""

from __future__ import annotations

import importlib
import io
import re
from contextlib import redirect_stdout

import pytest
from telethon.tl.types import auth as типы_auth

login = importlib.import_module("login")

ССЫЛКА = "tg://login?token=AQIDBAUGBwgJCgsMDQ4PEBESExQVFhcYGRobHB0eHyA"

ВСЕ_ТИПЫ = sorted(
    имя for имя in dir(типы_auth)
    if имя.startswith("SentCodeType") and isinstance(getattr(типы_auth, имя), type)
)


def test_список_типов_не_пуст():
    """Если библиотека переедет и типы уедут — знать об этом сразу."""
    assert len(ВСЕ_ТИПЫ) >= 9, ВСЕ_ТИПЫ


@pytest.mark.parametrize("имя_типа", ВСЕ_ТИПЫ)
def test_каждый_способ_доставки_объяснён(имя_типа):
    """Отвергает молчаливую слепоту: неизвестный способ = нет диагноза.

    Проверяется запрещённый исход (ответ «неизвестный способ»), а не
    разрешённый.
    """
    класс = getattr(типы_auth, имя_типа)
    # у типов разные обязательные поля; пустой объект достаточен — читаются
    # они через getattr с подстановкой
    экземпляр = класс.__new__(класс)
    строки = login._куда_ушёл_код(экземпляр)

    assert строки, f"{имя_типа}: пустое объяснение"
    склеено = " ".join(строки)
    assert "Неизвестный способ" not in склеено, (
        f"{имя_типа} не объяснён в login.py — при таком ответе Telegram мы "
        f"снова останемся без диагноза"
    )


def test_неизвестный_тип_честно_признаётся():
    """Обратная сторона: выдуманный тип НЕ должен получить ложное объяснение."""
    class SentCodeTypeВыдуманный:
        pass

    строки = login._куда_ушёл_код(SentCodeTypeВыдуманный())
    assert "Неизвестный способ" in " ".join(строки)


def test_qr_рисуется_и_ссылка_остаётся_видна():
    """QR может не сняться камерой с экрана — ссылка обязана быть напечатана."""
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        login._нарисовать_qr(ССЫЛКА)
    вывод = буфер.getvalue()

    assert ССЫЛКА in вывод, "без ссылки не останется запасного пути"
    квадрат = [с for с in вывод.splitlines() if "█" in с or "▀" in с]
    assert len(квадрат) >= 10, "QR не отрисовался"
    assert "Устройства" in вывод, "нет инструкции, где сканировать"


