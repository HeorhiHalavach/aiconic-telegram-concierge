# --- 5. Напоминания ---------------------------------------------------------

def test_reminders_off_выключает_и_цикл_и_обещания(tmp_path, салон, лог,
                                                   monkeypatch):
    """REMINDERS=off обязан выключить ОБА: и рассылку, и обещание в промпте.

    Отвергает реализацию, где флаг влияет только на цикл: бот пообещает
    напоминание, которое никто не отправит. Это ровно тот класс дефекта, из-за
    которого §26 вообще существует.
    """
    monkeypatch.setenv("REMINDERS", "off")
    с = собрать(tmp_path, канал=ФейкКанал(), салон=салон, лог=лог)
    assert с.напоминать is False
    assert с.дирижёр.напоминания is False, (
        "промпт обязан узнать, что напоминаний нет"
    )


def test_напоминания_включены_по_умолчанию(tmp_path, салон, лог, monkeypatch):
    """Обратный: без переменной напоминания работают.

    Отвергает реализацию, которая по ошибке читает переменную как «включить»
    вместо «выключить» — тогда по умолчанию всё было бы выключено молча.
    """
    monkeypatch.delenv("REMINDERS", raising=False)
    с = собрать(tmp_path, канал=ФейкКанал(), салон=салон, лог=лог)
    assert с.напоминать is True
    assert с.дирижёр.напоминания is True


def test_режим_наблюдения_гасит_напоминания(tmp_path, салон, лог, monkeypatch):
    """В наблюдении система не пишет первой — даже с REMINDERS=on.

    Отвергает реализацию `напоминать = REMINDERS != off` без `and not
    наблюдение`: в режиме, где мы обещали никому не писать, ушла бы рассылка.
    """
    monkeypatch.setenv("REMINDERS", "on")
    с = собрать(tmp_path, канал=ФейкКанал(), салон=салон, лог=лог,
                белый=set(), наблюдение=True)
    assert с.напоминать is False
