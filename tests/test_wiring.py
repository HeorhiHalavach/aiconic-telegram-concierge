"""Проводка системы: что `собрать_систему` обязана соединить.

Зачем этот файл вообще есть. Все остальные 382 теста собирают дирижёра САМИ,
через фикстуру `сделать_дирижёра`. Значит ни один из них не смотрит на
настоящую проводку из main.py — а именно там живут ошибки вида «забыли передать
файл выключателя» и «забыли обернуть чтение истории в try». Такая ошибка не
роняет ни один тест и обнаруживается только в бою: STOP не глушит, отказ
Telegram убивает обработку целиком.

Раньше проводка была внутри `main()` и тест на неё написать было НЕЛЬЗЯ:
`main()` требует живой Telegram, живой Cerebras и рабочий .env. Вынос
`собрать_систему` сделан ровно для этого файла.

Каждый тест ниже называет реализацию, которую отвергает.
"""

from __future__ import annotations

import pytest
from conftest import входящее

from aiconic.llm import FakeProvider, Ответ
from main import собрать_систему


class ФейкКанал:
    """Транспорт + история, как настоящий TelegramКанал.

    `падать=True` — Telegram отказал на чтении истории. Это не выдуманный
    случай: FloodWait и потеря соединения дают ровно это.
    """

    def __init__(self, история: list[dict] | None = None, падать: bool = False) -> None:
        self.отправленное: list[tuple[int, str]] = []
        self._история = история or []
        self._падать = падать
        self.запросов_истории = 0

    async def отправить(self, чат_id: int, текст: str) -> None:
        self.отправленное.append((чат_id, текст))

    async def история(self, чат_id: int, сколько: int) -> list[dict]:
        self.запросов_истории += 1
        if self._падать:
            raise RuntimeError("FloodWaitError: 42 секунды")
        return list(self._история)


def собрать(tmp_path, *, канал, салон, лог, ответы=None, белый={7},
            наблюдение=False):
    return собрать_систему(
        канал=канал, салон=салон, провайдер=FakeProvider(ответы or []),
        белый=set(белый), наблюдение=наблюдение, лог=лог, корень=tmp_path,
    )


# --- 1. Выключатель ----------------------------------------------------------

@pytest.mark.asyncio
async def test_stop_файл_подключён(tmp_path, салон, лог):
    """ГЛАВНЫЙ. STOP рядом с main.py обязан глушить всё.

    Отвергает реализацию, которая не передаёт `файл_выключателя` в Sender:
    убери этот аргумент из `собрать_систему` — Sender молча получит None,
    выключатель перестанет существовать, и ни один другой тест этого не увидит,
    потому что все они конструируют Sender сами.
    """
    канал = ФейкКанал()
    с = собрать(tmp_path, канал=канал, салон=салон, лог=лог,
                ответы=[Ответ(reply="Здравствуйте!"), Ответ(reply="Здравствуйте!")])

    await с.обработчик(входящее("привет"))
    await с.дирижёр.обработать(7)
    assert канал.отправленное, "без STOP ответ обязан уйти — иначе тест ниже пустой"

    (tmp_path / "STOP").write_text("", encoding="utf-8")
    канал.отправленное.clear()

    await с.обработчик(входящее("привет ещё раз", сдвиг_сек=30))
    await с.дирижёр.обработать(7)
    assert канал.отправленное == [], "STOP не заглушил — выключатель не подключён"


# --- 2. Белый список --------------------------------------------------------

@pytest.mark.asyncio
async def test_белый_список_доходит_до_обоих_заслонов(tmp_path, салон, лог):
    """Белый список нужен И приёму, И отправителю — это два разных заслона.

    Отвергает реализацию, которая передаёт список только в один из них: подставь
    `белый_список=set()` в Sender внутри `собрать_систему` — свой же клиент
    перестанет получать ответы, и это заметит только этот тест.
    """
    канал = ФейкКанал()
    с = собрать(tmp_path, канал=канал, салон=салон, лог=лог, белый={7},
                ответы=[Ответ(reply="Здравствуйте!")])

    await с.обработчик(входящее("привет", чат=7))
    await с.дирижёр.обработать(7)
    assert канал.отправленное, "клиент из белого списка обязан получить ответ"

    канал.отправленное.clear()
    await с.обработчик(входящее("привет", чат=999, сдвиг_сек=30))
    await с.дирижёр.обработать(999)
    assert канал.отправленное == [], "чужому чату ответа быть не должно"


# --- 3. Отказ истории -------------------------------------------------------

@pytest.mark.asyncio
async def test_отказ_истории_не_ломает_ответ(tmp_path, салон, лог):
    """ГЛАВНЫЙ. Telegram отказал на истории — клиент всё равно получает ответ.

    Отвергает реализацию без try/except вокруг `канал.история`: исключение
    улетит из обработчика, ответ не уйдёт, а клиент будет ждать. Проверяем и
    то, что причина попала в лог, — иначе отказ станет невидимым.
    """
    канал = ФейкКанал(падать=True)
    с = собрать(tmp_path, канал=канал, салон=салон, лог=лог,
                ответы=[Ответ(reply="Здравствуйте!")])

    await с.обработчик(входящее("привет"))
    await с.дирижёр.обработать(7)

    assert канал.запросов_истории == 1, "историю обязаны были попытаться прочитать"
    assert канал.отправленное, "отказ истории не должен отменять ответ"
    причины = [з.get("причина", "") for з in лог.записи]
    assert any("история недоступна" in п for п in причины), (
        "отказ истории обязан попасть в лог, иначе он невидим"
    )


@pytest.mark.asyncio
async def test_история_из_канала_доходит_до_модели(tmp_path, салон, лог):
    """История читается из Telegram и доезжает до промпта.

    Отвергает реализацию, где `история_кэш` наполняется, но в Дирижёр передана
    другая функция (или `lambda ч, n: []`): модель потеряет контекст диалога и
    начнёт каждый ответ с нуля. Молчаливая деградация — ни одного падения.
    """
    канал = ФейкКанал(история=[
        {"текст": "сколько стоит массаж спины", "наше": False},
        {"текст": "120 ₾ за 60 минут", "наше": True},
    ])
    с = собрать(tmp_path, канал=канал, салон=салон, лог=лог,
                ответы=[Ответ(reply="Здравствуйте!")])

    await с.обработчик(входящее("а какие мастера?"))
    await с.дирижёр.обработать(7)

    _, сообщения = с.дирижёр.провайдер.вызовы[0]
    склеено = " ".join(str(м.get("content", "")) for м in сообщения)
    assert "120" in склеено, "прошлый ответ салона обязан быть в контексте"


