@pytest.mark.asyncio
async def test_лента_собирается_ОДНИМ_запросом(канал):
    """ГЛАВНЫЙ. Сборка ленты не имеет права ходить в историю по чату.

    У чтения истории лимит около 10 запросов за 30 секунд. Реализация «пройти
    по чатам и у каждого спросить последнее сообщение» выбьет лимит на десятом
    чате, и дальше страница администратора покажет пустоту — причём именно в
    рабочий день, когда чатов много.

    Отвергает такую реализацию прямо: проверяем, что `get_messages` НЕ звался.
    """
    канал.клиент.диалоги = [
        ФейкДиалог(7, "Клиент", ФейкСообщение("привет")),
        ФейкДиалог(9, "Второй", ФейкСообщение("сколько стоит")),
    ]
    лента = await канал.диалоги(50)
    assert len(лента) == 2
    assert канал.клиент.вызовы_get_dialogs, "get_dialogs должен быть вызван"
    assert канал.клиент.вызовы_get_messages == [], (
        "лента обязана обходиться одним запросом: история по чату выбьет лимит"
    )


@pytest.mark.asyncio
async def test_группы_и_каналы_в_ленту_не_попадают(канал):
    """В группах мы намеренно не отвечаем — в ленте им делать нечего.

    Отвергает реализацию без проверки `is_user`: администратор увидел бы
    служебные группы и каналы вперемешку с клиентами.
    """
    канал.клиент.диалоги = [
        ФейкДиалог(7, "Клиент", ФейкСообщение("привет")),
        ФейкДиалог(-100, "Группа салона", ФейкСообщение("что-то"), личный=False),
        ФейкДиалог(-200, "Канал новостей", ФейкСообщение("новость"), личный=False),
    ]
    лента = await канал.диалоги(50)
    assert [д.чат_id for д in лента] == [7]


@pytest.mark.asyncio
async def test_пустой_чат_не_роняет_ленту(канал):
    """Чат без сообщений бывает: контакт добавлен, переписки нет.

    Отвергает обращение к `.text` у отсутствующего сообщения — одна такая
    строка в аккаунте, и лента падает целиком.
    """
    канал.клиент.диалоги = [ФейкДиалог(7, "Пустой", сообщение=None)]
    лента = await канал.диалоги(50)
    assert лента[0].последнее == ""
    assert лента[0].когда is None


@pytest.mark.asyncio
async def test_поля_ленты_переносятся_как_есть(канал):
    """Непрочитанные — счётчик мессенджера, и он переносится без толкования.

    «Нужен ответ» — это НЕ непрочитанные: бот мог сам закрыть чат, а значок
    остался. Смешивать их в этом слое нельзя, различает их уже окно.
    """
    сообщение = ФейкСообщение("последнее слово")
    канал.клиент.диалоги = [ФейкДиалог(7, "Гиорги", сообщение, непроч=35)]
    д = (await канал.диалоги(50))[0]
    assert (д.чат_id, д.имя, д.непрочитанных) == (7, "Гиорги", 35)
    assert д.последнее == "последнее слово"
    assert д.канал == "telegram", "канал обязан называть себя: в ленте их будет несколько"
    assert д.когда is сообщение.date

