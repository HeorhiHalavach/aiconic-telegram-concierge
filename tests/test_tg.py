"""Канал Telegram: проверяем то, что можно проверить без живого аккаунта.

Живой вход по номеру и коду проверить тестом нельзя — это в списке того,
что подтверждается только первым реальным запуском. Но КАК мы зовём
telethon — проверить можно, подменив клиент.
"""

from __future__ import annotations

from datetime import datetime, timezone

import pytest

from aiconic.tg import TelegramКанал


class ФейкСообщение:
    def __init__(self, текст, наше=False, дата=None):
        self.text = текст
        self.out = наше
        self.date = дата or datetime.now(timezone.utc)


class ФейкДиалог:
    """Как telethon.tl.custom.Dialog, но только те поля, которыми мы пользуемся."""

    def __init__(self, id_, имя, сообщение=None, непроч=0, личный=True):
        self.id = id_
        self.name = имя
        self.message = сообщение
        self.unread_count = непроч
        self.is_user = личный


class ФейкКлиент:
    def __init__(self, сообщения=None, диалоги=None):
        self.сообщения = сообщения or []
        self.диалоги = диалоги or []
        self.вызовы_get_messages: list[dict] = []
        self.вызовы_get_dialogs: list[dict] = []
        self.отправленное: list[tuple[int, str]] = []

    async def get_messages(self, чат_id, **kw):
        self.вызовы_get_messages.append({"чат": чат_id, **kw})
        return self.сообщения

    async def get_dialogs(self, **kw):
        self.вызовы_get_dialogs.append(kw)
        return self.диалоги

    async def send_message(self, чат_id, текст):
        self.отправленное.append((чат_id, текст))


@pytest.fixture
def канал() -> TelegramКанал:
    к = TelegramКанал.__new__(TelegramКанал)   # без реального входа в аккаунт
    к.белый_список = {7}
    к.клиент = ФейкКлиент()
    return к


@pytest.mark.asyncio
async def test_история_запрашивается_от_старых_к_новым(канал):
    """Отвергает забытый reverse=True.

    Без него telethon отдаёт «from newest to oldest», и модель увидела бы
    разговор задом наперёд. Проверяем сам вызов, а не его последствия.
    """
    await канал.история(7, 20)
    вызов = канал.клиент.вызовы_get_messages[-1]
    assert вызов["reverse"] is True, "история должна запрашиваться reverse=True"
    assert вызов["limit"] == 20


@pytest.mark.asyncio
async def test_история_разбирается_в_нужную_форму(канал):
    канал.клиент.сообщения = [
        ФейкСообщение("здравствуйте", наше=False),
        ФейкСообщение("здравствуйте! чем помочь?", наше=True),
    ]
    итог = await канал.история(7, 20)
    assert [m["наше"] for m in итог] == [False, True]
    assert итог[0]["текст"] == "здравствуйте"
    assert итог[0]["дата"].tzinfo is not None, "дата обязана быть tz-aware"


@pytest.mark.asyncio
async def test_сообщение_без_текста_не_ломает_разбор(канал):
    """У голосовых text пустой, у служебных — None."""
    канал.клиент.сообщения = [ФейкСообщение(None), ФейкСообщение("")]
    итог = await канал.история(7, 20)
    assert [m["текст"] for m in итог] == ["", ""]


@pytest.mark.asyncio
async def test_отправка_идёт_в_нужный_чат(канал):
    await канал.отправить(7, "привет")
    assert канал.клиент.отправленное == [(7, "привет")]


def test_read_acknowledge_не_вызывается_нигде():
    """Мы намеренно не помечаем сообщения прочитанными: непрочитанные
    у администратора должны вести себя как обычно."""
    from pathlib import Path

    import re

    пакет = Path(__file__).resolve().parent.parent / "aiconic"
    вызовы = []
    # rglob, а не glob: у заслона границ импортов ровно здесь была дыра —
    # файл во вложенной папке проходил мимо проверки. Найдено 2026-08-15 при
    # чертеже этапа 2, где появляется пакет aiconic/inbox/.
    for файл in пакет.rglob("*.py"):
        # ищем именно ВЫЗОВ, а не упоминание в docstring
        if re.search(r"send_read_acknowledge\s*\(", файл.read_text(encoding="utf-8")):
            вызовы.append(файл.name)
    assert not вызовы, f"найден вызов send_read_acknowledge в {вызовы}"


