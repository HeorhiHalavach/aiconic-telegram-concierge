# --- 3. Отсечка по старту снимается только для догоняющих -------------------

@pytest.mark.asyncio
async def test_догоняющее_сообщение_обрабатывается(сделать_дирижёра, транспорт):
    """ГЛАВНЫЙ. Клиент написал ночью, процесс подняли утром — ответ обязан быть.

    Отвергает реализацию, где отсечка «старше запуска» безусловна: сообщение,
    пришедшее пока процесс лежал, не получало ответа НИКОГДА. Для продукта,
    который держится на отложенных ответах, это дыра, а не защита.
    """
    д, _ = сделать_дирижёра([Ответ(reply="Массаж спины — 120 ₾.")])
    ночью = datetime.now(timezone.utc) - timedelta(hours=6)

    await д.принять(Входящее(
        чат_id=7, текст="сколько стоит массаж спины?", дата=ночью,
        личный=True, догоняем=True,
    ))
    await д.обработать(7)
    assert транспорт.отправленное, "догоняющее сообщение обязано быть отвечено"


@pytest.mark.asyncio
async def test_старое_сообщение_без_флага_по_прежнему_отсекается(
    сделать_дирижёра, транспорт
):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Заслон от ответа на весь backlog остаётся на месте.

    Отвергает «починку» через сдвиг времени старта назад: с ней первый запуск
    ответил бы на всю непрочитанную переписку, а после каждого перезапуска —
    ещё раз на то, что уже отвечено.
    """
    д, _ = сделать_дирижёра([Ответ(reply="Массаж спины — 120 ₾.")])
    ночью = datetime.now(timezone.utc) - timedelta(hours=6)

    await д.принять(Входящее(
        чат_id=7, текст="сколько стоит массаж спины?", дата=ночью, личный=True,
    ))
    await д.обработать(7)
    assert транспорт.отправленное == [], "старое сообщение без флага не отвечаем"


@pytest.mark.asyncio
async def test_догоняющее_проходит_остальные_заслоны(сделать_дирижёра, транспорт):
    """Флаг снимает ОДНУ проверку, а не все.

    Отвергает реализацию, где `догоняем` пропускает сообщение мимо белого
    списка, мимо «не личный чат» и мимо проверки таймзоны: тогда добор стал бы
    дырой в трёх заслонах вместо одного.
    """
    д, _ = сделать_дирижёра([Ответ(reply="…")])
    ночью = datetime.now(timezone.utc) - timedelta(hours=6)

    for кейс in (
        {"чат_id": 999, "личный": True},         # чужой чат
        {"чат_id": 7, "личный": False},          # группа
        {"чат_id": 7, "личный": True, "исходящее": True},   # наше же сообщение
    ):
        await д.принять(Входящее(
            текст="сколько стоит?", дата=ночью, догоняем=True,
            **{"чат_id": кейс.pop("чат_id"), **кейс},
        ))
    await д.обработать(7)
    await д.обработать(999)
    assert транспорт.отправленное == [], (
        "догоняющий флаг снимает только отсечку по старту"
    )


def test_наивная_дата_у_догоняющего_всё_равно_отвергается():
    """tz-aware обязателен и для добора: иначе сравнение упадёт в бою."""
    приём = guards.Приём(белый_список={7}, старт=datetime.now(timezone.utc))
    причина = приём.причина_отказа(
        чат_id=7, личный=True, исходящее=False,
        дата=datetime(2026, 8, 13, 10, 0), догоняем=True,
    )
    assert причина == "дата без таймзоны — не доверяем"
