"""Отказ записи ПОСЛЕ отправки ответа обязан дойти до клиента.

Единственное место в системе, где защита была отчётом, а не заслоном (§26).
Порядок такой: ответ модели «записала вас на 13:00» уходит клиенту → и только
потом `Booker` пытается создать запись. Если он отказал (окно успели занять,
модель назвала непредложенное время, дата не по ISO), записи не появлялось, а
клиент считал себя записанным. Об этом знал ТОЛЬКО лог.

Главные тесты здесь — первые два, и они противоположны по смыслу:
  отказ → клиент обязан узнать;
  дубль → клиент обязан НЕ узнать, потому что он правда записан.
"""

from __future__ import annotations

import pytest
from conftest import ЧЕТВЕРГ, входящее

from aiconic.llm import Ответ
from aiconic.sender import ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА

ВРЕМЯ = "13:00"


def запись(время: str = ВРЕМЯ, мастер: int = 1, дата: str | None = None) -> dict:
    return {
        "мастер": мастер,
        "дата": дата or ЧЕТВЕРГ.isoformat(),
        "время": время,
        "услуга": "back60",
    }


def последнее(транспорт) -> str:
    return транспорт.отправленное[-1][1] if транспорт.отправленное else ""


# --- 1. Отказ обязан дойти до клиента ---------------------------------------

@pytest.mark.asyncio
async def test_непредложенное_время_клиент_узнаёт(
    сделать_дирижёра, транспорт, салон
):
    """ГЛАВНЫЙ. Модель пообещала запись на время, которого мы не предлагали.

    Отвергает реализацию, которая только пишет в лог: клиент прочитал
    «записала вас», записи нет, и он об этом не узнал.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Записала вас на 13:00.", booking=запись())
    ])
    # Клиент ПРОСИТ записать, но времени не называет → 13:00 непредложенное.
    # Просьба важна: без неё поправка не отправляется намеренно — см.
    # test_apology.py. Раньше здесь стоял вопрос про цену, и тест проверял
    # правило, которого больше нет.
    await д.принять(входящее("запишите меня на массаж спины"))
    await д.обработать(7)

    assert len(салон.записи) == было, "записи быть не должно"
    assert len(транспорт.отправленное) == 2, (
        "клиент должен получить ДВА сообщения: ответ модели и поправку"
    )
    assert последнее(транспорт) == ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА
    assert "администратор" in последнее(транспорт).lower()


@pytest.mark.asyncio
async def test_занятое_время_клиент_узнаёт(сделать_дирижёра, транспорт, салон):
    """Окно заняли между предложением и подтверждением — настоящая гонка."""
    д, _ = сделать_дирижёра([
        Ответ(reply="Свободно сегодня в 13:00, подтвердите."),
        Ответ(reply="Записала вас на 13:00.", booking=запись()),
    ])
    await д.принять(входящее("когда свободно?"))
    await д.обработать(7)

    # пока клиент думал, окно занял кто-то другой
    салон.записи.append({"чат": 0, "мастер": 1, "дата": ЧЕТВЕРГ.isoformat(),
                         "начало": ВРЕМЯ, "длительность": 60,
                         "услуга": "back60", "клиент": "другой"})

    await д.принять(входящее("да, давайте", сдвиг_сек=20))
    await д.обработать(7)

    assert последнее(транспорт) == ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА


@pytest.mark.asyncio
async def test_дата_не_по_iso_клиент_узнаёт(сделать_дирижёра, транспорт, салон):
    """Модель отдаёт «14.08.2026» примерно в половине случаев.

    Записи при этом не создаётся, и раньше это тоже был только лог.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Записала вас на 13:00.", booking=запись(дата="13.08.2026"))
    ])
    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)

    assert len(салон.записи) == было
    assert последнее(транспорт) == ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА


# --- 2. Дубль — обратный случай: клиент узнавать НЕ должен -------------------

@pytest.mark.asyncio
async def test_дубль_клиент_не_получает_поправку(
    сделать_дирижёра, транспорт, салон
):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Клиент сказал «да» дважды — он записан.

    Подтверждение, которое он прочитал, — правда. Сказать ему «не получилось»
    было бы хуже молчания. Но и промолчать нельзя: имитация 13.08 показала, как
    модель второй раз отвечает «Записываю вас», и клиент не понимает, записан он
    один раз или два. Поэтому вместо поправки уходит прямая справка о том, на
    что он УЖЕ записан, собранная кодом из существующей записи.

    Отвергает две реализации:
      1) поправка на любой `ЗаписьОтклонена` — сделайте `_проверить_дубль`
         обычным отказом, и клиент получит «не получилось», хотя он записан;
      2) молчание на дубль — уберите вызов `_сказать_что_уже_записан`, и клиент
         второй раз услышит «Записываю вас» без единого уточнения.
    """
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.", booking=запись()),
        Ответ(reply="Записываю вас.", booking=запись()),
    ])
    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)
    сколько_после_первого = len(транспорт.отправленное)
    assert сколько_после_первого == 2, "первый раз: ответ модели + подтверждение"
    записей_после_первого = len(салон.записи)

    await д.принять(входящее("запишите на 13:00", сдвиг_сек=20))
    await д.обработать(7)

    assert len(салон.записи) == записей_после_первого, "дубля в файле быть не должно"
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА not in последнее(транспорт), (
        "клиент записан, а ему сказали «не получилось»"
    )
    п = последнее(транспорт)
    assert "уже записаны" in п.lower(), (
        "на повторную просьбу клиент обязан узнать, что он уже записан"
    )
    assert "13:00" in п and "Массаж спины" in п, (
        "справка обязана называть, на ЧТО он записан, — иначе она бесполезна"
    )
    assert "Готово, вы записаны" not in п, "это не новая запись, а справка о старой"


@pytest.mark.asyncio
async def test_дубль_без_просьбы_не_даёт_справки(сделать_дирижёра, транспорт):
    """Обратный к обратному: непрошеная справка — такой же шум, как извинение.

    Клиент спросил про цену, модель забежала вперёд и попыталась записать на
    время, где он уже записан. Отвергает реализацию, которая шлёт «вы уже
    записаны» на любой дубль: уберите условие `просил_записать`, и клиент на
    вопрос о цене получит справку о записи, о которой не спрашивал.
    """
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.", booking=запись()),
        Ответ(reply="Массаж спины — 120 ₾.", booking=запись()),
    ])
    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)
    было = len(транспорт.отправленное)

    await д.принять(входящее("а сколько стоит массаж спины?", сдвиг_сек=20))
    await д.обработать(7)

    assert len(транспорт.отправленное) == было + 1, (
        "только ответ модели: справка о записи здесь непрошеная"
    )
    assert "уже записаны" not in последнее(транспорт).lower()


# --- 3. Успех и молчание -----------------------------------------------------

@pytest.mark.asyncio
async def test_успешная_запись_подтверждается_кодом(
    сделать_дирижёра, транспорт, салон
):
    """Получилось — клиент получает подтверждение, собранное КОДОМ.

    Модель в подтверждениях врала живьём: «14:08» вместо 14.08, «14.08.2026»
    вместо ISO. Здесь каждое значение взято из записи, попавшей в файл.
    """
    было = len(салон.записи)
    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.", booking=запись())
    ])
    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)

    assert len(салон.записи) == было + 1
    assert len(транспорт.отправленное) == 2, "ответ модели + подтверждение кодом"
    п = последнее(транспорт)
    assert "записаны" in п.lower()
    assert "13:00" in п
    assert "Массаж спины" in п, "услуга берётся из прайса"
    assert "Нино" in п, "мастер берётся из расписания"
    assert "120" in п, "цена берётся из прайса"
    assert ШАБЛОН_ЗАПИСЬ_НЕ_ВЫШЛА not in п


@pytest.mark.asyncio
async def test_подтверждение_не_проходит_сверку_времени(
    сделать_дирижёра, транспорт, салон
):
    """Несущая деталь: подтверждение идёт БЕЗ сверки времени.

    Сразу после записи это время уже занято — своей же записью. Прогони
    подтверждение через заслон времени, и он пометил бы верный текст
    выдуманным. Отвергает отправку подтверждения через `отправить_ответ`.
    """
    д, _ = сделать_дирижёра([Ответ(reply="Записываю вас.", booking=запись())])
    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)

    assert "13:00" in последнее(транспорт), (
        "подтверждение с временем записи обязано дойти до клиента"
    )
    assert not салон.окно_свободно(ЧЕТВЕРГ, ВРЕМЯ, 60, 1), (
        "окно после записи занято — значит заслон времени его бы отверг"
    )


