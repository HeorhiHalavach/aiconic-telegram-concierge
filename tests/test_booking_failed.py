@pytest.mark.asyncio
async def test_поправка_слушается_stop(сделать_дирижёра, транспорт, лог, салон,
                                      tmp_path):
    """Поправка идёт через Sender, значит подчиняется выключателю."""
    from aiconic import guards
    from aiconic.app import Дирижёр
    from aiconic.llm import FakeProvider
    from aiconic.sender import Sender
    from datetime import datetime, timezone

    стоп = tmp_path / "STOP"
    отправитель = Sender(транспорт, салон, белый_список={7},
                         файл_выключателя=стоп, лог=лог)
    д = Дирижёр(
        салон=салон, провайдер=FakeProvider([
            Ответ(reply="Записала вас на 13:00.", booking=запись())
        ]),
        sender=отправитель,
        приём=guards.Приём(белый_список={7}, старт=datetime.now(timezone.utc)),
        лог=лог, история=lambda ч, n: [], сегодня=lambda: ЧЕТВЕРГ,
        пауза_группировки=0.0,
    )

    await д.принять(входящее("сколько стоит массаж спины?"))
    await д.обработать(7)
    assert транспорт.отправленное, "первый ответ должен был уйти"

    стоп.write_text("", encoding="utf-8")
    транспорт.отправленное.clear()

    await д.принять(входящее("сколько стоит массаж спины?", сдвиг_сек=20))
    await д.обработать(7)
    assert транспорт.отправленное == [], "STOP обязан заткнуть и поправку"
