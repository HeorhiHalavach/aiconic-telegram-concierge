"""Напоминания: за день и за 2 часа.

Первое в проекте, что уходит клиенту ПЕРВЫМ. Значит цена ошибки другая: не
«неудачный ответ», а «сообщение, которого никто не просил». Поэтому тесты здесь
проверяют в первую очередь запрещённые исходы — двойную отправку, отправку
после визита, отправку о вчерашнем визите после простоя.

Часов внутри модуля нет: «сейчас» приходит аргументом, поэтому проверяется всё
и без ожидания.
"""

from __future__ import annotations

import asyncio
from datetime import datetime, timedelta, timezone

import pytest

from aiconic import reminders as нап

ВИЗИТ = {"дата": "2026-08-14", "начало": "14:00", "мастер": 2,
         "услуга": "back60", "чат": 7}


def utc(строка: str) -> datetime:
    return datetime.fromisoformat(строка).replace(tzinfo=timezone.utc)


# --- расчёт моментов ---------------------------------------------------------

def test_визит_переводится_в_utc():
    """14:00 в Тбилиси (UTC+4) — это 10:00 UTC. Смешать зоны нельзя."""
    assert нап.начало_визита(ВИЗИТ) == utc("2026-08-14 10:00")


def test_моменты_напоминаний():
    assert нап.момент(ВИЗИТ, нап.ЗА_ДЕНЬ) == utc("2026-08-13 10:00")
    assert нап.момент(ВИЗИТ, нап.ЗА_2_ЧАСА) == utc("2026-08-14 08:00")


@pytest.mark.parametrize("битая", [
    {"дата": "14.08.2026", "начало": "14:00"},   # не ISO — живьём приходит и так
    {"дата": "2026-08-14", "начало": "утром"},
    {"дата": "2026-08-14"},
    {},
])
def test_битая_запись_не_роняет_расчёт(битая):
    """Модель отдаёт дату не по ISO в половине случаев — падать нельзя."""
    assert нап.начало_визита(битая) is None
    assert нап.созревшие([битая], utc("2026-08-13 12:00")) == []


def test_наивное_сейчас_отвергается():
    """Заслон: без зоны сравнение времён даёт молчаливо неверный результат."""
    with pytest.raises(ValueError):
        нап.созревшие([ВИЗИТ], datetime(2026, 8, 13, 12, 0))


# --- что созрело -------------------------------------------------------------

def test_до_срока_не_созревает():
    assert нап.созревшие([ВИЗИТ], utc("2026-08-13 09:59")) == []


def test_за_день_созревает_ровно_в_момент():
    """Граница: ровно момент — уже пора. Отвергает `>` вместо `>=`."""
    итог = нап.созревшие([ВИЗИТ], utc("2026-08-13 10:00"))
    assert итог == [(0, нап.ЗА_ДЕНЬ, [нап.ЗА_ДЕНЬ])]


def test_за_2_часа_созревает_отдельно():
    запись = dict(ВИЗИТ, напомнили=[нап.ЗА_ДЕНЬ])
    итог = нап.созревшие([запись], utc("2026-08-14 08:00"))
    assert итог == [(0, нап.ЗА_2_ЧАСА, [нап.ЗА_2_ЧАСА])]


def test_отмеченное_второй_раз_не_уходит():
    """ГЛАВНЫЙ заслон от двойной отправки."""
    запись = dict(ВИЗИТ, напомнили=[нап.ЗА_ДЕНЬ, нап.ЗА_2_ЧАСА])
    assert нап.созревшие([запись], utc("2026-08-14 09:00")) == []


def test_созрели_оба_уходит_только_ближайшее():
    """Процесс лежал сутки. Два сообщения подряд выглядят как сбой.

    Отвергает наивную реализацию «отправить всё, что созрело».
    """
    итог = нап.созревшие([ВИЗИТ], utc("2026-08-14 09:00"))
    (индекс, к_отправке, к_гашению) = итог[0]
    assert к_отправке == нап.ЗА_2_ЧАСА, "уйти должно ближайшее к визиту"
    assert set(к_гашению) == {нап.ЗА_ДЕНЬ, нап.ЗА_2_ЧАСА}, (
        "дальнее обязано погаситься без отправки, иначе уйдёт следующим тиком"
    )


def test_после_начала_визита_ничего_не_уходит():
    """Заслон от рассылки о вчерашних визитах после простоя."""
    итог = нап.созревшие([ВИЗИТ], utc("2026-08-14 10:00"))
    (индекс, к_отправке, к_гашению) = итог[0]
    assert к_отправке == "", "визит начался — напоминать нечего"
    assert set(к_гашению) == {нап.ЗА_ДЕНЬ, нап.ЗА_2_ЧАСА}


def test_старый_визит_гасится_а_не_рассылается():
    старый = {"дата": "2026-08-01", "начало": "14:00", "чат": 7}
    итог = нап.созревшие([старый], utc("2026-08-14 09:00"))
    assert итог == [(0, "", [нап.ЗА_ДЕНЬ, нап.ЗА_2_ЧАСА])]


def test_несколько_записей_разбираются_независимо():
    другой = {"дата": "2026-08-20", "начало": "11:00", "чат": 9}
    итог = нап.созревшие([ВИЗИТ, другой], utc("2026-08-13 10:00"))
    assert [(i, в) for i, в, _ in итог] == [(0, нап.ЗА_ДЕНЬ)]


# --- текст -------------------------------------------------------------------

def test_текст_называет_время_услугу_и_мастера():
    т = нап.текст(ВИЗИТ, нап.ЗА_ДЕНЬ, "Массаж спины", "Мариам")
    assert "14:00" in т and "Массаж спины" in т and "Мариам" in т
    assert "завтра" in т


def test_текст_за_2_часа_отличается():
    т = нап.текст(ВИЗИТ, нап.ЗА_2_ЧАСА, "Массаж спины", "Мариам")
    assert "через 2 часа" in т and "завтра" not in т


def test_текст_предлагает_перенос():
    """Напоминание обязано давать выход: иначе это односторонняя рассылка."""
    т = нап.текст(ВИЗИТ, нап.ЗА_ДЕНЬ, "Массаж спины", "Мариам")
    assert "напишите" in т.lower()


# --- обещание в промпте ------------------------------------------------------

def test_промпт_молчит_про_напоминания_когда_рассылка_выключена(салон):
    """Заслон от обещания, которого система не выполнит.

    ⚠️ Гарантия переехала: раньше промпт велел модели пообещать напоминания,
    теперь обещание стоит в подтверждении записи, которое собирает КОД. В
    промпте осталась одна строка — «сам про напоминания не пиши», — и её при
    выключенной рассылке быть не должно.
    """
    from datetime import date as _date

    from aiconic import prompt

    с = prompt.собрать(салон, _date(2026, 8, 13), напоминания=True)
    без = prompt.собрать(салон, _date(2026, 8, 13), напоминания=False)

    assert "напоминани" in с.lower()
    assert "напоминани" not in без.lower(), (
        "промпт говорит про напоминания при выключенной рассылке"
    )


@pytest.mark.parametrize("включены", [True, False])
@pytest.mark.asyncio
async def test_подтверждение_обещает_напоминания_только_когда_включены(
    сделать_дирижёра, транспорт, включены
):
    """ГЛАВНЫЙ про флаг. Обещание живёт в подтверждении, значит там и проверяем.

    Отвергает дирижёра, который флаг принял и проигнорировал: с выключенной
    рассылкой клиент не должен услышать «напомним».
    """
    from conftest import ЧЕТВЕРГ, входящее

    from aiconic.llm import Ответ

    д, _ = сделать_дирижёра([
        Ответ(reply="Записываю вас.",
              booking={"мастер": 1, "дата": ЧЕТВЕРГ.isoformat(),
                       "время": "13:00", "услуга": "back60"})
    ])
    д.напоминания = включены

    await д.принять(входящее("запишите на 13:00"))
    await д.обработать(7)

    подтверждение = транспорт.отправленное[-1][1]
    assert "записаны" in подтверждение.lower(), подтверждение
    assert ("напомним" in подтверждение.lower()) is включены, подтверждение


# --- сам цикл рассылки: единственное место, которое пишет первым -------------

def _визит_через(минут: int) -> dict:
    """Запись с визитом через N минут — чтобы оба срока уже наступили."""
    местное = datetime.now(нап.ЗОНА_САЛОНА) + timedelta(minutes=минут)
    return {"чат": 7, "мастер": 1, "услуга": "back60",
            "дата": местное.date().isoformat(),
            "начало": местное.strftime("%H:%M")}


async def _один_тик(салон, отправитель, лог) -> None:
    import main
    задача = asyncio.create_task(
        main._цикл_напоминаний(салон, отправитель, лог, интервал=0)
    )
    await asyncio.sleep(0.05)
    задача.cancel()
    try:
        await задача
    except asyncio.CancelledError:
        pass


@pytest.mark.asyncio
async def test_цикл_отправляет_ровно_одно_напоминание(
    салон, отправитель, транспорт, лог
):
    """РОВНО одно — не «хотя бы одно».

    Цикл крутится с нулевым интервалом, то есть за один тик успевает много
    оборотов. Если отметка не ставится, он шлёт на каждом обороте, пока не
    упрётся в лимит частоты — и проверка «хотя бы одно» этого не заметит.
    Первая версия теста была именно такой и мутацию пропускала.
    """
    салон.записи[:] = [_визит_через(90)]

    await _один_тик(салон, отправитель, лог)

    assert len(транспорт.отправленное) == 1, (
        f"ушло {len(транспорт.отправленное)} напоминаний вместо одного — "
        f"отметка не ставится"
    )
    чат, текст = транспорт.отправленное[0]
    assert чат == 7
    assert "Массаж спины" in текст and "Нино" in текст
    assert нап.ЗА_2_ЧАСА in салон.записи[0]["напомнили"], "не погашено"


@pytest.mark.asyncio
async def test_второй_тик_не_отправляет_повторно(салон, отправитель, транспорт, лог):
    """Заслон от рассылки на каждом тике — раз в минуту, всю ночь."""
    салон.записи[:] = [_визит_через(90)]

    await _один_тик(салон, отправитель, лог)
    assert len(транспорт.отправленное) == 1
    await _один_тик(салон, отправитель, лог)

    assert len(транспорт.отправленное) == 1, "напоминание ушло второй раз"


@pytest.mark.asyncio
async def test_отметка_цикла_попадает_на_диск(салон, отправитель, транспорт, лог):
    """Отметку должен записать САМ цикл, а не тест своими руками.

    Отвергает цикл, который отметил напоминание только в памяти: перезапуск
    процесса — и клиент получает его заново.
    """
    from aiconic.salon import Салон

    # Кладём на диск ровно одну запись БЕЗ отметки. Иначе тест зависит от
    # того, что лежит в data/bookings.yaml, — и живой прогон, дописавший туда
    # «напомнили», делает его зелёным при любой поломке. Так и случилось.
    салон.записи[:] = [_визит_через(90)]
    салон.сохранить_записи()
    assert not Салон(салон.каталог).записи[0].get("напомнили"), "исходное состояние"

    await _один_тик(салон, отправитель, лог)
    assert транспорт.отправленное

    заново = Салон(салон.каталог)
    assert len(заново.записи) == 1, "в файле должна быть только наша запись"
    assert нап.ЗА_2_ЧАСА in (заново.записи[0].get("напомнили") or []), (
        "цикл не сохранил отметку на диск — после перезапуска напомнит снова"
    )


@pytest.mark.asyncio
async def test_kill_switch_останавливает_напоминания(салон, транспорт, лог, tmp_path):
    """ГЛАВНЫЙ заслон: STOP обязан затыкать и то, что уходит первым.

    И отказ НЕ должен гасить напоминание — иначе снятие STOP оставит клиента
    без него навсегда.
    """
    from aiconic.sender import Sender

    стоп = tmp_path / "STOP"
    стоп.write_text("", encoding="utf-8")
    отправитель = Sender(транспорт, салон, белый_список={7},
                         файл_выключателя=стоп, лог=лог)
    салон.записи[:] = [_визит_через(90)]

    await _один_тик(салон, отправитель, лог)

    assert транспорт.отправленное == [], "STOP не остановил напоминание"
    assert not салон.записи[0].get("напомнили"), (
        "напоминание погашено без отправки — после снятия STOP оно не уйдёт"
    )


