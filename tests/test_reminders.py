class ПадающийТранспорт:
    """Роняет отправку так, как это делает tg.отправить при длинном FloodWait."""

    def __init__(self) -> None:
        self.попыток = 0

    async def отправить(self, чат_id: int, текст: str) -> None:
        self.попыток += 1
        raise RuntimeError("FloodWait 300s")


@pytest.mark.asyncio
async def test_сбой_отправки_не_убивает_рассылку(салон, лог):
    """ГЛАВНЫЙ заслон цикла: он не имеет права умереть молча.

    Задача создаётся через create_task — её исключение никто не забирает.
    Без перехвата рассылка прекратилась бы НАВСЕГДА, бот продолжал бы
    отвечать, и в логе не было бы ни строки.

    Отвергает цикл без `except Exception`: снимите его — тест увидит, что
    второй тик не состоялся.
    """
    import main
    from aiconic.sender import Sender

    транспорт = ПадающийТранспорт()
    отправитель = Sender(транспорт, салон, белый_список={7}, лог=лог)
    салон.записи[:] = [_визит_через(90)]

    задача = asyncio.create_task(
        main._цикл_напоминаний(салон, отправитель, лог, интервал=0)
    )
    await asyncio.sleep(0.05)
    жива = not задача.done()
    задача.cancel()
    try:
        await задача
    except asyncio.CancelledError:
        pass

    assert транспорт.попыток >= 2, (
        "после первого сбоя цикл больше не пытался — рассылка умерла молча"
    )
    assert жива, "задача рассылки погибла на первом же исключении"
    assert any("тик провален" in (з.get("причина") or "") for з in лог.записи), (
        "сбой не попал в лог — узнать о нём было бы нечем"
    )
    assert not салон.записи[0].get("напомнили"), (
        "напоминание погашено, хотя не отправилось"
    )


# --- гашение переживает перезапуск -------------------------------------------

def test_отметка_переживает_перезапуск_процесса(салон):
    """Настоящая гарантия, а не флаг в памяти.

    Отвергает реализацию, которая помнит отправленные напоминания только
    внутри процесса: упал, поднялся — и клиент получил напоминание второй раз.
    """
    from aiconic.salon import Салон

    салон.записи.append(dict(ВИЗИТ, напомнили=[нап.ЗА_ДЕНЬ]))
    салон.сохранить_записи()

    заново = Салон(салон.каталог)          # новый процесс читал бы так же
    наш = len(заново.записи) - 1
    assert заново.записи[наш].get("напомнили") == [нап.ЗА_ДЕНЬ], (
        "отметка не дожила до перечитывания файла"
    )

    # в фикстуре есть примеры со вчерашними визитами — они законно гасятся,
    # нас интересует только своя запись
    про_нашу = [
        (в, гасим) for i, в, гасим in нап.созревшие(заново.записи, utc("2026-08-13 12:00"))
        if i == наш
    ]
    assert про_нашу == [], (
        "после перезапуска напоминание за день созрело бы повторно"
    )
