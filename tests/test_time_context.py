"""Три правки заслона времени, найденные живым прогоном 2026-08-13, 21:30.

За один прогон заслон трижды задушил верный ответ, а один раз — верно поймал
галлюцинацию. Разбор каждого случая:

  1. клиент «запишите на завтра в 20:30» → ответ «в 20:30 есть 30-минутные
     сеансы» БЕЗ слова «завтра» → заслон сверил с сегодня и отверг.
     ⛔ ложное. День задаёт разговор, а не одна реплика.
  2. клиент «а в 23:00 можно?» → ответ «в 23:00 мы закрыты» → отверг.
     ⛔ ложное. Процитированное время — не выдумка.
  3. клиент «массаж спины» → ответ «сегодня свободен в 18:00» → отверг.
     ✅ ВЕРНО: 18:00 занято собственной записью клиента, модель взяла его из
     истории. Этот случай обязан ловиться и после правок.
  4. в 21:32 бот предложил «сегодня в 17:30» — время давно прошло.
     ⛔ расчёт окон не знал про текущее время вовсе.
"""

from __future__ import annotations

from datetime import date

import pytest
from conftest import УТРО, ЧЕТВЕРГ, входящее

from aiconic import guards, prompt
from aiconic.booker import Booker, ЗаписьОтклонена
from aiconic.llm import Ответ
from aiconic.salon import минут_сейчас

ОКНА = guards.Окна(
    по_дням={0: frozenset({"11:00", "13:00"}), 1: frozenset({"20:00", "20:30"})},
    метки={"сегодня": 0, "завтра": 1},
    часы=frozenset({"10:00", "21:00"}),
)


# --- 1. День берётся из вопроса клиента --------------------------------------

def test_день_из_вопроса_клиента_когда_в_ответе_метки_нет():
    """ГЛАВНЫЙ. Отвергает заслон, читающий только свой ответ.

    ⚠️ Время берём такое, которого клиент НЕ называл. Иначе сработает второе
    правило — освобождение по цитате, — и правило про день останется
    непроверенным. Первая версия теста была именно такой, и мутационная
    проверка это показала: снятие подстановки дня ничего не меняло.
    """
    ответ = "Уточните услугу: в 20:30 есть 30-минутные сеансы."
    assert guards.выдуманное_время(ответ, ОКНА, "а что свободно завтра?") == [], (
        "клиент сказал «завтра» — 20:30 завтра свободно"
    )
    assert guards.выдуманное_время(ответ, ОКНА, "а что свободно сегодня?") == ["20:30"], (
        "тот же ответ, но клиент спрашивал про сегодня — 20:30 сегодня занято"
    )


def test_метка_в_ответе_сильнее_метки_в_вопросе():
    """Ответ говорит про сегодня — значит про сегодня, что бы спрашивал клиент.

    Время берём такое, которого клиент НЕ называл: иначе сработает освобождение
    по цитате, и правило про день останется непроверенным. Первая версия этого
    теста была именно такой и ничего не проверяла.
    """
    ответ = "Сегодня в 20:00 свободно."
    assert guards.выдуманное_время(ответ, ОКНА, "а завтра свободно?") == ["20:00"], (
        "20:00 свободно завтра, но ответ говорит «сегодня»"
    )


def test_день_из_вопроса_не_ослабляет_заслон():
    """Обратная сторона: чужой день из вопроса не делает время законным."""
    ответ = "Свободно в 13:00."
    assert guards.выдуманное_время(ответ, ОКНА, "а что завтра?") == ["13:00"], (
        "13:00 свободно сегодня, но клиент спрашивал про завтра"
    )


# --- 2. Процитированное клиентом время — не выдумка --------------------------

@pytest.mark.parametrize("ответ, вопрос", [
    ("В 23:00 мы закрыты, работаем с 10:00 до 21:00.", "а в 23:00 можно?"),
    ("К сожалению, в 08:00 мы ещё закрыты.", "можно в 08:00?"),
])
def test_процитированное_время_проходит(ответ, вопрос):
    """ГЛАВНЫЙ. Верный отказ не должен уезжать администратору.

    Записать на такое время всё равно нельзя: `Booker` откажет, а клиент
    получит поправку — см. test_booking_failed.py.
    """
    assert guards.выдуманное_время(ответ, ОКНА, вопрос) == []


def test_не_процитированное_время_ловится_по_прежнему():
    """ЖИВОЙ СЛУЧАЙ 3. Отвергает реализацию, пропускающую всё при контексте.

    Клиент написал «массаж спины» — времени не называл. Модель предложила
    18:00, взяв его из истории, где стоит его же старая запись. Это настоящая
    галлюцинация, и она обязана ловиться.
    """
    ответ = "Массаж спины сегодня свободен в 18:00, а завтра в 13:00."
    лишние = guards.выдуманное_время(ответ, ОКНА, "массаж спины")
    assert "18:00" in лишние, "18:00 сегодня не свободно — обязано ловиться"


# --- 3. Прошедшее время не свободно ------------------------------------------

def test_окна_до_текущего_времени_отбрасываются(салон):
    полдень = 12 * 60
    все = салон.свободные_окна(ЧЕТВЕРГ, 60)
    после = салон.свободные_окна(ЧЕТВЕРГ, 60, не_раньше=полдень)

    assert "10:00" in все["Нино"], "исходно утренние окна есть"
    assert all(t >= "12:00" for t in после.get("Нино", [])), после
    assert len(после.get("Нино", [])) < len(все["Нино"])


def test_окно_остаётся_на_сетке_и_не_раньше_срока(салон):
    """Отсечка округляет ВВЕРХ: 12:15 → 12:30, а не назад к 12:00.

    ⚠️ Проверять только сетку недостаточно — округление вниз тоже даёт время
    на сетке, просто раньше срока. Мутационная проверка это и показала.
    """
    порог = 12 * 60 + 15
    после = салон.свободные_окна(ЧЕТВЕРГ, 60, не_раньше=порог)
    for имя, времена in после.items():
        assert all(t.endswith(":00") or t.endswith(":30") for t in времена), времена
        assert all(t >= "12:30" for t in времена), (
            f"{имя}: окно раньше порога 12:15 — округление пошло вниз: {времена}"
        )


def test_вечером_сегодняшних_окон_не_остаётся(салон):
    """В 21:30 салон закрыт — свободных окон на сегодня быть не должно."""
    поздно = 21 * 60 + 30
    assert салон.свободные_окна(ЧЕТВЕРГ, 60, не_раньше=поздно) == {}


def test_завтрашние_окна_не_отсекаются(салон):
    """`не_раньше` относится только к сегодня: у завтра прошедшего нет."""
    о = prompt.окна(салон, ЧЕТВЕРГ, сейчас_минут=21 * 60 + 30)
    assert о.по_дням[0] == frozenset(), "сегодня всё прошло"
    assert о.по_дням[1], "завтра окна остаются"


def test_записать_на_прошедшее_время_нельзя(салон):
    """Заслон записи, а не только предложения.

    Отвергает реализацию, где отсечка стоит лишь в промпте: клиент попросит
    прошедшее время сам, и запись создалась бы в прошлом.
    """
    b = Booker(салон)
    with pytest.raises(ЗаписьОтклонена):
        b.записать_синхронно(
            чат=7, день=ЧЕТВЕРГ, время="10:00", мастер_id=1,
            услуга_id="back60", предложенные=["10:00"],
            не_раньше=12 * 60,
        )


@pytest.mark.asyncio
async def test_дирижёр_не_записывает_на_прошедшее_время(транспорт, салон, лог):
    """Отсечка обязана стоять на пути ЗАПИСИ, а не только в промпте.

    Прямой вызов Booker с `не_раньше` проверяет сам заслон, но не то, что
    дирижёр ему это значение передаёт. Мутационная проверка показала разницу:
    убрал передачу в app.py — прямой тест остался зелёным.
    """
    from datetime import datetime, timezone

    from aiconic import guards
    from aiconic.app import Дирижёр
    from aiconic.llm import FakeProvider
    from aiconic.sender import Sender

    было = len(салон.записи)
    отправитель = Sender(транспорт, салон, белый_список={7}, лог=лог)
    д = Дирижёр(
        салон=салон,
        провайдер=FakeProvider([
            Ответ(reply="Записываю вас на 10:00.",
                  booking={"мастер": 1, "дата": ЧЕТВЕРГ.isoformat(),
                           "время": "10:00", "услуга": "back60"})
        ]),
        sender=отправитель,
        приём=guards.Приём(белый_список={7}, старт=datetime.now(timezone.utc)),
        лог=лог, история=lambda ч, n: [], сегодня=lambda: ЧЕТВЕРГ,
        сейчас_минут=lambda: 12 * 60,          # полдень: 10:00 уже прошло
        пауза_группировки=0.0,
    )

    await д.принять(входящее("запишите меня на 10:00"))
    await д.обработать(7)

    assert len(салон.записи) == было, "запись создана на прошедшее время"


def test_минут_сейчас_в_разумных_пределах():
    м = минут_сейчас()
    assert 0 <= м < 24 * 60


# --- 4. Через дирижёра целиком ------------------------------------------------

@pytest.mark.asyncio
async def test_отказ_с_процитированным_временем_доходит_до_клиента(
    сделать_дирижёра, транспорт
):
    """Живой случай 2 целиком: верный отказ обязан уйти клиенту."""
    д, _ = сделать_дирижёра([
        Ответ(reply="В 23:00 мы закрыты, работаем с 10:00 до 21:00. "
                    "Сегодня свободно 13:00.")
    ])
    await д.принять(входящее("а в 23:00 можно?"))
    await д.обработать(7)

    ушло = транспорт.отправленное[-1][1]
    assert "23:00" in ушло, "верный отказ подменён шаблоном"
    assert "администратор" not in ушло.lower()


@pytest.mark.asyncio
async def test_дирижёр_отдаёт_часы_в_промпт(сделать_дирижёра):
    """Отвергает дирижёра, который часы принял и не передал."""
    д, провайдер = сделать_дирижёра([Ответ(reply="ок")])
    await д.принять(входящее("когда свободно?"))
    await д.обработать(7)

    системный = провайдер.вызовы[-1][0]
    # УТРО = 09:00, значит 10:00 обязано быть в промпте
    assert "10:00" in системный
