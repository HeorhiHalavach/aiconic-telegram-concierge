"""Поиск услуги терпим к тому, как её называет модель.

Найдено имитацией 2026-08-13: модель прислала
`booking.услуга = "Массаж спины, 60 мин"` вместо `back60`. Поиск требовал точного
совпадения с id или названием, не нашёл — и НАСТОЯЩАЯ ЗАПИСЬ НЕ СОСТОЯЛАСЬ, а
клиент получил «записать не получилось».

Промпт теперь требует id, но строгий поиск превращал вариативность модели в
потерянного клиента. Терпимость здесь — не поддавки: она отображает вывод модели
на наши данные, а решение по-прежнему принимает код.

Главная тонкость — одноимённые услуги: «Классический массаж» есть на 60 и на 90
минут с разными id и разной ценой. Без длительности различить нельзя, и тогда
правильный ответ — отказать, а не угадать.
"""

from __future__ import annotations

import pytest


# --- по id: как требует промпт -----------------------------------------------

@pytest.mark.parametrize("id_", ["back60", "back90", "classic60", "classic90",
                                 "relax60", "neck30", "foot30"])
def test_по_id(салон, id_):
    u = салон.услуга(id_)
    assert u is not None and u.id == id_


def test_регистр_id_не_важен(салон):
    assert салон.услуга("BACK60").id == "back60"


# --- по названию и по «название, N мин» ---------------------------------------

@pytest.mark.parametrize("что, ожидаем", [
    ("Массаж спины", "back60"),
    ("массаж спины", "back60"),
    # ЖИВОЙ СЛУЧАЙ: ровно эта строка стоила записи
    ("Массаж спины, 60 мин", "back60"),
    ("массаж спины 60 минут", "back60"),
    ("Массаж спины расширенный", "back90"),
    ("Массаж шеи и плеч, 30 мин", "neck30"),
    ("Массаж стоп (30 мин)", "foot30"),
    ("Расслабляющий массаж, 60 мин.", "relax60"),
])
def test_по_названию_с_длительностью(салон, что, ожидаем):
    u = салон.услуга(что)
    assert u is not None, что
    assert u.id == ожидаем, (что, u.id)


# --- одноимённые услуги: длительность различает -------------------------------

def test_длительность_различает_одноимённые(салон):
    """«Классический массаж» есть на 60 и 90 минут — с разной ценой."""
    assert салон.услуга("Классический массаж, 60 мин").id == "classic60"
    assert салон.услуга("Классический массаж 90 мин").id == "classic90"


def test_без_длительности_одноимённые_не_угадываются(салон):
    """ГЛАВНЫЙ. Отвергает реализацию, берущую первую подходящую.

    Между 130 ₾ за 60 минут и 180 ₾ за 90 угадывать нельзя: ошибка уедет
    клиенту как цена. Отказ приведёт к «не получилось» и вопросу от
    администратора — это дороже по времени, но честно.
    """
    assert салон.услуга("Классический массаж") is None


# --- чего быть не должно ------------------------------------------------------

@pytest.mark.parametrize("что", [
    "", "   ", "массаж головы", "лимфодренажный массаж",
    "массаж", "спины", "60 мин", "услуга",
])
def test_чужое_и_пустое_не_находится(салон, что):
    """Терпимость не должна превращаться в угадывание по обрывку.

    «массаж» подходит ко всем позициям, «спины» — к части названия. Ни то, ни
    другое не должно давать услугу: иначе модель запишет клиента наугад.
    """
    assert салон.услуга(что) is None, что


def test_none_не_роняет(салон):
    assert салон.услуга(None) is None


# --- через Booker целиком -----------------------------------------------------

def test_запись_по_человеческому_названию_проходит(салон):
    """Живой путь целиком: та самая строка, что стоила записи."""
    from datetime import date

    from aiconic.booker import Booker

    ПЯТНИЦА = date(2026, 8, 14)

    было = len(салон.записи)
    з = Booker(салон).записать_синхронно(
        чат=7, день=ПЯТНИЦА, время="11:00", мастер_id=1,
        услуга_id="Массаж спины, 60 мин", предложенные=["11:00"],
    )
    assert з.услуга == "back60"
    assert з.длительность == 60
    assert len(салон.записи) == было + 1


def test_запись_по_неразличимому_названию_отклоняется(салон):
    """Одноимённая услуга без длительности — отказ, а не случайный выбор."""
    from datetime import date

    from aiconic.booker import Booker, ЗаписьОтклонена

    ПЯТНИЦА = date(2026, 8, 14)

    было = len(салон.записи)
    with pytest.raises(ЗаписьОтклонена, match="нет в прайсе"):
        Booker(салон).записать_синхронно(
            чат=7, день=ПЯТНИЦА, время="11:00", мастер_id=1,
            услуга_id="Классический массаж", предложенные=["11:00"],
        )
    assert len(салон.записи) == было
