"""Вердикт имитации: ложное красное и ложное зелёное одинаково вредны.

Здесь проверяется не поведение салона, а честность самой обвязки. Причина
писать этот файл появилась дважды за два дня, и оба раза обвязка врала:

1. исчерпанный суточный лимит Cerebras дал 33 «провала», и это выглядело как
   регрессия кода — правишь то, что не сломано;
2. условие «отказов >= шагов // 3» на прогоне из двух шагов давало `0 >= 0`,
   и прогон БЕЗ отказов объявлялся несостоявшимся.

Обвязка, которой нельзя верить, хуже отсутствия обвязки: она тратит время на
несуществующие дефекты и прячет настоящие.
"""

from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent


def _модуль():
    """`tools/simulate.py` — скрипт, а не пакет; грузим по пути.

    Ключ провайдера подставляем пустышкой: на импорте он не проверяется, а
    настоящий из окружения тесту не нужен и не должен быть нужен.
    """
    os.environ.setdefault("CEREBRAS_API_KEY", "тест")
    sys.path.insert(0, str(КОРЕНЬ))
    спец = importlib.util.spec_from_file_location(
        "simmod", КОРЕНЬ / "tools" / "simulate.py"
    )
    м = importlib.util.module_from_spec(спец)
    sys.modules["simmod"] = м
    спец.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def sim():
    return _модуль()


# --- ложное красное: то, что уже случилось -----------------------------------

@pytest.mark.parametrize("шагов", [1, 2, 3, 5, 20, 66])
def test_ноль_отказов_никогда_не_срывает_проверку(sim, шагов):
    """ГЛАВНЫЙ. Прогон без отказов провайдера состоялся при любом размере.

    Отвергает `отказов >= шагов // 3` — ровно ту реализацию, что стояла здесь:
    при шагов < 3 целочисленное деление даёт 0, и зелёный прогон объявлялся
    несостоявшимся. Параметр 2 — тот самый живой случай.
    """
    код, сообщение = sim.вердикт(шагов, 0, 0)
    assert код == 0, сообщение
    assert "НЕ СОСТОЯЛАСЬ" not in сообщение


def test_один_отказ_на_большом_прогоне_не_срывает_проверку(sim):
    """66 шагов и один отказ — это неполнота, а не несостоявшийся прогон."""
    код, сообщение = sim.вердикт(66, 0, 1)
    assert код == 1
    assert "НЕПОЛНАЯ" in сообщение


# --- ложное зелёное: обратная сторона ----------------------------------------

def test_пачка_отказов_не_выдаётся_за_зелёное(sim):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Треть прогона отказала — вердикт «не состоялось».

    Отвергает реализацию, которая сначала смотрит на провалы: при отказах
    провайдера провалов НЕТ по определению (ответа не было ни одного), и такой
    порядок дал бы «✅ все сценарии прошли» на пустом прогоне.
    """
    код, сообщение = sim.вердикт(60, 0, 33)
    assert код == 2
    assert "НЕ СОСТОЯЛАСЬ" in сообщение


def test_отказ_ровно_на_трети(sim):
    """Граница: 20 из 60 — треть, проверка не состоялась."""
    assert sim.вердикт(60, 0, 20)[0] == 2


def test_отказ_чуть_меньше_трети(sim):
    """19 из 60 — меньше трети, прогон неполный, но состоявшийся."""
    код, сообщение = sim.вердикт(60, 0, 19)
    assert код == 1
    assert "НЕПОЛНАЯ" in сообщение


def test_провалы_видны_даже_при_отказах(sim):
    """Настоящие провалы не прячутся за отказами провайдера."""
    код, сообщение = sim.вердикт(60, 4, 5)
    assert код == 1
    assert "провалы" in сообщение
    assert "5 отказов" in сообщение


def test_провалы_без_отказов(sim):
    код, сообщение = sim.вердикт(60, 1, 0)
    assert код == 1
    assert "отказ" not in сообщение.lower()


def test_известный_предел_не_считается_провалом(sim):
    """Предел модели живёт в отдельном списке и код возврата не портит.

    Отвергает реализацию, которая складывает пределы с провалами: тогда
    грузинский язык держал бы прогон красным навсегда, и красное перестали бы
    читать. Проверяем сам механизм: у шага с объявленным пределом провалы
    остаются пустыми.
    """
    итог = sim.Итог(сценарий="проверка")
    итог.пределов.append("[02] грузинский")
    код, сообщение = sim.вердикт(2, len(итог.провалы), 0)
    assert код == 0, "объявленный предел модели не имеет права ронять прогон"
    assert итог.пределов, "и при этом он обязан остаться видимым"


# --- заслон квоты: не начинать прогон, который не влезает ---------------------

def test_квоты_не_хватает_прогон_не_начинается(sim):
    """ГЛАВНЫЙ. 28 сценариев при 42K остатка — прогон обязан НЕ начаться.

    Живой случай 14.08: полный прогон стоит ≈390K, в сутках оставалось 42K. Без
    заслона он дошёл бы до восьмого шага, сжёг остаток и напечатал «проверка не
    состоялась» — полная цена за нулевой результат.

    Отвергает реализацию-отчёт: сделайте условие `if False`, и заслон превратится
    в предупреждение, которое можно проигнорировать (§26).
    """
    можно, сообщение = sim.хватит_ли_квоты(
        {"токенов_в_сутки": 42_000}, шагов=63, размер_промпта=10_744
    )
    assert можно is False
    assert "НЕ НАЧАТ" in сообщение
    assert "42K" in сообщение, "клиент этого сообщения — человек, ему нужны оба числа"


def test_квоты_хватает_прогон_идёт(sim):
    """Обратный: с полной квотой заслон не мешает.

    Отвергает заслон, который блокирует всегда: такой «безопасный» вариант
    просто отменил бы имитацию целиком.
    """
    можно, сообщение = sim.хватит_ли_квоты(
        {"токенов_в_сутки": 1_000_000}, шагов=63, размер_промпта=10_744
    )
    assert можно is True
    assert "НЕ НАЧАТ" not in сообщение


def test_остаток_неизвестен_прогон_не_блокируется(sim):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Заголовков нет — гоним, но говорим об этом прямо.

    Заслон на догадке хуже отсутствия заслона: сеть отказала на пробном запросе,
    и прогон бы не состоялся никогда. Отвергает реализацию, которая при пустом
    остатке возвращает False.
    """
    for остаток in ({}, {"запросов_в_сутки": 5}):
        можно, сообщение = sim.хватит_ли_квоты(остаток, 63, 10_744)
        assert можно is True, "неизвестный остаток не повод отменять проверку"
        assert "не удалось" in сообщение, "и молчать об этом нельзя"


def test_маленький_целевой_прогон_влезает_когда_полный_нет(sim):
    """Смысл фильтра сценариев: 7 шагов влезают там, где 63 не влезают.

    Это и есть экономия, ради которой фильтр стал списком: один и тот же
    остаток пропускает целевой прогон и отвергает полный.
    """
    остаток = {"токенов_в_сутки": 60_000}
    assert sim.хватит_ли_квоты(остаток, 7, 10_744)[0] is True
    assert sim.хватит_ли_квоты(остаток, 63, 10_744)[0] is False


def test_оценка_не_считает_шаги_без_вызова_модели(sim):
    """Семь шагов из 63 до модели не доходят — они бесплатны.

    Живой случай 14.08: заслон потребовал 387K при остатке 376K и отменил
    полный прогон, который на самом деле стоил ≈344K. Заслон, отвергающий
    верное, начинают обходить руками — и тогда он не защищает вовсе.

    Отвергает реализацию `нужно = шагов * цена`: с ней 63 шага дают ≈387K,
    и прогон при остатке 376K не начинается.
    """
    остаток = {"токенов_в_сутки": 376_000}
    можно, сообщение = sim.хватит_ли_квоты(остаток, шагов=63, размер_промпта=11_086)
    assert можно is True, сообщение
    assert "56 вызовов" in сообщение, "оценка обязана называть, во что она верит"


def test_оценка_остаётся_заслоном_а_не_поблажкой(sim):
    """Уточнение оценки не должно превратить заслон в отчёт.

    При честно недостаточном остатке прогон по-прежнему не начинается.
    """
    assert sim.хватит_ли_квоты(
        {"токенов_в_сутки": 50_000}, 63, 11_086
    )[0] is False


# --- отбор сценариев: опечатка в фильтре не должна молча урезать прогон -------

def test_напоминания_законный_фильтр(sim):
    """«напомин» выбирает проверку напоминаний, которой нет в списке сценариев.

    Отвергает реализацию, сверяющую фильтр ТОЛЬКО с именами сценариев: свой же
    заслон отверг бы законный `simulate.py напоминания`.
    """
    имена = [с.имя.lower() for с in sim.сценарии()]
    assert not any("напомин" in имя for имя in имена), (
        "проверка напоминаний намеренно живёт вне списка сценариев"
    )


def test_опечатка_в_фильтре_видна(sim):
    """Обратный: несуществующий фильтр не должен давать пустой зелёный прогон.

    Молча прогнать ноль сценариев и напечатать «✅ все прошли» — то же ложное
    зелёное, за которым мы гоняемся весь этап.
    """
    имена = [с.имя.lower() for с in sim.сценарии()]
    assert not any("нетакогосценария" in имя for имя in имена)

