"""Метка «нужен ответ» ставится ровно там, где эскалация уже происходит.

Модуль `handover.py` сам по себе проверен в `test_handover.py`. Здесь — про
проводку: узнаёт ли окно администратора о передаче, и молчит ли бот, пока
разговор у человека.

Главные здесь противоположны по смыслу:
  эскалация ОБЯЗАНА поставить метку — иначе админ не увидит, где его ждут;
  обычный ответ ОБЯЗАН метку не ставить — иначе лента покраснеет целиком и
  перестанет что-либо значить.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import pytest
from conftest import ЧЕТВЕРГ, УТРО, ФейкТранспорт, входящее

from aiconic import guards, handover
from aiconic.app import Дирижёр, Лог
from aiconic.llm import FakeProvider, Ответ
from aiconic.sender import ШАБЛОН_АДМИНУ, Sender


@pytest.fixture
def передачи(tmp_path: Path) -> handover.Передачи:
    return handover.Передачи(tmp_path)


@pytest.fixture
def собрать(салон, передачи, лог):
    """Дирижёр и Sender с ОДНИМ экземпляром передач — как в бою."""
    def фабрика(ответы=None, история=None):
        транспорт = ФейкТранспорт()
        отправитель = Sender(
            транспорт, салон, белый_список={7}, лог=лог, передачи=передачи
        )
        д = Дирижёр(
            салон=салон,
            провайдер=FakeProvider(ответы or []),
            sender=отправитель,
            приём=guards.Приём(
                белый_список={7}, старт=datetime.now(timezone.utc)
            ),
            лог=лог,
            история=(история or (lambda ч, n: [])),
            сегодня=lambda: ЧЕТВЕРГ,
            сейчас_минут=lambda: УТРО,
            пауза_группировки=0.0,
            передачи=передачи,
        )
        return д, отправитель, транспорт
    return фабрика


# --- 1. Эскалации ставят метку ----------------------------------------------

@pytest.mark.asyncio
async def test_needs_human_ставит_метку(собрать, передачи):
    """ГЛАВНЫЙ. Модель попросила человека — окно обязано это узнать.

    Отвергает реализацию без вызова в `_администратору`: клиент получил
    «передала администратору», а в ленте администратора чат ничем не выделен —
    то есть обещание клиенту никем не выполняется.
    """
    д, _, транспорт = собрать([Ответ(reply="…", needs_human=True, reason="торг")])
    await д.принять(входящее("сделайте скидку 30%"))
    await д.обработать(7)

    assert транспорт.отправленное[-1][1] == ШАБЛОН_АДМИНУ
    assert передачи.открытая(7) is not None
    assert передачи.открытая(7).код == handover.МОДЕЛЬ_ПРОСИТ


@pytest.mark.asyncio
async def test_заслон_цены_ставит_свой_код(собрать, передачи):
    """Разные эскалации — разные коды, иначе лента их не различит."""
    д, _, _ = собрать([Ответ(reply="Массаж спины — 95 ₾.")])
    await д.принять(входящее("а можно за 95?"))
    await д.обработать(7)
    assert передачи.открытая(7).код == handover.ЗАСЛОН_ЦЕНЫ


@pytest.mark.asyncio
async def test_медицинский_путь_ставит_метку(собрать, передачи):
    """ГЛАВНЫЙ. Медицинский заслон идёт МИМО Sender._администратору.

    Модель на этом пути не вызывается вовсе, значит хук в Sender сюда не
    достаёт. Отвергает реализацию, где метку ставит только Sender: самый
    важный для администратора случай остался бы невидимым.
    """
    д, _, транспорт = собрать([])
    await д.принять(входящее("болит спина после операции, можно массаж?"))
    await д.обработать(7)

    assert транспорт.отправленное, "клиент обязан получить шаблон"
    assert передачи.открытая(7).код == handover.МЕДИЦИНА


@pytest.mark.asyncio
async def test_в_метке_нет_текста_клиента(собрать, передачи, tmp_path: Path):
    """ГЛАВНЫЙ ПО ТРЕБОВАНИЮ ГЕОРГИЯ: данных о здоровье в файле быть не может.

    Отвергает реализацию, кладущую в метку причину словами: причина
    медицинского заслона — слово-триггер из сообщения клиента, а сообщение
    бывает про операцию и беременность. Проверяем сам файл на диске.
    """
    д, _, _ = собрать([])
    await д.принять(входящее("болит спина после операции, можно массаж?"))
    await д.обработать(7)

    содержимое = (tmp_path / handover.ФАЙЛ).read_text(encoding="utf-8").lower()
    for запрещено in ("болит", "спина", "операц", "боли"):
        assert запрещено not in содержимое, (
            f"в файле метки оказалось слово из сообщения клиента: {запрещено!r}"
        )
    assert "медицина" in содержимое


# --- 2. Обычный ответ метку НЕ ставит ---------------------------------------

@pytest.mark.asyncio
async def test_обычный_ответ_не_ставит_метку(собрать, передачи):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Ответил сам — администратору делать нечего.

    Отвергает реализацию, помечающую любой обработанный чат: лента стала бы
    списком всех разговоров подряд, и красный цвет в ней перестал бы что-либо
    значить. Ровно так «отчёт» подменяет собой смысл (§26).
    """
    д, _, транспорт = собрать([Ответ(reply="Массаж спины — 120 ₾.")])
    await д.принять(входящее("сколько стоит массаж спины?"))
    await д.обработать(7)

    assert транспорт.отправленное[-1][1] == "Массаж спины — 120 ₾."
    assert передачи.открытые() == {}


