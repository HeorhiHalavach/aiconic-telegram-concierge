@pytest.mark.asyncio
async def test_ответ_админа_не_слушается_stop(собрать, передачи, tmp_path, салон, лог):
    """Осознанное нажатие сильнее выключателя — и это названное отличие.

    `STOP` глушит БОТА. Администратор, нажавший «отправить», знает, что делает;
    молча съесть его сообщение было бы хуже, чем отправить.

    Отвергает реализацию, где второй выход проходит через `_базовый_отказ`.
    """
    транспорт = ФейкТранспорт()
    стоп = tmp_path / "STOP"
    стоп.write_text("", encoding="utf-8")
    отправитель = Sender(
        транспорт, салон, белый_список={7}, файл_выключателя=стоп, лог=лог,
        передачи=передачи,
    )
    решение = await отправитель.отправить_от_админа(7, "я на месте, отвечаю")
    assert решение.отправлено, "STOP не должен глушить человека"
    assert транспорт.отправленное == [(7, "я на месте, отвечаю")]


@pytest.mark.asyncio
async def test_пустой_ответ_админа_не_уходит(собрать):
    """Пустое сообщение Telegram и так не примет — отказываем раньше."""
