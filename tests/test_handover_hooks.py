# --- 3. Пока метка висит — бот молчит ---------------------------------------

@pytest.mark.asyncio
async def test_при_открытой_метке_модель_не_вызывается(собрать, передачи):
    """ГЛАВНЫЙ. Разговор у человека — бот не отвечает и не тратит модель.

    Отвергает реализацию без этой проверки: администратор пишет клиенту, и
    поверх его слов уходит ответ модели, которая про них не знает. Клиент
    получает два разных ответа на один вопрос.

    Проверяем и то, что модель не вызвана: платить за ответ, который нельзя
    отправлять, незачем.
    """
    д, _, транспорт = собрать([Ответ(reply="Массаж спины — 120 ₾.")])
    передачи.открыть(7, handover.ТОРГ)

    await д.принять(входящее("а сколько стоит массаж спины?"))
    await д.обработать(7)

    assert транспорт.отправленное == [], "бот обязан молчать, пока чат у человека"
    assert д.провайдер.вызовы == [], "модель не должна вызываться вовсе"


@pytest.mark.asyncio
async def test_после_снятия_метки_бот_снова_отвечает(собрать, передачи):
    """Обратная половина: снятая метка возвращает бота в работу.

    Отвергает реализацию, которая молчит навсегда после первой эскалации —
    например, если бы метка снималась только вручную правкой файла.
    """
    д, отправитель, транспорт = собрать([Ответ(reply="Массаж спины — 120 ₾.")])
    передачи.открыть(7, handover.ТОРГ)
    передачи.снять(7)

    await д.принять(входящее("а сколько стоит массаж спины?"))
    await д.обработать(7)
    assert транспорт.отправленное[-1][1] == "Массаж спины — 120 ₾."


# --- 4. Второй выход: ответ администратора ----------------------------------

@pytest.mark.asyncio
async def test_ответ_админа_уходит_и_снимает_метку(собрать, передачи):
    """ГЛАВНЫЙ. Человек ответил — сообщение ушло, метка снята.

    Отвергает реализацию, которая шлёт, но метку не снимает: чат навсегда
    останется красным в ленте, и бот в нём навсегда замолчит.
    """
    _, отправитель, транспорт = собрать([])
    передачи.открыть(7, handover.ТОРГ)

    решение = await отправитель.отправить_от_админа(7, "Сделаем скидку 20%.")
    assert решение.отправлено
    assert транспорт.отправленное[-1] == (7, "Сделаем скидку 20%.")
    assert передачи.открытые() == {}


@pytest.mark.asyncio
async def test_ответ_админа_не_проверяется_заслонами_модели(собрать, передачи):
    """ГЛАВНЫЙ. Слова человека — не галлюцинация модели.

    В тексте разом три вещи, каждая из которых заблокировала бы ответ модели:
    цена не из прайса, время не из свободных окон, условие не из правил.
    Отвергает реализацию, гоняющую ответ администратора через те же заслоны:
    администратор не смог бы дать скидку и назвать своё время — то есть окно
    было бы бесполезно ровно в тех случаях, для которых оно и сделано.
    """
    _, отправитель, транспорт = собрать([])
    текст = "Сделаю скидку: 95 ₾ вместо 120, приходите в 23:30, деньги вернём."
    решение = await отправитель.отправить_от_админа(7, текст)
    assert решение.отправлено, решение.причина
    assert транспорт.отправленное[-1][1] == текст


