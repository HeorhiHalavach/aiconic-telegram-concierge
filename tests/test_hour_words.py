"""«8 утра» — то же время, что «08:00». Освобождение по цитате обязано это знать.

Живой прогон 2026-08-14, полная имитация: клиент спросил «можно в 8 утра?»,
модель ответила верно — «в 08:00 мы закрыты, работаем с 10:00» — и заслон
времени счёл 08:00 выдумкой. Освобождение по цитате искало только формат с
двоеточием, а клиент двоеточия не писал.

Это был дефект ЗАСЛОНА, а не модели: он душил правильный ответ и подменял его
шаблоном «передала администратору». Ровно тот класс ошибки, из-за которого
защита начинает мешать вместо того, чтобы защищать.

⚠️ Обратная половина здесь важнее прямой: освобождение не имеет права быть
широким. «Хочу 5 сеансов» и «на 90 минут» — не про время, и если считать любое
число часом, заслон продырявится молча.
"""

from __future__ import annotations

import pytest
from conftest import ЧЕТВЕРГ

from aiconic import guards


def окна() -> guards.Окна:
    """Четверг: 13:00 свободно, 08:00 и 09:00 — нет (салон с 10:00)."""
    return guards.Окна(
        по_дням={0: frozenset({"13:00", "14:00", "16:30"})},
        метки={"сегодня": 0},
        часы=frozenset({"10:00", "21:00"}),
    )


# --- прямая половина: цитату клиента повторить можно --------------------------

@pytest.mark.parametrize("вопрос", [
    "можно в 8 утра?",
    "а в 8 часов можно?",
    "хочу в 8 час",
    "можно записаться в 8 утра сегодня?",
])
def test_час_словами_из_вопроса_не_выдумка(вопрос):
    """ГЛАВНЫЙ. Отвергает реализацию, ищущую цитату только как ЧЧ:ММ.

    Уберите разбор `_ЧАС_СЛОВАМИ` из `_процитированные_времена` — и каждый из
    этих случаев снова начнёт уезжать администратору.
    """
    ответ = "В 08:00 мы закрыты, работаем с 10:00. Есть окно в 13:00."
    assert guards.выдуманное_время(ответ, окна(), сказал_клиент=вопрос) == []


def test_вечер_и_ночь_тоже_считаются():
    """«9 вечера» — 21:00, а не 09:00 по смыслу, но обе цифры клиент назвал.

    Заслон намеренно не разбирает «вечера» в 21:00: он лишь освобождает то
    ЧИСЛО, которое клиент произнёс. Записать на это время всё равно нельзя —
    для этого стоит `Booker`, а не текстовый заслон.
    """
    assert guards._процитированные_времена("можно в 9 вечера?") == {"09:00"}


# --- обратная половина: освобождение обязано быть узким ----------------------

@pytest.mark.parametrize("вопрос,выдумка", [
    ("хочу абонемент на 5 сеансов", "05:00"),
    ("массаж на 90 минут", "09:00"),
    ("нас будет 8 человек", "08:00"),
    ("сколько стоит 60 минут?", "06:00"),
])
def test_числа_не_про_время_не_освобождают(вопрос, выдумка):
    """ГЛАВНЫЙ ОБРАТНЫЙ. Отвергает широкое освобождение по любому числу.

    Замените `_ЧАС_СЛОВАМИ` на `\\b(\\d{1,2})\\b` — заслон перестанет ловить
    выдуманное время всякий раз, когда в вопросе клиента была любая цифра.
    Это тот самый случай, где защита исчезает молча: тесты про ЧЧ:ММ останутся
    зелёными.
    """
    ответ = f"Свободно в {выдумка}, записать вас?"
    assert guards.выдуманное_время(ответ, окна(), сказал_клиент=вопрос) == [выдумка]


def test_минуты_не_путаются_с_часами():
    """«за 3 часа» из правил салона — это срок, а не время визита.

    Освобождение тут срабатывает (число 3 названо со словом «часа»), и это
    безобидно: 03:00 в свободных окнах не появится, а записать на него нельзя.
    Тест фиксирует границу сознательно, чтобы следующий читатель не считал это
    недосмотром.
    """
    assert guards._процитированные_времена("отмена за 3 часа?") == {"03:00"}
    # но само по себе 03:00 в ответе без цитаты — выдумка
    assert guards.выдуманное_время(
        "Свободно в 03:00", окна(), сказал_клиент="когда свободно?"
    ) == ["03:00"]


def test_цена_не_становится_временем():
    """«120 ₾ за 60 минут» не содержит ни одного часа."""
    assert guards._процитированные_времена("120 ₾ за 60 минут") == set()
