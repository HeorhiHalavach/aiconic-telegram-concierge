"""Заслон на выдуманные условия — дефект C.

Дважды на живых прогонах модель приписала салону денежное условие, которого в
правилах нет:

  «при отмене будет удержана часть стоимости»   (прогон 2026-08-13)
  «позже возврата не будет»                     (живой диалог 2026-08-13)

Оба раза не сработал ни один заслон: ни цены, ни времени в этих фразах нет.
Промпт после первого случая «вылечил» — и живьём оно вернулось другими словами.
Промпт просьба, заслон гарантия.
"""

from __future__ import annotations

import pytest
from conftest import входящее

from aiconic import guards
from aiconic.llm import Ответ

ЖИВОЙ_СЛУЧАЙ = "Отмена возможна бесплатно до 3 часов до сеанса; позже возврата не будет."
ПЕРВЫЙ_ПРОГОН = "При отмене будет удержана часть стоимости."


# --- сама функция -----------------------------------------------------------

@pytest.mark.parametrize("текст, ожидаем", [
    (ЖИВОЙ_СЛУЧАЙ, "возврат"),
    (ПЕРВЫЙ_ПРОГОН, "удерж"),
    # Живой промах 2026-08-13: этот корень отсутствовал, и фраза УШЛА КЛИЕНТУ.
    ("Если отмените за 1 час, стоимость не будет возвращена.", "возвращ"),
    ("деньги не возвращаются", "возвращ"),
    ("возмещение не предусмотрено", "возмещ"),
    ("из стоимости вычтем половину", "вычт"),
    ("Сделаем вам скидку 10%.", "скидк"),
    ("Гарантируем результат после первого сеанса.", "гарантиру"),
    ("Нужна предоплата 50 лари.", "предоплат"),
    ("Спишем деньги за неявку.", "спишем"),
    ("При отмене штраф 30 ₾.", "штраф"),
])
def test_выдуманное_условие_ловится(салон, текст, ожидаем):
    """Проверяем ЗАПРЕЩЁННЫЙ путь: обязательство, которого нет в правилах."""
    assert ожидаем in guards.выдуманные_условия(текст, салон.правила), текст


@pytest.mark.parametrize("текст", [
    "Отменить или перенести можно бесплатно не позднее чем за 3 часа.",
    "Опоздание больше 15 минут сокращает сеанс, стоимость не меняется.",
    "Оплата на месте: наличными или картой.",
    "Записаться можно минимум за 2 часа до визита.",
    "Массаж спины 60 минут — 120 ₾.",
    "Записали вас на 14:00, напомним за день и за 2 часа до визита.",
])
def test_правила_салона_дословно_проходят(салон, текст):
    """Обратная сторона: заслон не должен душить верные ответы.

    Слово «бесплатно» есть в правилах — значит его произносить можно.
    """
    assert guards.выдуманные_условия(текст, салон.правила) == [], текст


@pytest.mark.parametrize("текст", [
    # ЖИВОЙ ПРОМАХ 2026-08-13: «раСПИСАНии» ловилось как «списан», и верный
    # ответ уехал администратору. Заслон условий искал подстрокой, хотя тот же
    # класс бага был уже исправлен в медицинских и спам-триггерах (§17).
    "60-минутный сеанс в 20:30 завтра нет в расписании.",
    "Посмотрите расписание мастеров.",
    "У нас бурная реакция на такие просьбы.",
    "Приятное пение птиц во время сеанса.",
])
def test_безобидные_слова_не_считаются_условиями(салон, текст):
    """Отвергает поиск подстрокой в заслоне условий."""
    assert guards.выдуманные_условия(текст, салон.правила) == [], текст


def test_вернуться_ловится_и_это_осознанный_компромисс(салон):
    """«Мы вернёмся к вопросу» уедет администратору. Так решено.

    `вернут` — начало слова «вернуться», границей слова не лечится. Выбор был
    между двумя ошибками:
      потерять `вернут` → «деньги вернут» проскочит как обещание;
      оставить        → «вернуться к вопросу» уедет человеку.
    Второе безопасно, первое нет. Тест закрепляет выбор, чтобы он не был
    отменён случайно: снимите `вернут` — и первая строка покраснеет.
    """
    assert "вернут" in guards.выдуманные_условия("деньги вернут", салон.правила)
    assert guards.выдуманные_условия(
        "Мы можем вернуться к этому вопросу позже.", салон.правила
    ) == ["вернут"], "известное ложное срабатывание, принято осознанно"


@pytest.mark.parametrize("текст, ждём", [
    # ЖИВОЙ СЛУЧАЙ имитации: «с 10 до 21» дало «выдуманную цену 21», и верный
    # ответ про часы работы уехал администратору.
    ("Работаем с 10 до 21, приходите.", []),
    ("Мы открыты с 10 до 21.", []),
    ("Часы работы 10-21.", []),
    ("Салон работает с 10 до 21, массаж спины 120 ₾.", []),
    # обратная сторона: настоящая выдуманная цена в тех же пределах ловится
    ("Сделаем за 21 ₾.", [21]),
    ("Абонемент за 95 лари.", [95]),
    # диапазон цен под шаблон часов не попадает: числа больше 24
    ("Абонементы от 550 до 1000 ₾.", []),
])
def test_часы_без_минут_не_считаются_ценой(салон, текст, ждём):
    """Отвергает заслон цен, который читает «с 10 до 21» как цену 21."""
    assert guards.выдуманные_цены(текст, салон.все_цены()) == ждём, текст


def test_расписание_не_считается_списанием(салон):
    """Точечно про живой промах — отдельным именем, чтобы мутация нашла сторожа."""
    т = "60-минутный сеанс в 20:30 завтра нет в расписании."
    assert guards.выдуманные_условия(т, салон.правила) == []
    # а настоящее списание по-прежнему ловится
    assert "списан" in guards.выдуманные_условия(
        "С карты будет списана предоплата.", салон.правила
    )


def test_словарь_задают_правила_а_не_список_в_коде(салон):
    """Несущее свойство: добавили условие в прайс — бот вправе его называть.

    Отвергает реализацию с зашитым списком разрешённых слов.
    """
    assert guards.выдуманные_условия("Возврат возможен в течение 7 дней.",
                                     салон.правила) == ["возврат"]
    салон.правила.append("Возврат предоплаты возможен в течение 7 дней.")
    assert guards.выдуманные_условия("Возврат возможен в течение 7 дней.",
                                     салон.правила) == []


def test_пустые_правила_не_разрешают_всё(салон):
    """Нет правил — значит обязательств нет вообще, а не «всё можно»."""
    assert guards.выдуманные_условия(ЖИВОЙ_СЛУЧАЙ, []) == ["возврат"]
    assert guards.выдуманные_условия(ЖИВОЙ_СЛУЧАЙ, None) == ["возврат"]


# --- заслон в Sender целиком -------------------------------------------------

@pytest.mark.asyncio
async def test_выдуманное_условие_не_уходит_клиенту(сделать_дирижёра, транспорт):
    """Живой случай целиком: текст модели заменяется шаблоном."""
    д, _ = сделать_дирижёра([Ответ(reply=ЖИВОЙ_СЛУЧАЙ)])
    await д.принять(входящее("а если я отменю за час, деньги вернутся?"))
    await д.обработать(7)

    assert транспорт.отправленное, "клиент не должен остаться без ответа"
    ушло = транспорт.отправленное[-1][1]
    assert "возврат" not in ушло.lower(), (
        "выдуманное денежное условие ушло клиенту"
    )
    assert "администратор" in ушло.lower()


@pytest.mark.asyncio
async def test_верный_ответ_про_отмену_доходит(сделать_дирижёра, транспорт):
    д, _ = сделать_дирижёра([
        Ответ(reply="Отменить можно бесплатно не позднее чем за 3 часа до визита.")
    ])
    await д.принять(входящее("могу отменить за час?"))
    await д.обработать(7)
    ушло = транспорт.отправленное[-1][1]
    assert "бесплатно" in ушло, "верный ответ подменён шаблоном"
    assert "администратор" not in ушло.lower()
