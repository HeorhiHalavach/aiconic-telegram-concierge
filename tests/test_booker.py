"""Три заслона записи. Модель предлагает — пишет Booker."""

from __future__ import annotations

from datetime import date

import pytest
import yaml
from conftest import ЧЕТВЕРГ

from aiconic.booker import Booker, ЗаписьОтклонена

ПЯТНИЦА = date(2026, 8, 14)


@pytest.fixture
def booker(салон) -> Booker:
    return Booker(салон)


def записать(booker, **kw):
    базово = dict(
        чат=7, день=ПЯТНИЦА, время="11:00", мастер_id=1,
        услуга_id="back60", предложенные=["11:00"], клиент="тест",
    )
    базово.update(kw)
    return booker.записать_синхронно(**базово)


def test_b1_время_которое_не_предлагали(booker):
    """Отвергает доверяющую модели выбор времени.

    Это ключевой заслон: он делает шаг «предложили → подтвердили»
    требованием кода, а не пожеланием в промпте.
    """
    with pytest.raises(ЗаписьОтклонена, match="не предлагали"):
        записать(booker, время="13:00", предложенные=["11:00", "12:00"])


def test_b2_время_успели_занять(booker, салон):
    """Отвергает проверку свободности в момент предложения вместо момента записи."""
    салон.записи.append(
        {"чат": 99, "мастер": 1, "дата": ПЯТНИЦА.isoformat(),
         "начало": "11:00", "длительность": 60, "услуга": "back60"}
    )
    with pytest.raises(ЗаписьОтклонена, match="занято"):
        записать(booker)


def test_b3_корректная_запись_проходит(booker, салон):
    """Отвергает слишком строгие заслоны, блокирующие всё."""
    было = len(салон.записи)
    з = записать(booker)
    assert з.начало == "11:00" and з.длительность == 60
    assert len(салон.записи) == было + 1


def test_b4_повторное_подтверждение_не_даёт_дубля(booker, салон):
    """Отвергает отсутствие идемпотентности."""
    записать(booker)
    было = len(салон.записи)
    with pytest.raises(ЗаписьОтклонена, match="уже записан"):
        записать(booker)
    assert len(салон.записи) == было


def test_b4a_другой_мастер_на_то_же_время_тоже_дубль(booker, салон):
    """ГЛАВНЫЙ. Клиент не может быть в двух креслах одновременно.

    Найдено имитацией 2026-08-13: ключ дубля включал мастера, и один и тот же
    запрос дважды дал две записи на 14:00 — к Мариам и к Нино. Формально не
    дубль, фактически человек в двух местах.
    """
    записать(booker)                       # 11:00 к мастеру 1
    было = len(салон.записи)
    with pytest.raises(ЗаписьОтклонена, match="уже записан"):
        записать(booker, мастер_id=3)      # то же время, другой мастер
    assert len(салон.записи) == было


def test_b4b_пересечение_интервалов_тоже_дубль(booker, салон):
    """Сравниваются интервалы, а не начала: 11:00–12:00 и 11:30–12:00.

    Отвергает проверку по равенству времени начала.
    """
    записать(booker)                       # 11:00, 60 минут
    было = len(салон.записи)
    with pytest.raises(ЗаписьОтклонена, match="уже записан"):
        записать(booker, время="11:30", услуга_id="neck30",
                 предложенные=["11:00", "11:30"])
    assert len(салон.записи) == было


def test_b4c_соседний_интервал_не_дубль(booker, салон):
    """Обратная сторона: 11:00–12:00 и 12:00–12:30 не пересекаются.

    Отвергает слишком широкую проверку, блокирующую вторую услугу подряд.
    """
    записать(booker)                       # 11:00–12:00 к Нино
    было = len(салон.записи)
    записать(booker, время="12:00", услуга_id="neck30",
             предложенные=["11:00", "12:00"])
    assert len(салон.записи) == было + 1


def test_b5_записанное_окно_исчезло_из_свободных(booker, салон):
    """Отвергает хранение свободных окон вместо вычисления."""
    assert "11:00" in салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1)["Нино"]
    записать(booker)
    assert "11:00" not in салон.свободные_окна(ПЯТНИЦА, 60, мастер_id=1)["Нино"]


def test_b6_файл_читается_обратно(booker, каталог):
    """Отвергает запись напрямую в файл, оставляющую битый YAML при падении."""
    записать(booker)
    данные = yaml.safe_load((каталог / "bookings.yaml").read_text(encoding="utf-8"))
    сохранённые = [з for з in данные["записи"] if з["чат"] == 7]
    assert сохранённые and сохранённые[0]["начало"] == "11:00"


def test_b7_ваши_файлы_не_тронуты(booker, каталог):
    """Отвергает реализацию, перезаписывающую price.yaml/schedule.yaml
    и убивающую комментарии в них."""
    до = {
        имя: (каталог / имя).read_bytes()
        for имя in ("price.yaml", "schedule.yaml")
    }
    записать(booker)
    for имя, содержимое in до.items():
        assert (каталог / имя).read_bytes() == содержимое, f"{имя} изменён!"
    # и комментарии на месте
    assert b"#" in (каталог / "schedule.yaml").read_bytes()


@pytest.mark.asyncio
async def test_b8_два_чата_одновременно(салон):
    """Отвергает отсутствие замка вокруг чтения-изменения-записи."""
    import asyncio

    b = Booker(салон)
    было = len(салон.записи)
    await asyncio.gather(
        b.записать(чат=7, день=ПЯТНИЦА, время="11:00", мастер_id=1,
                   услуга_id="back60", предложенные=["11:00"]),
        b.записать(чат=8, день=ПЯТНИЦА, время="13:00", мастер_id=1,
                   услуга_id="back60", предложенные=["13:00"]),
    )
    assert len(салон.записи) == было + 2


@pytest.mark.asyncio
async def test_b9_две_попытки_на_одно_время_под_замком(салон):
    """Гонка: два чата подтверждают ОДНО время. Пройти должен ровно один."""
    import asyncio

    b = Booker(салон)
    итоги = await asyncio.gather(
        b.записать(чат=7, день=ПЯТНИЦА, время="11:00", мастер_id=1,
                   услуга_id="back60", предложенные=["11:00"]),
        b.записать(чат=8, день=ПЯТНИЦА, время="11:00", мастер_id=1,
                   услуга_id="back60", предложенные=["11:00"]),
        return_exceptions=True,
    )
    успехи = [x for x in итоги if not isinstance(x, Exception)]
    отказы = [x for x in итоги if isinstance(x, ЗаписьОтклонена)]
    assert len(успехи) == 1 and len(отказы) == 1


def test_b12_сбой_записи_не_портит_существующий_файл(booker, салон, каталог):
    """Отвергает запись напрямую в целевой файл.

    Настоящее свойство атомарности: если запись упала на середине, старый файл
    остался целым и мусорных .tmp рядом не валяется.
    """
    было = (каталог / "bookings.yaml").read_bytes()

    def падать(*a, **kw):
        raise OSError("диск кончился")

    import yaml as _yaml
    настоящий = _yaml.safe_dump
    _yaml.safe_dump = падать
    try:
        with pytest.raises(OSError):
            записать(booker)
    finally:
        _yaml.safe_dump = настоящий

    assert (каталог / "bookings.yaml").read_bytes() == было, "старый файл испорчен"
    assert not list(каталог.glob("*.tmp")), "остались временные файлы"


