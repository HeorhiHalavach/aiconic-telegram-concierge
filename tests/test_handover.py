"""Метка «нужен ответ»: без неё окно администратора бесполезно.

Порядок работы был обратный привычному и по совету Георгия: сначала проба
гипотезы живьём (`scratchpad/probe_handover.py` — открыл, перезапустил, снял,
подсунул свободный текст), и только потом эта обёртка. Тесты закрепляют то, что
проба показала, а не то, что я предполагал.

Два главных здесь противоположны по смыслу:
  метка обязана ПЕРЕЖИТЬ перезапуск;
  свободный текст обязан НЕ ПОПАСТЬ в файл — иначе туда просочатся данные о
  здоровье, а Георгий прямо просил их не хранить.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from aiconic import handover


@pytest.fixture
def передачи(tmp_path: Path) -> handover.Передачи:
    return handover.Передачи(tmp_path)


# --- 1. Главный: метка переживает перезапуск --------------------------------

def test_метка_переживает_перезапуск(tmp_path: Path):
    """ГЛАВНЫЙ. Новый процесс обязан знать, где ждут человека.

    Отвергает хранение в памяти процесса: сделайте `self.записи` единственным
    хранилищем без `сохранить()` — и после перезапуска администратор потеряет
    все передачи, а лента станет пустой при живых нерешённых диалогах. Ровно
    та же ошибка, что была бы с отметкой `напомнили`.
    """
    первый = handover.Передачи(tmp_path)
    первый.открыть(7, handover.МЕДИЦИНА)
    первый.открыть(9, handover.ТОРГ)

    второй = handover.Передачи(tmp_path)          # «перезапуск»
    assert sorted(второй.открытые()) == [7, 9]
    assert второй.открытая(7).код == handover.МЕДИЦИНА


def test_снятие_переживает_перезапуск(tmp_path: Path):
    """Обратная половина: снятая метка не возвращается после перезапуска.

    Отвергает снятие только в памяти — администратор ответил, а лента после
    перезапуска снова требует ответа.
    """
    первый = handover.Передачи(tmp_path)
    первый.открыть(7, handover.ТОРГ)
    первый.снять(7)
    assert handover.Передачи(tmp_path).открытые() == {}


# --- 2. Главный обратный: свободный текст не попадает в файл ----------------

@pytest.mark.parametrize("текст", [
    "болит спина после операции",
    "клиент жалуется на давление",
    "медицина: беременность",
    "",
    "MEDICINE",
])
def test_свободный_текст_вместо_кода_отвергнут(передачи, текст, tmp_path: Path):
    """ГЛАВНЫЙ ОБРАТНЫЙ. В файл попадают только коды из закрытого списка.

    Отвергает реализацию без проверки `код not in КОДЫ`: тогда вызывающий рано
    или поздно передаст сюда причину словами — а причина берётся из сообщения
    клиента, и в ней окажется диагноз. Файл метки станет хранилищем
    медицинских данных, которого Георгий просил не создавать.
    """
    with pytest.raises(handover.НеизвестныйКод):
        передачи.открыть(7, текст)
    assert передачи.открытые() == {}
    assert not (tmp_path / handover.ФАЙЛ).exists(), (
        "отвергнутая передача не должна создавать файл"
    )


def test_все_объявленные_коды_проходят(tmp_path: Path):
    """Прямая половина: список кодов не пустой и все они рабочие.

    Отвергает `КОДЫ = frozenset()` — с ним «заслон» отвергал бы всё, включая
    законные вызовы, и передача не работала бы вовсе.
    """
    п = handover.Передачи(tmp_path)
    for i, код in enumerate(sorted(handover.КОДЫ), start=100):
        assert п.открыть(i, код).код == код
    assert len(п.открытые()) == len(handover.КОДЫ)


# --- 3. Повтор и приоритет кода ---------------------------------------------

def test_повтор_не_плодит_записей(передачи):
    """Клиент пишет пять сообщений, пока админ молчит — передача одна.

    Отвергает реализацию без проверки уже открытой: файл распухнет, а лента
    покажет один чат пять раз.
    """
    for _ in range(5):
        передачи.открыть(7, handover.ТОРГ)
    assert len(передачи.записи) == 1


def test_первый_код_побеждает(передачи):
    """Медицинский вопрос, за которым пошёл торг, остаётся медицинским.

    Отвергает перезапись кода последним: администратор увидел бы «торг» и не
    узнал, что там был вопрос о здоровье — а это самое важное в этой ленте.
    """
    передачи.открыть(7, handover.МЕДИЦИНА)
    передачи.открыть(7, handover.ТОРГ)
    assert передачи.открытая(7).код == handover.МЕДИЦИНА


# --- 4. Снятие ---------------------------------------------------------------

def test_снятая_исчезает_из_ленты_но_остаётся_в_истории(передачи):
    """Отвергает удаление записи вместо отметки: пропадёт история передач,
    а по ней потом считается, как часто бот зовёт человека."""
    передачи.открыть(7, handover.ОТМЕНА)
    assert передачи.снять(7) is True
    assert передачи.открытые() == {}
    assert len(передачи.записи) == 1
    assert передачи.записи[0]["снята"] is not None


def test_снятие_без_передачи_не_пишет_файл(передачи, tmp_path: Path):
    """Обратный: снимать нечего — на диск не ходим.

    Отвергает безусловное `сохранить()` в `снять`: файл переписывался бы на
    каждом сообщении каждого клиента, хотя менять нечего.
    """
    assert передачи.снять(7) is False
    assert not (tmp_path / handover.ФАЙЛ).exists()


def test_снятие_не_задевает_другие_чаты(передачи):
    передачи.открыть(7, handover.ТОРГ)
    передачи.открыть(9, handover.МЕДИЦИНА)
    передачи.снять(7)
    assert sorted(передачи.открытые()) == [9]


# --- 5. Файл и время ---------------------------------------------------------

def test_время_в_зоне_салона_а_не_наивное(передачи):
    """Наивное время потом сравнят с датой сообщения Telegram (UTC, tz-aware)
    и получат TypeError в бою — этот проект уже ловил такое.

    Отвергает `datetime.now()` без зоны.
    """
    п = передачи.открыть(7, handover.ТОРГ)
    from datetime import datetime
    д = datetime.fromisoformat(п.открыта)
    assert д.tzinfo is not None, "время передачи обязано быть с зоной"
    assert д.utcoffset().total_seconds() == 4 * 3600, "зона салона — UTC+4"


def test_файл_читается_обратно_и_без_мусора(передачи, tmp_path: Path):
    """Атомарная запись: после сохранения нет ни битого файла, ни `.tmp`."""
    передачи.открыть(7, handover.МЕДИЦИНА)
    assert (tmp_path / handover.ФАЙЛ).exists()
    assert list(tmp_path.glob("*.tmp")) == [], "временный файл не убран"
    текст = (tmp_path / handover.ФАЙЛ).read_text(encoding="utf-8")
    assert "медицина" in текст
    assert "здоровь" in текст, "шапка обязана объяснять, почему тут только коды"


@pytest.mark.parametrize("мусор", [
    "передачи: не список",
    "передачи:\n- просто строка\n- 42",
    "совсем не тот ключ: 1",
    "[]",
    "",
])
def test_битый_файл_не_роняет_окно(tmp_path: Path, мусор):
    """ГЛАВНЫЙ, найден собственным враждебным тестом ДО реализации окна.

    Первая версия падала здесь с `AttributeError: 'str' object has no attribute
    'get'`: `перечитать` брал что угодно, а `открытые()` считал это списком
    словарей. В бою это значит, что окно администратора не открывается вовсе —
    из-за одной правки файла руками.

    Отвергает реализацию `self.записи = list(данные.get("передачи") or [])`
    без проверки формы.
    """
    (tmp_path / handover.ФАЙЛ).write_text(мусор, encoding="utf-8")
    п = handover.Передачи(tmp_path)
    assert п.открытые() == {}, "из мусора не должно взяться ни одной передачи"
    assert п.открытая(7) is None
    п.открыть(7, handover.ТОРГ)               # и запись поверх мусора работает
    assert sorted(handover.Передачи(tmp_path).открытые()) == [7]


def test_годные_записи_уцелевают_рядом_с_мусором(tmp_path: Path):
    """Обратная половина: фильтр не должен выбрасывать ВСЁ.

    Отвергает `self.записи = []` как «безопасную» реакцию на любой файл — с ней
    все открытые передачи молча исчезли бы при одной битой строке.
    """
    (tmp_path / handover.ФАЙЛ).write_text(
        "передачи:\n"
        "- просто строка\n"
        "- {чат: 7, код: медицина, открыта: '2026-08-15T10:00:00+04:00', снята: null}\n",
        encoding="utf-8",
    )
    п = handover.Передачи(tmp_path)
    assert sorted(п.открытые()) == [7]
    assert п.открытая(7).код == handover.МЕДИЦИНА
