@pytest.mark.parametrize("фраза", БЕЗОБИДНЫЕ)
def test_безобидное_не_ловится(фраза):
    """ГЛАВНЫЙ. Проверяет запрещённый исход: срабатывание на обычном вопросе.

    Отвергает поиск подстрокой — верните `слово in t` вместо `\\b` + слово,
    и восемь первых фраз покраснеют.
    """
    м = guards.медицинский_триггер(фраза)
    с = guards.спам(фраза)
    assert м is None, f"ложная медицина {м!r} в {фраза!r} — уйдёт к человеку"
    assert с is None, f"ложный спам {с!r} в {фраза!r} — клиент получит МОЛЧАНИЕ"


# --- 3. Свойство механизма: триггер — начало слова ---------------------------

def test_триггер_ловится_только_в_начале_слова():
    """«операц» ловит «операция», но не «кооперация»."""
    assert guards.медицинский_триггер("после операции") == "операц"
    assert guards.медицинский_триггер("кооперация с салоном") is None


def test_окончания_разрешены():
    """Русский склоняется: одна форма триггера обязана покрывать падежи."""
    for ф in ("операция", "операции", "операцию", "операцией"):
        assert guards.медицинский_триггер(f"была {ф}") == "операц", ф


# --- 4. Заслон от возврата жадных триггеров ----------------------------------

ЖАДНЫЕ = {
    "боль": ["больше", "больница", "больной палец"],
    "приз": ["признаться", "призыв", "признак"],
    "ставки": ["доставки"],
    "займ": ["займёт"],
    "боле": ["более"],
}


@pytest.mark.parametrize("жадный, слова", list(ЖАДНЫЕ.items()))
def test_жадные_триггеры_не_вернулись_в_списки(жадный, слова):
    """Отвергает возврат короткой формы в список.

    Каждый из этих триггеров — начало безобидного слова, поэтому границей слова
    не лечится и держаться в списке не имеет права. Правило на будущее: новый
    триггер не должен быть началом безобидного слова.
    """
    все = guards.МЕДИЦИНСКИЕ_ТРИГГЕРЫ + guards.СПАМ_ТРИГГЕРЫ
    assert жадный not in все, (
        f"{жадный!r} вернулся в список — он поймает {слова}"
    )


def test_ни_одна_услуга_салона_не_задевает_триггеры(салон):
    """Заслон от триггера, который убивает целую услугу.

    Живой прогон 2026-08-13: модель сама (не наш заслон) сочла «массаж шеи»
    медицинским вопросом и увела диалог администратору. Наши списки чисты, и
    этот тест не даёт им испортиться: добавь кто-нибудь «шея» или «спина» в
    медицинские триггеры — и заказ услуги перестал бы обрабатываться вовсе.

    Медицина начинается там, где клиент говорит о состоянии, а не о позиции
    прайса. Обратная сторона проверяется тестом ниже.
    """
    задели = []
    for u in салон.услуги:
        м = guards.медицинский_триггер(u.название)
        с = guards.спам(u.название)
        if м or с:
            задели.append((u.название, м or с))
    assert задели == [], задели


def test_жалоба_на_ту_же_часть_тела_ловится():
    """Обратная сторона: «массаж шеи» — заказ, «болит шея» — медицина."""
    assert guards.медицинский_триггер("хочу массаж шеи и плеч") is None
    assert guards.медицинский_триггер("болит шея") is not None
    assert guards.медицинский_триггер("ноет шея после сна") is not None
    assert guards.медицинский_триггер("массаж спины") is None
    assert guards.медицинский_триггер("болит спина") is not None


def test_ни_один_триггер_не_короче_трёх_букв():
    """Короткий триггер почти наверняка начало чего-то безобидного."""
    все = guards.МЕДИЦИНСКИЕ_ТРИГГЕРЫ + guards.СПАМ_ТРИГГЕРЫ
    короткие = [т for т in все if len(т.strip()) < 3]
    assert короткие == [], короткие


def test_каждый_триггер_ловит_сам_себя():
    """Опечатка в списке = мёртвый триггер, который никто не заметит."""
    мёртвые = [
        т for т in guards.МЕДИЦИНСКИЕ_ТРИГГЕРЫ
        if guards.медицинский_триггер(f"вот {т}а") != т
        and guards.медицинский_триггер(f"вот {т}а") is None
    ]
    assert мёртвые == [], мёртвые


def test_регистр_и_пунктуация_не_мешают():
    assert guards.медицинский_триггер("БОЛИТ спина!") is not None
    assert guards.медицинский_триггер("(беременность)") is not None
    assert guards.спам("КАЗИНО!!!") is not None


def test_регулярка_не_ломается_на_особых_символах():
    """Триггеры уходят в regex — они обязаны экранироваться."""
    for т in guards.МЕДИЦИНСКИЕ_ТРИГГЕРЫ + guards.СПАМ_ТРИГГЕРЫ:
        re.compile(r"\b" + re.escape(т))
