"""Окно администратора на выдуманных данных: посмотреть глазами без Telegram.

    .venv\\Scripts\\python.exe tools/демо_окна.py          # порт 8742
    .venv\\Scripts\\python.exe tools/демо_окна.py 9000     # другой порт

Ни аккаунта, ни ключа, ни сети не нужно: подменён только мессенджер, всё
остальное настоящее — `inbox/api.py`, карточка клиента, метка передачи, `Sender`
со своими заслонами. Второй канал (Instagram) — тот же протокол `Канал`, он и
показывает, что мультиканальность держится на протоколе, а не на правках окна.

Отсюда же сняты скриншоты для README: маршрут `/shot/<экран>` отдаёт ту же
страницу, но с уже вписанным токеном и автоматически открытым экраном. Нужен
потому, что headless-браузер умеет только «загрузить URL и снять кадр», щёлкать
по экранам он не умеет. Как снимать — в docs/STATUS.md.
"""
from __future__ import annotations

