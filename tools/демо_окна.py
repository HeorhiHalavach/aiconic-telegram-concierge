import shutil
import sys
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

import uvicorn  # noqa: E402
from fastapi.responses import HTMLResponse  # noqa: E402

from aiconic import handover  # noqa: E402
from aiconic.app import Лог  # noqa: E402
from aiconic.inbox.api import создать_приложение  # noqa: E402
from aiconic.salon import Салон  # noqa: E402
from aiconic.sender import Sender  # noqa: E402
from aiconic.канал import Диалог  # noqa: E402

ТОКЕН = "demo-token-1234567890"
ПОРТ_ПО_УМОЛЧАНИЮ = 8742
СЕЙЧАС = datetime.now(timezone.utc)
СТРАНИЦА = КОРЕНЬ / "aiconic" / "inbox" / "страница.html"

# Экран → строка на JS, которая его откроет. Функции страницы глобальные.
ВАРИАНТЫ = {
    "channels": "",
    "feed": 'setTimeout(() => показать_ленту("telegram"), 250);',
    "instagram": 'setTimeout(() => показать_ленту("instagram"), 250);',
    "chat": 'setTimeout(() => открыть_чат(7), 250);',
    "medical": 'setTimeout(() => открыть_чат(9), 250);',
    "booked": 'setTimeout(() => открыть_чат(11), 250);',
}


def _страница_для_кадра(экран: str) -> str:
    html = СТРАНИЦА.read_text(encoding="utf-8")
    html = html.replace(
        "<script>",
        f'<script>localStorage.setItem("inbox-token","{ТОКЕН}");</script>\n<script>',
        1,
    )
    return html.replace(
        "</body>", f"<script>{ВАРИАНТЫ.get(экран, '')}</script>\n</body>", 1)


