async def собрать_приложение():
    """Настоящее приложение окна на выдуманных данных.

    Записи и метки складываются во временную папку: демонстрация не имеет права
    тронуть `data/` рабочего проекта.
    """
    каталог = Path(tempfile.mkdtemp(prefix="демо-окна-"))
    for имя in ("price.yaml", "schedule.yaml", "bookings.yaml"):
        shutil.copy(КОРЕНЬ / "data" / имя, каталог / имя)
    салон = Салон(каталог)
    салон.записи.clear()
    завтра = (СЕЙЧАС + timedelta(days=1)).date().isoformat()
    давно = (СЕЙЧАС - timedelta(days=20)).date().isoformat()
    салон.записи += [
        {"чат": 7, "мастер": 1, "дата": завтра, "начало": "13:00",
         "длительность": 60, "услуга": "back60", "клиент": "Гиорги"},
        {"чат": 7, "мастер": 2, "дата": давно, "начало": "16:30",
         "длительность": 30, "услуга": "neck30", "клиент": "Гиорги"},
        {"чат": 11, "мастер": 1, "дата": завтра, "начало": "15:00",
         "длительность": 60, "услуга": "classic60", "клиент": "Мариам К."},
    ]
    салон.сохранить_записи()

    передачи = handover.Передачи(каталог)
    передачи.открыть(7, handover.ЗАСЛОН_УСЛОВИЙ)
    передачи.открыть(9, handover.МЕДИЦИНА)
    передачи.открыть(31, handover.ТОРГ)

    телеграм, инстаграм = ФейкTelegram(), ФейкInstagram()
    отправитель = Sender(телеграм, салон, белый_список={7, 9, 11, 13},
                         лог=Лог(путь=None), передачи=передачи)
    приложение = создать_приложение(
        каналы=[телеграм, инстаграм], салон=салон, отправитель=отправитель,
        передачи=передачи, токен=ТОКЕН,
    )

    # ⚠️ Имя параметра ASCII: Starlette ищет их по [a-zA-Z_], и «{экран}» она
    # приняла бы за буквальный текст пути — /shot/feed отдавал бы 404.
    @приложение.get("/shot/{screen}", response_class=HTMLResponse)
    async def кадр(screen: str) -> HTMLResponse:
        return HTMLResponse(_страница_для_кадра(screen))

    return приложение


async def main() -> None:
    # ⚠️ Порт читается ЗДЕСЬ, а не на уровне модуля: `собрать_приложение` зовут
    # из других скриптов (например, чтобы снять кадры), и модуль, читающий
    # sys.argv при импорте, подхватывал их аргументы и падал.
    порт = int(sys.argv[1]) if len(sys.argv) > 1 else ПОРТ_ПО_УМОЛЧАНИЮ
    приложение = await собрать_приложение()
    print(f"окно:  http://127.0.0.1:{порт}/")
    print(f"токен: {ТОКЕН}")
    print(f"кадры: {'  '.join('/shot/' + и for и in ВАРИАНТЫ)}")
    сервер = uvicorn.Server(uvicorn.Config(
        приложение, host="127.0.0.1", port=порт, log_level="error"))
    await сервер.serve()


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        print("\nостановлено")
