def main() -> int:
    print(f"{'заслон':<50} результат")
    print("-" * 74)
    поймано = 0
    пропущено: list[str] = []

    for файл, было, стало, тест, описание in МУТАЦИИ:
        путь = КОРЕНЬ / файл
        исходник = путь.read_text(encoding="utf-8")
        if было not in исходник:
            print(f"{описание:<50} строка мутации не найдена — проверьте список")
            пропущено.append(описание)
            continue

        путь.write_text(исходник.replace(было, стало, 1), encoding="utf-8")
        try:
            r = subprocess.run(
                [str(PYTHON), "-m", "pytest", "-x", "-q", "-k", тест],
                cwd=КОРЕНЬ, capture_output=True, text=True, timeout=300,
                # errors="replace": дочерний pytest пишет в cp1251, и падение
                # декодера в потоке чтения печатало трейсбек поверх отчёта.
                encoding="utf-8", errors="replace",
            )
            упал = r.returncode != 0
        finally:
            путь.write_text(исходник, encoding="utf-8")   # откат всегда

        if упал:
            поймано += 1
            print(f"{описание:<50} КРАСНОЕ, мутация поймана")
        else:
            пропущено.append(описание)
            print(f"{описание:<50} зелёное — ЗАСЛОН НЕ ПРОВЕРЕН")

    print("-" * 74)
    print(f"поймано: {поймано} / {len(МУТАЦИИ)}")
    if пропущено:
        print("\nне проверены — тест не отвергает поломку:")
        for о in пропущено:
            print(f"  - {о}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
