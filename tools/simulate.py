# Доля шагов, доходящих до модели. Остальные отсекаются заслонами ДО неё —
# медицина, спам, нетекстовое, выключатель, чужой чат — и не стоят ни токена.
# Замер подставным провайдером 14.08: 56 вызовов на 63 шага. Считать все шаги
# значило отказывать прогонам, которые влезают: заслон, отвергающий верное, в
# итоге начинают обходить руками, и он перестаёт защищать.
ДОЛЯ_ДО_МОДЕЛИ = 56 / 63


def хватит_ли_квоты(остаток: dict, шагов: int, размер_промпта: int) -> tuple[bool, str]:
    """Заслон, а не отчёт (§26): при нехватке прогон НЕ начинается.

    Причина конкретная. 14.08 я собирался запустить полный прогон на ~330K
    токенов, когда в сутках оставалось 41K. Прогон дошёл бы шагов до восьмого,
    сжёг остаток и напечатал «проверка не состоялась» — то есть заплатил бы
    полную цену за нулевой результат. Проверка стоит один короткий запрос.

    Пустой остаток (заголовков нет, сеть отказала) прогон НЕ блокирует: заслон
    на догадке хуже отсутствия заслона. Но и молчать нельзя — говорим прямо.
    """
    if not остаток or "токенов_в_сутки" not in остаток:
        return True, "остаток квоты узнать не удалось — гоню, но бюджет не проверен"
    вызовов = max(1, round(шагов * ДОЛЯ_ДО_МОДЕЛИ))
    нужно = вызовов * (размер_промпта // 2 + 600)
    есть = остаток["токенов_в_сутки"]
    if нужно > есть:
        return False, (
            f"⛔ прогон НЕ НАЧАТ: нужно ≈{нужно // 1000}K токенов, в сутках "
            f"осталось {есть // 1000}K. Это не дефект — суточный лимит. "
            f"Варианты: дождаться сброса или взять меньше сценариев фильтром."
        )
    return True, (f"бюджет: нужно ≈{нужно // 1000}K на ~{вызовов} вызовов, "
                  f"есть {есть // 1000}K")


def вердикт(шагов: int, провалов: int, отказов: int) -> tuple[int, str]:
    """Код возврата и человеческая формулировка. Вынесено ради теста.

    ⚠️ Здесь жил ложный красный собственного производства: условие было
    `отказов >= шагов // 3`, и на прогоне из двух шагов `2 // 3` даёт 0, то есть
    `0 >= 0` — прогон без единого отказа объявлялся несостоявшимся. Вылезло, как
    только появились маленькие целевые прогоны. Порядок вердиктов важен:
    «проверка не состоялась» обязана идти ПЕРВОЙ, иначе пачка отказов
    провайдера выдаст себя за зелёный прогон.
    """
    if отказов and отказов * 3 >= шагов:
        return 2, (f"⛔ проверка НЕ СОСТОЯЛАСЬ: провайдер отказал на {отказов} "
                   f"шагах из {шагов}. Это лимит, а не дефект — подождите и "
                   f"прогоните заново.")
    if провалов:
        хвост = (f" (плюс {отказов} отказов провайдера — по ним не судим)"
                 if отказов else "")
        return 1, f"⛔ есть провалы — правим и гоняем заново.{хвост}"
    if отказов:
        return 1, (f"⚠️ проверка НЕПОЛНАЯ: {отказов} шагов пропущено из-за "
                   f"отказов провайдера. Провалов нет, но судить рано.")
    return 0, "✅ все сценарии прошли."


def main_() -> int:
    p = argparse.ArgumentParser()
    # Несколько фильтров через запятую: «запись,абонемент». Нужно ради экономии —
    # 91% стоимости прогона это системный промпт, уходящий с КАЖДЫМ вызовом, поэтому
    # дешевеет прогон только сокращением числа вызовов. Гонять все 27 сценариев,
    # когда правка задела четыре, — это выброшенные три четверти суточной квоты.
    p.add_argument("фильтр", nargs="?", default="",
                   help="подстроки имён через запятую: «запись,абонемент»")
    p.add_argument("--пауза", type=float, default=13.0,
                   help="секунд между вызовами модели (лимит 5/мин)")
    p.add_argument("--подробно", action="store_true")
    а = p.parse_args()

    env.загрузить()
    try:
        провайдер = CerebrasProvider(seed=SEED)
    except ОшибкаПровайдера as e:
        print(f"провайдер не готов: {e}")
        return 2
    провайдер.вызовы = []                     # счётчик для пауз
    старый = провайдер.ответить

    def считая(системный, сообщения):
        провайдер.вызовы.append(1)
        return старый(системный, сообщения)

    провайдер.ответить = считая

    куски = [к.strip().lower() for к in а.фильтр.split(",") if к.strip()]
    выбранные = [с for с in сценарии()
                 if not куски or any(к in с.имя.lower() for к in куски)]
    if куски:
        # «напомин» выбирает не сценарий, а отдельную проверку напоминаний —
        # она живёт в своей функции, а не в списке сценариев. Без этого
        # исключения собственный заслон отвергал законный фильтр.
        непонятые = [к for к in куски
                     if "напомин" not in к
                     and not any(к in с.имя.lower() for с in сценарии())]
        if непонятые:
            # Молча прогнать меньше, чем просили, — тот же обман, что ложное зелёное.
            print(f"⛔ ни одного сценария по фильтру: {', '.join(непонятые)}")
            return 2
    print(f"сценариев: {len(выбранные)}   день: {ДЕНЬ}   час: {ЧАС // 60}:00   "
          f"seed: {SEED}   пауза: {а.пауза} с")

    шагов_всего = sum(len(с.шаги) for с in выбранные)
    хватает, что_с_квотой = хватит_ли_квоты(
        провайдер.остаток_квоты(), шагов_всего,
        len(prompt.собрать(Салон(), сегодня=ДЕНЬ, сейчас_минут=ЧАС)),
    )
    print(что_с_квотой)
    if not хватает:
        return 2

    итоги: list[Итог] = []
    for с in выбранные:
        итоги.append(asyncio.run(прогнать(с, провайдер, а.пауза, а.подробно)))

    if not куски or any("напомин" in к for к in куски):
        итоги.append(asyncio.run(проверить_напоминания(провайдер)))

    print("\n" + "=" * 78)
    всего = сумма_провалов = отказы = 0
    for и in итоги:
        всего += и.шагов
        сумма_провалов += len(и.провалы)
        отказы += и.отказов_провайдера
        знак = "✅" if not и.провалы else "⛔"
        if not и.провалы and и.пределов:
            знак = "⚠️"
        если_отказ = (f"   отказов провайдера {и.отказов_провайдера}"
                      if и.отказов_провайдера else "")
        print(f"{знак} {и.сценарий:28} шагов {и.шагов:2}   "
              f"провалов {len(и.провалы)}{если_отказ}")
        for пр in и.провалы:
            print(f"     {пр}")
        for пр in и.пределов:
            print(f"     ⚠️ {пр}")
    print("=" * 78)
    print(f"шагов: {всего}   провалов: {сумма_провалов}   "
          f"отказов провайдера: {отказы}   "
          f"вызовов модели: {sum(и.вызовов for и in итоги)}")

    код, сообщение = вердикт(всего, сумма_провалов, отказы)
    print("\n" + сообщение)
    return код


if __name__ == "__main__":
    sys.exit(main_())
