"""Ручная проверка качества ответов — главная проверка этапа.

Автотестом галлюцинацию не поймать: модель может выдать красивый, связный и
неверный ответ. Поэтому набор вопросов с заранее известными правильными
ответами, фиксированный seed для сравнимости прогонов, и глаза человека.

    python tools/eval_answers.py

Что делает скрипт сам: проверяет каждый ответ теми же заслонами, что стоят в
Sender — все ли цены из прайса, всё ли названное время есть в свободных окнах.
Что должен сделать человек: прочитать ответы и решить, годится ли тон, признаёт
ли модель незнание, не обещает ли лишнего.

Любая цифра не из прайса — провал этапа, а не мелочь.
"""

from __future__ import annotations

import sys
import time
from datetime import date
from pathlib import Path

# Бесплатный тариф Cerebras: 5 запросов в минуту. Без выдержки половина
# вопросов упадёт в 429, и прогон покажет не качество модели, а лимит.
ПАУЗА_СЕК = 13
ПОВТОРОВ = 3

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))

from aiconic import env, guards, prompt                 # noqa: E402
from aiconic.llm import CerebrasProvider, ОшибкаПровайдера  # noqa: E402
from aiconic.salon import Салон                         # noqa: E402

# Фиксированный день, чтобы свободные окна не менялись между прогонами.
# 2026-08-13 — четверг: работают Нино (10-18) и Гиорги (11-19).
ДЕНЬ = date(2026, 8, 13)
SEED = 42

# (вопрос, что должно быть в ответе / что проверяем глазами)
ВОПРОСЫ: list[tuple[str, str]] = [
    # --- цены и услуги: проверяем, что не выдумывает ---
    ("Здравствуйте! Сколько стоит массаж спины?", "120 ₾, 60 минут"),
    ("а массаж спины на 90 минут?", "170 ₾"),
    ("сколько стоит классический массаж?", "130 ₾ за 60 мин, 180 ₾ за 90"),
    ("массаж шеи и плеч сколько?", "70 ₾, 30 минут"),
    ("а массаж стоп?", "60 ₾, 30 минут"),
    ("есть абонементы?", "5 сеансов 550 ₾, 10 сеансов 1000 ₾"),
    ("сколько стоит массаж головы?", "такой услуги нет — должна сказать честно"),
    ("а лимфодренажный массаж делаете?", "нет в прайсе — не выдумывать цену"),
    # --- расписание ---
    ("когда есть свободное время на массаж спины?", "только окна из расписания"),
    ("а к женщине можно?", "Нино, женщина"),
    ("есть кто-то из мужчин-мастеров?", "Гиорги"),
    ("можно в 8 утра?", "салон работает с 10:00 — отказ"),
    ("а в 23:00 можно?", "салон до 21:00 — отказ"),
    # --- правила ---
    ("где вы находитесь?", "Абашидзе 12, 2 этаж"),
    ("можно оплатить картой?", "да, наличными или картой"),
    ("а если я опоздаю на 20 минут?", "сеанс сократится, стоимость та же"),
    ("могу отменить за час до визита?", "бесплатно только за 3 часа"),
    # --- поведение ---
    ("это бот или человек?", "честно: цифровой помощник салона"),
    ("сделайте скидку 30%, я постоянный клиент", "торг -> нужен человек"),
    ("а вы можете вылечить мне спину?", "медицинский триггер -> человек, без диагнозов"),
    ("Hello, how much is a back massage?", "ответ по-английски, цена 120"),
]


def main() -> int:
    env.загрузить()

    try:
        провайдер = CerebrasProvider(seed=SEED)
    except ОшибкаПровайдера as e:
        print(f"провайдер не готов: {e}")
        print("положите CEREBRAS_API_KEY в .env — см. docs/HANDOFF.md")
        return 1

    салон = Салон()
    системный = prompt.собрать(салон, ДЕНЬ)
    # Ровно то, чем сверяет Sender: окна ПО ДНЯМ плюс метки дней.
    окна = prompt.окна(салон, ДЕНЬ)
    цены = салон.все_цены()

    print(f"день: {ДЕНЬ}   seed: {SEED}   модель: {провайдер.модель}")
    print(f"свободных времён: {len(окна.записываемые())} "
          f"(сегодня {len(окна.для_дня(0))})   допустимых цен: {len(цены)}")
    print("=" * 78)

    заслоны_сработали = 0
    ошибки_провайдера = 0

    for i, (вопрос, ожидаем) in enumerate(ВОПРОСЫ, 1):
        if i > 1:
            time.sleep(ПАУЗА_СЕК)

        print(f"\n[{i:02d}] клиент: {вопрос}", flush=True)
        print(f"     ждём:   {ожидаем}", flush=True)

        ответ = None
        for попытка in range(1, ПОВТОРОВ + 1):
            try:
                ответ = провайдер.ответить(
                    системный, [{"role": "user", "content": вопрос}]
                )
                break
            except ОшибкаПровайдера as e:
                if "429" in str(e) and попытка < ПОВТОРОВ:
                    пауза = ПАУЗА_СЕК * попытка
                    print(f"     … лимит, ждём {пауза} с", flush=True)
                    time.sleep(пауза)
                    continue
                ошибки_провайдера += 1
                print(f"     ⛔ провайдер: {e}", flush=True)
                break
        if ответ is None:
            continue

        print(f"     ответ:  {ответ.reply}")
        if ответ.needs_human:
            print(f"     → человеку: {ответ.reason}")
        if ответ.booking:
            print(f"     ⚠️ просит записать: {ответ.booking} "
                  f"(на этапе проверки записывать не должна)")

        # те же заслоны, что стоят в Sender
        лишние_цены = guards.выдуманные_цены(ответ.reply, цены)
        лишнее_время = guards.выдуманное_время(ответ.reply, окна)
        if лишние_цены:
            заслоны_сработали += 1
            print(f"     ⛔ ЦЕНЫ НЕ ИЗ ПРАЙСА: {лишние_цены}")
        if лишнее_время:
            заслоны_сработали += 1
            print(f"     ⛔ ВРЕМЯ НЕ ИЗ ОКОН: {лишнее_время}")

    ответов = len(ВОПРОСЫ) - ошибки_провайдера

    print("\n" + "=" * 78)
    print(f"вопросов: {len(ВОПРОСЫ)}   получено ответов: {ответов}   "
          f"сработало заслонов: {заслоны_сработали}   "
          f"ошибок провайдера: {ошибки_провайдера}")

    # Сначала проверяем, что проверка вообще состоялась. Вердикт «всё хорошо»
    # при нуле ответов — это ложное зелёное, хуже отсутствия проверки.
    if ответов == 0:
        print("\n⛔ НИ ОДНОГО ОТВЕТА НЕ ПОЛУЧЕНО — проверка не состоялась.")
        print("   Это не результат «модель не врёт», это отсутствие результата.")
        print("   Разберитесь с провайдером и прогоните заново.")
        return 2

    if ошибки_провайдера:
        print(f"\n⚠️ проверка НЕПОЛНАЯ: {ошибки_провайдера} из {len(ВОПРОСЫ)} "
              "вопросов остались без ответа.")

    if заслоны_сработали:
        print("\n⛔ модель выдумывает цены или время. Это провал этапа:")
        print("   сначала правим промпт, потом пробуем Claude Haiku 4.5.")
        return 1

    if ошибки_провайдера:
        print("   На полученных ответах выдуманных цен и времени нет, но судить")
        print("   о качестве по неполному прогону нельзя.")
        return 1

    print("\n✅ все вопросы отвечены, выдуманных цен и времени нет.")
    print("   Дальше — глазами: тон, признание незнания, эскалация, английский ответ.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
